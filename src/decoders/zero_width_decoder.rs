    #[test]
    fn checks_the_readings_in_order() {
        // The issue scheme also fits zwsp-steg's MODE_FULL alphabet, and 98 characters
        // make 14 groups of 7. That reading is valid UTF-16 but not plaintext, so the
        // checker rejects it and accepts the issue scheme's reading after it.
        let readings = readings(HELLO_WORLD);
        assert_eq!(readings.len(), 2, "{readings:?}");
        assert_eq!(readings[0].0, "zwsp-steg full");
        assert_eq!(
            readings[1],
            (
                "separator U+200D, U+200B=0".to_string(),
                "hello world".to_string()
            )
        );
    }

    #[test]
    fn rejects_control_characters() {
        // 330k's text mode read as its binary mode: a NUL before every ASCII letter
        let all = candidates(&extract(&zw(TEXT_330K)));
        let binary = all
            .iter()
            .find(|reading| reading.key == "330k binary")
            .expect("the 330k binary reading");
        assert!(binary.text.starts_with("\0a\0t"), "{:?}", binary.text);
        assert_eq!(
            readings(TEXT_330K),
            [("330k text".to_string(), "attack at dawn".to_string())]
        );
    }

    #[test]
    fn rejects_invalid_utf16_and_utf8() {
        // A lone high surrogate (U+D800) then `a` in 330k's text mode. Read as 330k's
        // binary mode it is D8 00 00 61, which isn't UTF-8 either.
        assert_eq!(crack(&zw("x[ZDPCCCCCCCCCDPCD]y")), None);
        // C3 starts a two-byte character, and `a` can't end it
        assert_eq!(crack(&issue_scheme(&[0xC3, b'a'], ZWSP, ZWNJ, ZWJ)), None);
    }

    #[test]
    fn unwraps_only_a_character_that_appears_twice() {
        let hidden = extract(&zw(STEGANOGRAPHR));
        assert_eq!(unwrap(&hidden), Some(&hidden[1..hidden.len() - 1]));
        // U+FEFF three times: no wrapper
        let three = extract(&zw("[ZCCBBBBCWZCCCBCBBZ]"));
        assert_eq!(unwrap(&three), None);
        // Too short to be a wrapped message
        let short = extract(&zw("[ZCCBBBBCZ]"));
        assert_eq!(unwrap(&short), None);
    }

