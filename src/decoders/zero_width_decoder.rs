    const MISS: &str =
        "T00 l3= ox+#G WKyV pajU6j qxH@ %B4+a 5Pn^ 7p_v1q 9sLvu *+36i R5rL&3 mVJZI iO0 Ut8_m COTV";

    /// The text of the bench `medium` input
    const MEDIUM_PLAINTEXT: &str =
        "Meet me at the old lighthouse after midnight and bring the map, the key and a torch.";

    /// U+200B ZERO WIDTH SPACE, 0 in the issue scheme
    const ZWSP: char = '\u{200B}';
    /// U+200C ZERO WIDTH NON-JOINER, 1 in the issue scheme
    const ZWNJ: char = '\u{200C}';
    /// U+200D ZERO WIDTH JOINER, between the bytes in the issue scheme
    const ZWJ: char = '\u{200D}';

    /// Copies `text`, writing each letter between `[` and `]` as its zero-width character
    fn zw(text: &str) -> String {
        let mut inside = false;
        text.chars()
            .filter_map(|c| match c {
                '[' => {
                    inside = true;
                    None
                }
                ']' => {
                    inside = false;
                    None
                }
                _ if !inside => Some(c),
                'B' => Some('\u{200B}'),
                'C' => Some('\u{200C}'),
                'D' => Some('\u{200D}'),
                'E' => Some('\u{200E}'),
                'F' => Some('\u{200F}'),
                'P' => Some('\u{202C}'),
                'W' => Some('\u{2060}'),
                'Z' => Some('\u{FEFF}'),
                _ => panic!("{c:?} isn't a zero-width letter"),
            })
            .collect()
    }

    /// `bytes` in the issue scheme: the 8 bits of each byte with `zero` for 0 and `one`
    /// for 1, and `separator` between the bytes
    fn issue_scheme(bytes: &[u8], zero: char, one: char, separator: char) -> String {
        bytes
            .iter()
            .map(|byte| {
                format!("{byte:08b}")
                    .chars()
                    .map(|bit| if bit == '0' { zero } else { one })
                    .collect::<String>()
            })
            .collect::<Vec<_>>()
            .join(&separator.to_string())
    }

    /// `text` in the issue scheme, as the issue made its example
    fn issue(text: &str) -> String {
        issue_scheme(text.as_bytes(), ZWSP, ZWNJ, ZWJ)
    }

    /// The Athena checker, as the search uses it
    fn get_athena_checker() -> CheckerTypes {
        let athena_checker = Checker::<Athena>::new();
        CheckerTypes::CheckAthena(athena_checker)
    }

    /// Runs the decoder with the Athena checker
    fn crack_result(text: &str) -> CrackResult {
        Decoder::<ZeroWidthDecoder>::new().crack(text, &get_athena_checker())
    }

    /// Runs the decoder on `text` and returns what it hands on, checking that a failure
    /// isn't marked successful
    fn crack(text: &str) -> Option<Vec<String>> {
        let result = crack_result(text);
        if result.unencrypted_text.is_none() {
            assert!(!result.success, "{text:?} failed but was marked successful");
            assert!(result.key.is_none(), "{text:?} failed but has a key");
        }
        result.unencrypted_text
    }

    /// Asserts that Athena accepts `plaintext`, hidden in `text` (in `zw` notation) with
    /// the scheme `key`, and that it comes back alone
    #[track_caller]
    fn assert_identified(text: &str, plaintext: &str, key: &str) {
        let result = crack_result(&zw(text));
        assert!(
            result.success,
            "Athena should accept {plaintext:?}: {result:?}"
        );
        assert_eq!(result.unencrypted_text, Some(vec![plaintext.to_string()]));
        assert_eq!(result.key.as_deref(), Some(key));
    }

    /// The readings of `text` (in `zw` notation) that survive the filter
    fn readings(text: &str) -> Vec<(String, String)> {
        hidden_messages(&zw(text))
            .into_iter()
            .map(|Reading { key, text }| (key, text))
            .collect()
    }

