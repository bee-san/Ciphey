/// The Zero-width decoder, call:
/// `let zero_width_decoder = Decoder::<ZeroWidthDecoder>::new()` to create a new instance
/// And then call:
/// `result = zero_width_decoder.crack(input)` to read the message hidden in a text
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::zero_width_decoder::ZeroWidthDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_zero_width = Decoder::<ZeroWidthDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // The bits of "hi", U+200B for 0 and U+200C for 1, with U+200D between the bytes
/// let text = "Nothing\u{200b}\u{200c}\u{200c}\u{200b}\u{200c}\u{200b}\u{200b}\u{200b}\
///             \u{200d}\u{200b}\u{200c}\u{200c}\u{200b}\u{200c}\u{200b}\u{200b}\u{200c} to see here";
/// let result = decode_zero_width.crack(text, &checker).unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "hi");
/// ```
pub struct ZeroWidthDecoder;

/// Texts with fewer zero-width characters than this hide nothing. Eight are one byte in
/// plain binary and two in 330k's binary mode, and a stray byte order mark or the joiners
/// of a few emoji are not a message.
const MIN_HIDDEN: usize = 8;

/// Texts with more distinct zero-width characters than this hide nothing. zero-width-lib
/// uses the most: five digits and a separator.
const MAX_SYMBOLS: usize = 6;

/// 330k's characters for the digits 0 to 3 (its default `setUseChars`)
const DIGITS_330K: [char; 4] = ['\u{200C}', '\u{200D}', '\u{202C}', '\u{FEFF}'];

/// zwsp-steg's characters for the digits 0 to 4 in `MODE_FULL`. `MODE_ZWSP` uses the
/// first three for 0 to 2.
const DIGITS_ZWSP_STEG: [char; 5] = ['\u{200B}', '\u{200C}', '\u{200D}', '\u{200E}', '\u{200F}'];

/// zero-width-lib's characters for the digits 0 to 4
const DIGITS_ZERO_WIDTH_LIB: [char; 5] =
    ['\u{200E}', '\u{200F}', '\u{200C}', '\u{200D}', '\u{FEFF}'];

/// What zero-width-lib puts between the digits of two code points
const ZERO_WIDTH_LIB_SEPARATOR: char = '\u{200B}';

/// zero-width-lib writes code points in base 5 without leading zeros, and U+10FFFF takes
/// 9 digits.
const MAX_ZERO_WIDTH_LIB_DIGITS: usize = 9;

/// One way of reading the hidden characters: the scheme, which becomes the key, and the
/// text it gives.
#[derive(Debug, PartialEq, Eq)]
struct Reading {
    /// The scheme, such as `330k text` or `separator U+200D, U+200B=0`
    key: String,
    /// The hidden message as the scheme reads it
    text: String,
}

impl Crack for Decoder<ZeroWidthDecoder> {
    fn new() -> Decoder<ZeroWidthDecoder> {
        Decoder {
            name: "Zero-width",
            description: "Zero-width character steganography: a message hidden as invisible Unicode characters (U+200B–U+200F, U+2060–U+2064, U+202C, U+FEFF) inside a cover text, in the issue/Steganographr binary schemes, 330k's base-4 scheme, zwsp-steg's base-3/base-5 schemes or zero-width-lib's base-5 scheme.",
            link: "https://330k.github.io/misc_tools/unicode_steganography.html",
            tags: vec!["zero-width", "steganography", "unicode", "decoder", "program"],
            popularity: 0.5,
            phantom: std::marker::PhantomData,
        }
    }

    /// Reads the message hidden in `text` in every scheme that fits and checks the
    /// readings with `checker`, in the order of the table in the module docs. The first
    /// one the checker accepts is returned alone, with its scheme as the key. If it
    /// accepts none, all of them are returned for the search to decode further.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Zero-width with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let readings = hidden_messages(text);
        if readings.is_empty() {
            debug!("Failed to decode Zero-width because the text hides no message it can read");
            return results;
        }

        for reading in &readings {
            let checker_result = checker.check(&reading.text);
            if checker_result.is_identified {
                trace!(
                    "Found a hidden message with Zero-width scheme {}",
                    reading.key
                );
                results.unencrypted_text = Some(vec![reading.text.clone()]);
                results.key = Some(reading.key.clone());
                results.update_checker(&checker_result);
                return results;
            }
        }

        // A key per reading only works for one reading: the library splits a key on ", "
        // to give each candidate its own, and the separator schemes' keys contain ", "
        if let [reading] = readings.as_slice() {
            results.key = Some(reading.key.clone());
        }
        results.unencrypted_text = Some(readings.into_iter().map(|reading| reading.text).collect());
        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// The messages hidden in `text`, one per scheme that reads it as text without control
/// characters, in the order of the table in the module docs and without repeats.
fn hidden_messages(text: &str) -> Vec<Reading> {
    // Every zero-width character is outside ASCII. This one check is the whole miss path
    // for almost every text the search sees.
    if text.is_ascii() {
        return Vec::new();
    }
    let hidden = extract(text);
    if hidden.len() < MIN_HIDDEN {
        return Vec::new();
    }
    // One symbol is what Persian text (U+200C) and emoji sequences (U+200D) are full of
    if !(2..=MAX_SYMBOLS).contains(&symbols(&hidden).len()) {
        return Vec::new();
    }

    let mut readings = Vec::new();
    if let Some(inner) = unwrap(&hidden) {
        readings.extend(candidates(inner));
    }
    readings.extend(candidates(&hidden));

    let mut seen = HashSet::new();
    readings.retain(|reading| {
        check_string_success(&reading.text, text)
            && is_printable(&reading.text)
            && seen.insert(reading.text.clone())
    });
    readings
}

/// Whether `c` is one of the zero-width characters the schemes use.
fn is_zero_width(c: char) -> bool {
    matches!(
        c,
        '\u{200B}'..='\u{200F}' | '\u{202A}'..='\u{202E}' | '\u{2060}'..='\u{2064}' | '\u{FEFF}'
    )
}

/// The zero-width characters of `text`, in order, without the visible text around them.
fn extract(text: &str) -> Vec<char> {
    text.chars().filter(|&c| is_zero_width(c)).collect()
}

/// The distinct characters of `hidden` in the order they first appear, stopping after
/// one more than `MAX_SYMBOLS`.
fn symbols(hidden: &[char]) -> Vec<char> {
    let mut symbols = Vec::new();
    for &c in hidden {
        if !symbols.contains(&c) {
            symbols.push(c);
            if symbols.len() > MAX_SYMBOLS {
                break;
            }
        }
    }
    symbols
}

/// `hidden` without its first and last character if they are the same character and it
/// appears nowhere else, as Steganographr's U+FEFF does around its message. The message
/// is read both with and without them.
fn unwrap(hidden: &[char]) -> Option<&[char]> {
    let (&first, rest) = hidden.split_first()?;
    let (&last, inner) = rest.split_last()?;
    if hidden.len() >= 10 && first == last && !inner.contains(&first) {
        Some(inner)
    } else {
        None
    }
}

/// Every reading of `hidden` (only zero-width characters) whose scheme fits it and that
/// is valid UTF-8 or UTF-16, in the order of the table in the module docs. The readings
/// still have to be checked for control characters.
fn candidates(hidden: &[char]) -> Vec<Reading> {
    let mut readings = Vec::new();
    let mut add = |key: String, text: Option<String>| {
        if let Some(text) = text {
            readings.push(Reading { key, text });
        }
    };

    if let Some(digits) = digits(hidden, &DIGITS_330K) {
        add("330k text".to_string(), utf16_units(&digits, 4, 8));
        add("330k binary".to_string(), utf8_bytes(&digits, 4, 4));
    }
    if let Some(digits) = digits(hidden, &DIGITS_ZWSP_STEG) {
        add("zwsp-steg full".to_string(), utf16_units(&digits, 5, 7));
        if digits.iter().all(|&digit| digit < 3) {
            add("zwsp-steg zwsp".to_string(), utf16_units(&digits, 3, 11));
        }
    }
    add("zero-width-lib".to_string(), zero_width_lib(hidden));

    match *symbols(hidden).as_slice() {
        [first, second] => {
            for (zero, one) in [(first, second), (second, first)] {
                add(
                    format!("binary {}=0", code_point(zero)),
                    binary(hidden, zero, one),
                );
            }
        }
        [first, second, third] => {
            for (separator, a, b) in [
                (first, second, third),
                (second, first, third),
                (third, first, second),
            ] {
                for (zero, one) in [(a, b), (b, a)] {
                    add(
                        format!(
                            "separator {}, {}=0",
                            code_point(separator),
                            code_point(zero)
                        ),
                        separated_binary(hidden, separator, zero, one),
                    );
                }
            }
        }
        _ => {}
    }
    readings
}

/// The digit each character of `hidden` stands for in `alphabet`, or `None` if one of
/// them isn't in it.
fn digits(hidden: &[char], alphabet: &[char]) -> Option<Vec<u32>> {
    hidden
        .iter()
        .map(|c| {
            alphabet
                .iter()
                .position(|digit| digit == c)
                .map(|digit| digit as u32)
        })
        .collect()
}

/// `digits` read as a number in `base`, most significant digit first. The callers' groups
/// are at most 11 digits in base 3 or 9 in base 5, far below `u32::MAX`.
fn number(digits: &[u32], base: u32) -> u32 {
    digits
        .iter()
        .fold(0, |number, &digit| number * base + digit)
}

/// The text whose UTF-16 code units are `digits` in groups of `width` digits in `base`,
/// or `None` if the digits don't divide into groups, a group is over U+FFFF or a
/// surrogate is unpaired.
fn utf16_units(digits: &[u32], base: u32, width: usize) -> Option<String> {
    if digits.is_empty() || !digits.len().is_multiple_of(width) {
        return None;
    }
    let units = digits
        .chunks(width)
        .map(|group| u16::try_from(number(group, base)).ok())
        .collect::<Option<Vec<u16>>>()?;
    String::from_utf16(&units).ok()
}

/// The text whose UTF-8 bytes are `digits` in groups of `width` digits in `base`, or
/// `None` if the digits don't divide into groups or the bytes aren't UTF-8.
fn utf8_bytes(digits: &[u32], base: u32, width: usize) -> Option<String> {
    if digits.is_empty() || !digits.len().is_multiple_of(width) {
        return None;
    }
    let bytes = digits
        .chunks(width)
        .map(|group| u8::try_from(number(group, base)).ok())
        .collect::<Option<Vec<u8>>>()?;
    String::from_utf8(bytes).ok()
}

/// zero-width-lib's reading of `hidden`: code points in base 5, separated by U+200B.
fn zero_width_lib(hidden: &[char]) -> Option<String> {
    if !hidden.contains(&ZERO_WIDTH_LIB_SEPARATOR) {
        return None;
    }
    hidden
        .split(|&c| c == ZERO_WIDTH_LIB_SEPARATOR)
        .map(|group| {
            if group.is_empty() || group.len() > MAX_ZERO_WIDTH_LIB_DIGITS {
                return None;
            }
            char::from_u32(number(&digits(group, &DIGITS_ZERO_WIDTH_LIB)?, 5))
        })
        .collect()
}

/// `hidden` read as UTF-8 bytes of 8 bits each, `zero` for 0 and `one` for 1.
fn binary(hidden: &[char], zero: char, one: char) -> Option<String> {
    if !hidden.len().is_multiple_of(8) {
        return None;
    }
    let bytes = hidden
        .chunks(8)
        .map(|bits| byte(bits, zero, one))
        .collect::<Option<Vec<u8>>>()?;
    String::from_utf8(bytes).ok()
}

/// `hidden` read as UTF-8 bytes with `separator` between them, `zero` for 0 and `one`
/// for 1. A byte has 1 to 8 bits, so leading zeros may be left out as Steganographr does.
/// A separator before the first byte or after the last is ignored.
fn separated_binary(hidden: &[char], separator: char, zero: char, one: char) -> Option<String> {
    let hidden = hidden.strip_prefix(&[separator]).unwrap_or(hidden);
    let hidden = hidden.strip_suffix(&[separator]).unwrap_or(hidden);
    let bytes = hidden
        .split(|&c| c == separator)
        .map(|bits| {
            if bits.is_empty() || bits.len() > 8 {
                return None;
            }
            byte(bits, zero, one)
        })
        .collect::<Option<Vec<u8>>>()?;
    // One byte can't be told from chance
    if bytes.len() < 2 {
        return None;
    }
    String::from_utf8(bytes).ok()
}

/// The byte whose bits are `bits`, most significant first, or `None` if one of them is
/// neither `zero` nor `one`. There are at most 8 bits.
fn byte(bits: &[char], zero: char, one: char) -> Option<u8> {
    bits.iter().try_fold(0u8, |byte, &bit| match bit {
        _ if bit == zero => Some(byte << 1),
        _ if bit == one => Some((byte << 1) | 1),
        _ => None,
    })
}

/// `c` as `U+XXXX`
fn code_point(c: char) -> String {
    format!("U+{:04X}", u32::from(c))
}

/// Whether `text` has no control characters other than tabs and line breaks and no
/// U+FFFD. Reading a scheme's digits in the wrong grouping gives control characters
/// (330k's text mode read as its binary mode has a NUL before every ASCII letter).
fn is_printable(text: &str) -> bool {
    text.chars()
        .all(|c| c != '\u{FFFD}' && (!c.is_control() || matches!(c, '\t' | '\n' | '\r')))
}

