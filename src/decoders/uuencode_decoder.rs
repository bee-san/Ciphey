//! Decode Uuencode (Unix-to-Unix encoding): every 3 bytes become 4 characters, each 6-bit
//! value `v` written as the character `32 + v` (space to `_`), with the backtick also
//! meaning 0 because many encoders avoid the space. Every line starts with a length
//! character, `32 + n` for the `n` bytes it holds (`!` to `M`, 1 to 45). A file is usually
//! wrapped in a `begin <mode> <name>` header and an `end` line, with a zero-length line (a
//! backtick or a space) before `end`. `+:&5L;&\@=V]R;&0` is `hello world`.
//! Call uuencode_decoder.crack to use. It returns a `CrackResult` whose `unencrypted_text` is
//! `None` when the input isn't uuencoded text.
//!
//! The framing is optional: data lines on their own decode too. Python's `uu` module and
//! `binascii.b2a_uu` write a space for 0 unless asked for backticks, so a line often ends
//! in spaces, and those get lost when the text is copied around. Like `binascii.a2b_uu`,
//! this decoder reads missing characters at the end of a line as zeros.
//!
//! References: <https://en.wikipedia.org/wiki/Uuencoding>,
//! <https://docs.python.org/3/library/binascii.html#binascii.a2b_uu>,
//! <https://man.freebsd.org/cgi/man.cgi?query=uuencode&sektion=5>.

