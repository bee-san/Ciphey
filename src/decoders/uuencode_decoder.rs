/// The Uuencode decoder, call:
/// `let uuencode_decoder = Decoder::<UuencodeDecoder>::new()` to create a new instance
/// And then call:
/// `result = uuencode_decoder.crack(input)` to decode uuencoded text
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::uuencode_decoder::UuencodeDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_uuencode = Decoder::<UuencodeDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // What `uuencode` writes for a file called hello.txt that holds "hello world"
/// let encoded = "begin 644 hello.txt\n+:&5L;&\\@=V]R;&0`\n`\nend\n";
/// let result = decode_uuencode.crack(encoded, &checker).unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "hello world");
/// ```
pub struct UuencodeDecoder;

/// Decoded texts shorter than this are rejected. One or two bytes are too short to
/// identify, and one- and two-byte lines (`!` or `"` and two or three characters from a
/// 65-character alphabet) are easily matched by text that isn't uuencode.
const MIN_DECODED_BYTES: usize = 3;

impl Crack for Decoder<UuencodeDecoder> {
    fn new() -> Decoder<UuencodeDecoder> {
        Decoder {
            name: "Uuencode",
            description: "Unix-to-Unix encoding: 3 bytes to 4 printable chars (value + 32, backtick for zero), each line prefixed with its byte count, optionally wrapped in `begin <mode> <name>` and `end`.",
            link: "https://en.wikipedia.org/wiki/Uuencoding",
            tags: vec!["uuencode", "uu", "decoder", "base"],
            popularity: 0.3,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` as Uuencode and checks the result with `checker`.
    /// `unencrypted_text` is `None` when `text` isn't uuencoded UTF-8 text.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Uuencode with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(decoded_text) = decode_uuencode(text) else {
            debug!("Failed to decode Uuencode because the text isn't uuencoded UTF-8 text");
            return results;
        };
        trace!("Decoded text for Uuencode: {:?}", decoded_text);

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Uuencode because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Decodes uuencoded text, or returns `None` if `text` isn't uuencoded UTF-8 text without
/// control characters (tabs and line breaks are allowed).
///
/// `text` is one or more data lines, optionally after a `begin <mode> <name>` header, and
/// optionally followed by `end`. Zero-length lines (empty, a space or a backtick) can be
/// anywhere, and only those can follow `end`.
fn decode_uuencode(text: &str) -> Option<String> {
    // Trimming loses nothing. A data line can't start with a space, which would be a
    // length of zero, and trailing spaces are zeros, which is what a missing character is
    // read as.
    let text = text.trim();
    let mut lines = text.split('\n');

    // Only a `begin` header or a length character (`!` to `M`) can come first. Most input
    // fails here, at byte 0: lower-case letters, `N` to `Z` (the bench `miss` string starts
    // with `T`), `[` to `_`, and anything that isn't ASCII.
    match *text.as_bytes().first()? {
        b'b' => {
            if !is_begin_line(trim_line(lines.next()?)) {
                return None;
            }
        }
        b'!'..=b'M' => {}
        _ => return None,
    }

    let mut decoded = Vec::with_capacity(text.len() / 4 * 3);
    let mut seen_end = false;
    for line in lines {
        let line = trim_line(line);
        match line {
            // Zero-length lines, like the one before `end`
            b"" | b"`" => {}
            _ if seen_end => return None,
            b"end" => seen_end = true,
            _ => decode_line(line, &mut decoded)?,
        }
    }

    // Also rejects framing without any data lines, like `begin 644 x` and `end` on their own
    if decoded.len() < MIN_DECODED_BYTES {
        return None;
    }
    // Strict UTF-8, like Base64: a uuencoded binary file isn't plaintext
    let decoded = String::from_utf8(decoded).ok()?;
    // This rejects most text that only looks like uuencode, such as upper-case hex, Morse
    // code and A1Z26: their length characters promise more bytes than their lines hold, and
    // the missing characters decode to NULs.
    if decoded
        .chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\n' | '\r'))
    {
        return None;
    }
    Some(decoded)
}

/// `line` without the `\r` of a CRLF line break and without trailing spaces. Spaces are
/// zeros, and so are missing characters, so dropping them doesn't change the line's bytes.
fn trim_line(line: &str) -> &[u8] {
    let line = line.strip_suffix('\r').unwrap_or(line);
    line.trim_end_matches(' ').as_bytes()
}

/// Whether `line` is a `begin <mode> <name>` header: `begin`, a space, the file mode as 3
/// or 4 octal digits, a space and the file name. `begin-base64` is Base64, as written by
/// `uuencode -m`, so it isn't one.
fn is_begin_line(line: &[u8]) -> bool {
    let Some(rest) = line.strip_prefix(b"begin ") else {
        return false;
    };
    let mode_digits = rest
        .iter()
        .take_while(|&&byte| (b'0'..=b'7').contains(&byte))
        .count();
    (3..=4).contains(&mode_digits)
        && rest.get(mode_digits) == Some(&b' ')
        && rest.len() > mode_digits + 1
}

/// Decodes a data line, its length character and then up to 60 characters, onto the end
/// of `out`. Returns `None` if `line` isn't a data line.
fn decode_line(line: &[u8], out: &mut Vec<u8>) -> Option<()> {
    let (&length, symbols) = line.split_first()?;
    // `!` to `M`: 1 to 45 bytes, the most a line holds
    if !(b'!'..=b'M').contains(&length) {
        return None;
    }
    let length = usize::from(length - b' ');
    // Every 3 bytes take 4 characters. Fewer is fine (zeros at the end were lost), more
    // isn't.
    if symbols.len() > length.div_ceil(3) * 4 {
        return None;
    }

    let start = out.len();
    for group in symbols.chunks(4) {
        let mut values = [0u8; 4];
        for (value, &symbol) in values.iter_mut().zip(group) {
            // Space to backtick. The backtick is 64, which is 0 in six bits.
            if !(b' '..=b'`').contains(&symbol) {
                return None;
            }
            *value = (symbol - b' ') & 0x3F;
        }
        let [a, b, c, d] = values;
        out.extend_from_slice(&[(a << 2) | (b >> 4), (b << 4) | (c >> 2), (c << 6) | d]);
    }
    // Drops the padding of the last group, or adds the zeros whose characters were lost
    out.resize(start + length, 0);
    Some(())
}

