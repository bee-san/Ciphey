use log::{debug, info, trace};
use num::BigUint;

/// The Base36 decoder, call:
/// `let base36_decoder = Decoder::<Base36Decoder>::new()` to create a new instance
/// And then call:
/// `result = base36_decoder.crack(input)` to decode a Base36 string
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::base36_decoder::Base36Decoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_base36 = Decoder::<Base36Decoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// let result = decode_base36.crack("fuvrsivvnfrbjwajo", &checker).unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "hello world");
/// ```
pub struct Base36Decoder;

/// Inputs with fewer digits than this, not counting leading zeros, are rejected. Eight
/// digits are at least 36^7 ≈ 2^36, so at least 5 bytes: `hello` is `5pzcszu7`. Shorter
/// texts are too short to identify, and too much else decodes to printable UTF-8: 6.2 % of
/// random 6-digit strings, against 0.7 % of 8-digit ones and 0.9 % of English words of eight
/// or more letters.
const MIN_DIGITS: usize = 8;

/// Inputs longer than this are rejected. 1300 digits decode to at most 841 bytes, and the
/// search drops results and candidates of 821 to 5000 bytes anyway (see
/// `calculate_string_quality`). The cap bounds the big-integer work on every long
/// single-case alphanumeric string the search produces.
const MAX_LEN: usize = 1300;

impl Crack for Decoder<Base36Decoder> {
    fn new() -> Decoder<Base36Decoder> {
        Decoder {
            name: "Base36",
            description: "Base36 writes the bytes of the text as one big-endian integer in radix 36 using the digits 0-9 and letters a-z (case-insensitive). Used for short IDs and in CTFs; dCode's word-by-word 'Base 36 cipher' is not this mode.",
            link: "https://en.wikipedia.org/wiki/Base36",
            tags: vec!["base36", "decoder", "base"],
            popularity: 0.3,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` as Base36 and checks the result with `checker`.
    /// `unencrypted_text` is `None` when `text` isn't Base36 of UTF-8 text.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Base36 with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(decoded_text) = decode_base36(text) else {
            debug!("Failed to decode Base36 because the text isn't Base36 of UTF-8 text");
            return results;
        };
        trace!("Decoded text for Base36: {:?}", decoded_text);

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Base36 because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Decodes Base36 to text, or returns `None` if `text` isn't Base36 of UTF-8 text without
/// control characters (tabs and line breaks are allowed).
fn decode_base36(text: &str) -> Option<String> {
    let digits = text.trim().as_bytes();
    if digits.len() > MAX_LEN {
        return None;
    }

    // A single scan that rejects almost every input before anything is allocated. It stops
    // at the first byte that isn't an ASCII letter or digit (spaces, `=`, `+`, `/`, `-`, `_`,
    // non-ASCII), and at the first letter in the other case: mixed case is Base58, Base62 or
    // Base64, not Base36.
    let mut has_lower = false;
    let mut has_upper = false;
    for &byte in digits {
        match byte {
            b'0'..=b'9' => {}
            b'a'..=b'z' if !has_upper => has_lower = true,
            b'A'..=b'Z' if !has_lower => has_upper = true,
            _ => return None,
        }
    }
    // Only digits (including empty input): decimal numbers belong to Decimal, A1Z26 and
    // dCode's "Base 36 cipher". This also means the number below is never zero.
    if !has_lower && !has_upper {
        return None;
    }
    let leading_zeros = digits.iter().take_while(|&&byte| byte == b'0').count();
    if digits.len() - leading_zeros < MIN_DIGITS {
        return None;
    }

    // `parse_bytes` alone isn't a validator: it also accepts a leading `+` and skips `_`.
    // The scan above has rejected both. It accepts either case.
    let number = BigUint::parse_bytes(digits, 36)?;
    let decoded = String::from_utf8(number.to_bytes_be()).ok()?;
    if decoded
        .chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\n' | '\r'))
    {
        return None;
    }
    Some(decoded)
}

