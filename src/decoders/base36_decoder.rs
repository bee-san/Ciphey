//! Decode Base36: the bytes of the text written as one big-endian unsigned integer in radix
//! 36, with the digits `0-9` and the letters `a-z` (`a` = 10 … `z` = 35). `fuvrsivvnfrbjwajo`
//! is `hello world`.
//! Call base36_decoder.crack to use. It returns a `CrackResult` whose `unencrypted_text` is
//! `None` when the input isn't Base36.
//!
//! This is what Python's `int(text, 36).to_bytes(...)`, PyPI `base36.loads` and CyberChef's
//! `From Base` (radix 36) → `To Base` (16) → `From Hex` do. Letters may be upper or lower case,
//! but not both in one input: encoders write a single case, and mixed-case alphanumerics are
//! Base58, Base62 or Base64. Input that is only digits is left to the decimal decoders.
//!
//! dCode's "Base 36 cipher" is a different encoding, which writes every word as a base-36
//! number in decimal (`HELLO` is `29234652`). It isn't decoded here.
//!
//! References: <https://en.wikipedia.org/wiki/Base36>,
//! <https://gchq.github.io/CyberChef/#recipe=From_Base(36)To_Base(16)From_Hex('Auto')>,
//! <https://pypi.org/project/base36/>.

use crate::checkers::CheckerTypes;
use crate::decoders::interface::check_string_success;

use super::crack_results::CrackResult;
