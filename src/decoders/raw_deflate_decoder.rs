    #[test]
    fn block_headers_are_checked_before_inflating() {
        let fox = bytes_of(FOX_HEX);
        assert!(starts_like_raw_deflate(&fox));
        let stored = bytes_of("012b00d4ff54686520717569636b2062726f776e20666f78206a756d7073206f76657220746865206c617a7920646f67");
        assert!(starts_like_raw_deflate(&stored));

        for (stream, why) in [
            (&b"\x07abcdef"[..], "BTYPE 3 is reserved"),
            (b"\x1f\x8b\x08\x00\x00\x00", "so gzip fails"),
            (
                b"\x01\x02\x00\xfc\xffab",
                "a stored block's NLEN has to be LEN's complement",
            ),
            (
                b"\x01\x03\x00\xfc\xffab",
                "a stored block can't be longer than the input",
            ),
            (
                b"\xf5\x00\x00\x00\x00\x00",
                "HLIT 30 is too many literal/length codes",
            ),
            (
                b"\x05\x1e\x00\x00\x00\x00",
                "HDIST 30 is too many distance codes",
            ),
            (
                b"\x78\x9c\x03\x00\x00\x00\x00\x01",
                "a zlib stream is the Zlib decoder's",
            ),
            (b"\x03\x00", "too short"),
        ] {
            assert!(!starts_like_raw_deflate(stream), "{why}");
        }
        // The largest counts are allowed, and LEN can be all that is left
        assert!(starts_like_raw_deflate(b"\xed\x1d\x00\x00\x00\x00"));
        assert!(starts_like_raw_deflate(b"\x01\x01\x00\xfe\xffa"));
        // A zlib header on something too short for a zlib stream doesn't count
        assert!(!super::has_zlib_header(b"\x78\x9c\x01\x00\xff\xff"));
    }

