/// Largest output we inflate, in bytes. Anything longer is treated as a failure (a zip
/// bomb, or text far too long to be the answer) instead of being truncated.
const MAX_OUTPUT: usize = 1 << 20;

/// Output the checker doesn't accept is only handed on for more decoding up to this many
/// bytes, as in the Gzip decoder: every decoder runs on every node of the search, so a few
/// hundred bytes of compressed data could otherwise make a megabyte node.
const MAX_CANDIDATE: usize = 16 * 1024;

/// Shorter byte strings aren't tried. Six bytes inflate to a few letters at most (the
/// stream for "abc" is 5 bytes, for "hello" 7), too few for the checkers to tell text from
/// noise, and short random byte strings are far more often a complete stream than long
/// ones.
const MIN_STREAM_LEN: usize = 6;

/// The fewest characters, not counting whitespace, the Base64 view reads: 6 bytes are 8
/// characters.
const MIN_BASE64_CHARS: usize = 8;

/// The fewest digits the hex view reads: 6 bytes are 12 digits.
const MIN_HEX_DIGITS: usize = 12;

/// The shortest zlib stream: a 2-byte header, an empty final block (2 bytes) and the
/// 4-byte Adler-32 checksum. Shorter input with a zlib header is no zlib stream.
const MIN_ZLIB_STREAM_LEN: usize = 8;

thread_local! {
    /// One inflater per thread, reset before each stream. Making a new one allocates and
    /// zeroes about 42 KiB (a 32 KiB window and the Huffman tables), which takes longer
    /// than rejecting most streams does, and this decoder runs on every node of the search
    /// that looks like Base64 or hex.
    static INFLATER: RefCell<Decompress> = RefCell::new(Decompress::new(false));
}

/// The Raw DEFLATE decoder, call:
/// `let raw_deflate_decoder = Decoder::<RawDeflateDecoder>::new()` to create a new instance
/// And then call:
/// `result = raw_deflate_decoder.crack(input)` to inflate a raw DEFLATE stream
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::raw_deflate_decoder::RawDeflateDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_raw_deflate = Decoder::<RawDeflateDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // Python: deflate = zlib.compressobj(9, zlib.DEFLATED, -15)
/// // base64.b64encode(deflate.compress(b"The quick brown fox jumps over the lazy dog") + deflate.flush())
/// let result = decode_raw_deflate
///     .crack("C8lIVSgszUzOVkgqyi/PU0jLr1DIKs0tKFbIL0stUigBSuckVlUqpOSnAwA=", &checker)
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "The quick brown fox jumps over the lazy dog");
/// ```
pub struct RawDeflateDecoder;

impl Crack for Decoder<RawDeflateDecoder> {
    fn new() -> Decoder<RawDeflateDecoder> {
        Decoder {
            name: "Raw DEFLATE",
            description: "Raw DEFLATE (RFC 1951) is zlib/gzip's compressed body without header or checksum, as produced by PHP gzdeflate, .NET DeflateStream and CyberChef Raw Deflate. Ciphey reads the bytes from Base64, hex or raw text and inflates them.",
            link: "https://datatracker.ietf.org/doc/html/rfc1951",
            tags: vec!["deflate", "compression", "decoder"],
            popularity: 0.4,
            phantom: std::marker::PhantomData,
        }
    }

    /// Inflates the raw DEFLATE stream in `text` and runs the checker on the output.
    /// The result has no text unless a view of `text` (Base64, hex or raw bytes) is
    /// exactly one complete stream that inflates to text, or to another compressed stream.
    /// Text the checker doesn't accept is only returned up to [`MAX_CANDIDATE`] bytes.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Raw DEFLATE with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        match first_output(text, checker) {
            Some(Output::Text(plaintext, checker_result)) => {
                results.unencrypted_text = Some(vec![plaintext]);
                results.update_checker(&checker_result);
            }
            // Compressed twice. The inner stream goes on one character per byte (Latin-1),
            // which the next decoder reads back as raw bytes. It is binary, so there is
            // nothing for the checker to look at.
            Some(Output::Compressed(inner)) => {
                debug!("Raw DEFLATE output is another compressed stream");
                results.unencrypted_text = Some(vec![inner]);
            }
            None => trace!("Raw DEFLATE: no view of the input is a usable stream"),
        }

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// What a stream inflated to, if it is worth handing on.
enum Output {
    /// Text, and what the checker made of it.
    Text(String, CheckResult),
    /// Another compressed stream, one Latin-1 character per byte.
    Compressed(String),
}

/// Tries the views of `text` in turn (Base64, hex, then the raw bytes as Latin-1 and as
/// UTF-8) and returns what the first stream worth handing on inflated to. A view that
/// doesn't hold one doesn't stop the next being tried: hex is in the Base64 alphabet too.
fn first_output(text: &str, checker: &CheckerTypes) -> Option<Output> {
    let trimmed = text.trim();
    let output = |stream: Vec<u8>| output_of(&stream, text, checker);
    base64_view(trimmed)
        .and_then(output)
        .or_else(|| hex_view(trimmed).and_then(output))
        .or_else(|| {
            // Raw bytes are not trimmed: the stream can end with bytes that look like
            // whitespace.
            if !looks_binary(text) {
                return None;
            }
            latin1_bytes(text).and_then(output).or_else(|| {
                // Hexadecimal and Binary return UTF-8 instead of Latin-1 when the bytes
                // happen to be UTF-8
                if text.is_ascii() {
                    return None;
                }
                output_of(text.as_bytes(), text, checker)
            })
        })
}

/// Inflates `stream` and returns its output if it is worth handing on: text, which has
/// to be at most [`MAX_CANDIDATE`] bytes unless the checker accepts it, or another
/// compressed stream of at most [`MAX_CANDIDATE`] bytes.
fn output_of(stream: &[u8], text: &str, checker: &CheckerTypes) -> Option<Output> {
    let inflated = raw_inflate_bounded(stream)?;
    let plaintext = match into_text(inflated) {
        Ok(plaintext) => plaintext,
        Err(binary) if is_compressed(&binary) && binary.len() <= MAX_CANDIDATE => {
            return Some(Output::Compressed(
                binary.into_iter().map(char::from).collect(),
            ));
        }
        Err(_) => {
            debug!("Raw DEFLATE output is binary, not text");
            return None;
        }
    };
    if !check_string_success(&plaintext, text) {
        debug!("Raw DEFLATE output is empty");
        return None;
    }

    // The checker runs after the inflater is given back: it can use the thread pool, and
    // a task stolen meanwhile could be this decoder again on the same thread.
    let checker_result = checker.check(&plaintext);
    if !checker_result.is_identified && plaintext.len() > MAX_CANDIDATE {
        debug!(
            "Raw DEFLATE output is not plaintext and too long ({} bytes) to decode further",
            plaintext.len()
        );
        return None;
    }
    Some(Output::Text(plaintext, checker_result))
}

/// Base64, standard or URL-safe, with or without padding and line breaks, decoded with
/// the Base64 decoder's engines. Nothing is allocated unless [`looks_like_base64`].
fn base64_view(text: &str) -> Option<Vec<u8>> {
    if !looks_like_base64(text) {
        return None;
    }
    let compact: String = text.chars().filter(|c| !c.is_ascii_whitespace()).collect();
    let unpadded = compact.trim_end_matches('=');
    let engine = if unpadded.contains(['-', '_']) {
        &general_purpose::URL_SAFE_NO_PAD
    } else {
        &general_purpose::STANDARD_NO_PAD
    };
    // Both engines reject a last character with bits left over, which most English
    // that fits the alphabet ("hello world") has.
    engine.decode(unpadded).ok()
}

/// Whether every character of `text` is a Base64 character (standard or URL-safe) or
/// whitespace, with at most two `=` and only at the end, and at least
/// [`MIN_BASE64_CHARS`] of them aren't whitespace. Stops at the first character that
/// doesn't fit.
fn looks_like_base64(text: &str) -> bool {
    let mut chars = 0;
    let mut padding = 0;
    for byte in text.bytes() {
        if byte.is_ascii_whitespace() {
            continue;
        }
        if byte == b'=' {
            padding += 1;
            if padding > 2 {
                return false;
            }
        } else if padding > 0
            || !(byte.is_ascii_alphanumeric() || matches!(byte, b'+' | b'/' | b'-' | b'_'))
        {
            return false;
        }
        chars += 1;
    }
    chars >= MIN_BASE64_CHARS
}

/// Hex of at least [`MIN_HEX_DIGITS`] digits, an even number of them. Whitespace, `:` and
/// `,` between them and `0x` / `\x` prefixes are skipped. Nothing is allocated unless
/// every character fits.
fn hex_view(text: &str) -> Option<Vec<u8>> {
    let count = hex_digits(text).try_fold(0, |count: usize, digit| digit.map(|_| count + 1))?;
    if count < MIN_HEX_DIGITS || count % 2 != 0 {
        return None;
    }
    let mut digits = hex_digits(text).flatten();
    Some(std::iter::from_fn(|| Some((digits.next()? << 4) | digits.next()?)).collect())
}

/// The values of the hex digits in `text`, skipping whitespace, `:`, `,` and `0x` / `\x`
/// prefixes. The first character that is none of those ends it, with a `None`.
fn hex_digits(text: &str) -> impl Iterator<Item = Option<u8>> + '_ {
    let mut rest = text.as_bytes();
    std::iter::from_fn(move || loop {
        let (&first, tail) = rest.split_first()?;
        if matches!(first, b'0' | b'\\') && matches!(tail.first(), Some(b'x' | b'X')) {
            rest = &tail[1..];
            continue;
        }
        rest = tail;
        if let Some(digit) = char::from(first).to_digit(16) {
            return Some(Some(digit as u8));
        }
        if !(first.is_ascii_whitespace() || matches!(first, b':' | b',')) {
            rest = &[];
            return Some(None);
        }
    })
}

/// Whether `text` contains a character that ordinary text doesn't but compressed bytes
/// almost always do: a control character other than tab and line breaks, or non-ASCII.
/// This keeps text away from the raw view.
fn looks_binary(text: &str) -> bool {
    text.bytes().any(|byte| {
        !byte.is_ascii() || (byte.is_ascii_control() && !matches!(byte, b'\t' | b'\n' | b'\r'))
    })
}

/// One byte per character, if every character is at most U+00FF (Latin-1).
fn latin1_bytes(text: &str) -> Option<Vec<u8>> {
    text.chars().map(|c| u8::try_from(c).ok()).collect()
}

/// Checks on the first block header that about half of all byte strings fail, so most of
/// what isn't raw DEFLATE is rejected without inflating it (RFC 1951 section 3.2.3 to
/// 3.2.7). Zlib streams fail too: they are the Zlib decoder's.
fn starts_like_raw_deflate(stream: &[u8]) -> bool {
    if stream.len() < MIN_STREAM_LEN || has_zlib_header(stream) {
        return false;
    }
    // The block header is the low three bits: BFINAL, then the two bits of BTYPE
    let header = stream[0];
    match (header >> 1) & 0b11 {
        // Stored: LEN, then NLEN, its one's complement, both little-endian from the next
        // byte on, then LEN bytes of data
        0 => {
            let len = u16::from_le_bytes([stream[1], stream[2]]);
            let nlen = u16::from_le_bytes([stream[3], stream[4]]);
            len ^ nlen == 0xFFFF && usize::from(len) <= stream.len() - 5
        }
        // Fixed Huffman codes: nothing else to check without inflating
        1 => true,
        // Dynamic Huffman codes: HLIT + 257 literal/length codes, at most 286, and
        // HDIST + 1 distance codes, at most 30
        2 => header >> 3 <= 29 && stream[1] & 0x1F <= 29,
        // 3 is reserved. Gzip's first byte, 1F, has it.
        _ => false,
    }
}

/// The RFC 1950 header check the Zlib decoder makes (section 2.2): compression method 8
/// (DEFLATE), a window of at most 32 KiB (CINFO <= 7), the two header bytes a multiple of
/// 31 as a big-endian number, no preset dictionary, and long enough to be a zlib stream.
fn has_zlib_header(stream: &[u8]) -> bool {
    let &[cmf, flg, ..] = stream else {
        return false;
    };
    stream.len() >= MIN_ZLIB_STREAM_LEN
        && cmf & 0x0F == 8
        && cmf >> 4 <= 7
        && u16::from_be_bytes([cmf, flg]) % 31 == 0
        && flg & 0x20 == 0
}

/// Inflates `stream` if it is exactly one complete raw DEFLATE stream: a first block that
/// passes [`starts_like_raw_deflate`], blocks that inflate without error to at most
/// [`MAX_OUTPUT`] bytes, a final block, and nothing after it.
///
/// This is flate2's low-level API: its readers can't tell a stream whose final block has
/// been read from one that was cut short, which they return as if it were complete.
fn raw_inflate_bounded(stream: &[u8]) -> Option<Vec<u8>> {
    if !starts_like_raw_deflate(stream) {
        return None;
    }
    INFLATER.with_borrow_mut(|inflater| {
        inflater.reset(false);
        let mut output = Vec::with_capacity((4 * stream.len()).clamp(64, MAX_OUTPUT + 1));
        loop {
            let (read, written) = (inflater.total_in(), output.len());
            // total_in counts from the reset, so it is where the unread input starts
            let unread = &stream[read as usize..];
            match inflater
                .decompress_vec(unread, &mut output, FlushDecompress::None)
                .ok()?
            {
                Status::StreamEnd => break,
                Status::Ok | Status::BufError if output.len() == output.capacity() => {
                    // Out of room. Growing to one byte over the cap tells an output of
                    // exactly MAX_OUTPUT bytes from a longer one.
                    if output.len() > MAX_OUTPUT {
                        debug!("Raw DEFLATE output is over {MAX_OUTPUT} bytes");
                        return None;
                    }
                    let room = (2 * output.capacity()).min(MAX_OUTPUT + 1) - output.len();
                    output.reserve_exact(room);
                }
                // Room to spare and no progress: the input ended before a final block did,
                // because it was cut short or only flushed (Z_SYNC_FLUSH)
                Status::Ok | Status::BufError
                    if inflater.total_in() == read && output.len() == written =>
                {
                    return None;
                }
                Status::Ok | Status::BufError => {}
            }
        }
        // The inflater stops at the end of the final block without looking at what
        // follows it, so check that the stream used up the whole input.
        (inflater.total_in() == stream.len() as u64 && output.len() <= MAX_OUTPUT).then_some(output)
    })
}

/// `bytes` as text, if they are UTF-8 without control characters other than tab and line
/// breaks. Otherwise the bytes, given back.
fn into_text(bytes: Vec<u8>) -> Result<String, Vec<u8>> {
    let text = String::from_utf8(bytes).map_err(|error| error.into_bytes())?;
    if text
        .chars()
        .all(|c| !c.is_control() || matches!(c, '\t' | '\n' | '\r'))
    {
        Ok(text)
    } else {
        Err(text.into_bytes())
    }
}

/// Whether binary output is itself compressed, so worth handing on: a zlib stream starting
/// with `78` (the only first byte the Zlib decoder's raw view reads), a gzip member
/// (`1F 8B 08`), bzip2 (`BZh`) or XZ (`FD 37 7A 58 5A 00`). Raw DEFLATE inside raw
/// DEFLATE can't be told from other binary data, so it isn't.
fn is_compressed(bytes: &[u8]) -> bool {
    (bytes.first() == Some(&0x78) && has_zlib_header(bytes))
        || bytes.starts_with(&[0x1F, 0x8B, 0x08])
        || bytes.starts_with(b"BZh")
        || bytes.starts_with(&[0xFD, b'7', b'z', b'X', b'Z', 0x00])
}

