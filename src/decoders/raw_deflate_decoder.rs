    #[test]
    fn random_bytes_do_not_inflate_to_text() {
        // Pseudo-random bytes (xorshift64), 12 to 64 of them, as the Base64 and hex views
        // read them. The plan in #1022 measured 0 text outputs in 200,000 tries per length.
        let mut state = 0x2545_f491_4f6c_dd1d_u64;
        let mut next_byte = || {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            state as u8
        };
        let mut complete = 0;
        for i in 0..20_000 {
            let stream: Vec<u8> = (0..12 + i % 53).map(|_| next_byte()).collect();
            if let Some(output) = raw_inflate_bounded(&stream) {
                complete += 1;
                assert!(super::into_text(output).is_err(), "{stream:02x?}");
            }
        }
        // 9 of them are complete streams, all of binary output
        assert!(complete < 40, "{complete} complete streams");
    }

