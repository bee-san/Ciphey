//! Inflate raw DEFLATE streams (RFC 1951): the compressed data inside zlib and gzip,
//! without their header and checksum. PHP's `gzdeflate()`, .NET's `DeflateStream`, Java's
//! `Deflater` with `nowrap`, Python's `zlib.compressobj(wbits=-15)` and CyberChef's Raw
//! Deflate write it.
//! Call raw_deflate_decoder.crack to use. It returns a `CrackResult`; check
//! `result.unencrypted_text.is_some()` to see if it decoded.
//!
//! Raw DEFLATE has no magic bytes: the only test is that it inflates cleanly. Compressed
//! data is binary and Ciphey passes text between decoders (the Base64 decoder drops output
//! that isn't UTF-8), so, like the Zlib and Gzip decoders, this one reads the compressed
//! bytes itself, from the first of these views of its input that holds a stream:
//!
//! * Base64, standard or URL-safe, with or without padding and line breaks,
//! * hex, optionally split by whitespace, `:` or `,`, with or without `0x` / `\x` prefixes,
//! * raw bytes, as the text the Hexadecimal and Binary decoders produce for binary data
//!   (one Latin-1 character per byte, or UTF-8 when the bytes happen to be UTF-8).
//!
//! Which views apply is decided by the alphabet, in one pass that stops at the first
//! character that doesn't fit, before anything is allocated. A view's bytes then have to
//! start with a plausible block header (RFC 1951 section 3.2.3: not the reserved block
//! type, a stored block's length matching its complement, a dynamic block's code counts
//! in range) and not be a zlib stream, which is the Zlib decoder's. That rejects about
//! half of all byte strings without inflating them. The rest has to inflate without error,
//! end with a final block exactly where the input ends and inflate to at most
//! [`MAX_OUTPUT`] bytes of text, so random bytes almost never get through.

