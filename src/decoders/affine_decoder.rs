    #[test]
    fn unidentified_text_returns_the_three_best_decryptions() {
        let affine_decoder = Decoder::<AffineDecoder>::new();
        let text = "Lorem ipsum dolor sit amet, consectetur adipiscing elit";
        let result = affine_decoder.crack(text, &get_athena_checker());
        assert!(!result.success);
        assert!(result.key.is_none());
        let expected: Vec<String> = rank_keys(text)
            .into_iter()
            .take(CANDIDATES_RETURNED)
            .map(|(a, b)| decrypt(text, a, b))
            .collect();
        assert_eq!(result.unencrypted_text.unwrap(), expected);
    }

    #[test]
    fn pre_checks_reject_input_that_cannot_be_affine() {
        let affine_decoder = Decoder::<AffineDecoder>::new();
        for text in [
            "",
            "😀",
            "ab",
            "12345",
            // 5 letters
            "abc de",
            // 6 letters but only 2 pairs
            "ab cd e f",
            // 6 letters and 4 pairs, but more digits than letters
            "abc12345 def67890",
            // hex
            "48656c6c6f2c20576f726c6421",
            // letters, but no two next to each other
            "a1b2c3d4e5f6g7h8",
            // non-ASCII letters only
            "éèêëàâäôöûüç",
            "     ",
        ] {
            assert!(rank_keys(text).is_empty(), "{text:?} passed the pre-checks");
            let result = affine_decoder.crack(text, &get_athena_checker());
            assert!(!result.success, "{text:?}");
            assert!(result.unencrypted_text.is_none(), "{text:?}");
            assert!(result.key.is_none(), "{text:?}");
        }
        // Just enough: 6 letters, 3 pairs, half the non-whitespace characters
        assert_eq!(rank_keys("abcd e f").len(), 285);
        assert_eq!(rank_keys("abcd e f 1!2?3.").len(), 285);
    }

    #[test]
    fn caesar_atbash_and_plaintext_are_not_cracked() {
        // ROT13 and Atbash keys are skipped (the Caesar and Atbash decoders own them),
        // and ordinary English shouldn't decrypt to anything English.
        let affine_decoder = Decoder::<AffineDecoder>::new();
        for text in [
            "Uryyb, Jbeyq!",
            "Svool, Dliow!",
            "The quick brown fox jumps over the lazy dog",
        ] {
            let result = affine_decoder.crack(text, &get_athena_checker());
            assert!(!result.success, "{text:?} was cracked: {result:?}");
            assert!(result.key.is_none());
            let candidates = result.unencrypted_text.unwrap_or_default();
            assert!(candidates.len() <= CANDIDATES_RETURNED);
            assert!(!candidates.iter().any(|c| c == "Hello, World!"));
        }
    }

    #[test]
    fn decoder_metadata() {
        let affine_decoder = Decoder::<AffineDecoder>::new();
        assert_eq!(affine_decoder.get_name(), "Affine");
        assert_eq!(affine_decoder.get_popularity(), 0.5);
        assert_eq!(
            affine_decoder.get_link(),
            "https://en.wikipedia.org/wiki/Affine_cipher"
        );
        // A cracker, not a decoder, and not reciprocal: two affine steps compose into one
        let tags = affine_decoder.get_tags();
        assert!(!tags.contains(&"decoder"));
        assert!(!tags.contains(&"reciprocal"));
        assert!(tags.contains(&"affine"));
    }

