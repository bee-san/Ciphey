    // helper for tests: the decoded candidate, if the decoder returned one
    fn decode(text: &str) -> Option<String> {
        crack(text)
            .unencrypted_text
            .and_then(|candidates| candidates.into_iter().next())
    }

    // Cracks `ciphertext` and asserts the checker accepted `plaintext`
    fn assert_cracks_to(ciphertext: &str, plaintext: &str) {
        let result = crack(ciphertext);
        assert_eq!(
            result.unencrypted_text.as_deref(),
            Some(&[plaintext.to_string()][..]),
            "{ciphertext:?}"
        );
        assert!(result.success, "the checker should accept {plaintext:?}");
    }

    // Asserts the decoder rejects `text` without producing a candidate
    fn assert_fails(text: &str) {
        let result = crack(text);
        assert_eq!(result.unencrypted_text, None, "{text:?} should fail");
        assert!(!result.success, "{text:?} should fail");
    }

