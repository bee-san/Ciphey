    #[test]
    fn backslash_escape_octal_takes_at_most_two_digits_after_4_to_7() {
        // CyberChef and JavaScript agree. Python reads three digits and wraps \400 around
        // to \x00.
        assert_eq!(decode(r"\400").as_deref(), Some(" 0"));
        assert_eq!(decode(r"\777").as_deref(), Some("?7"));
        assert_eq!(decode(r"\608").as_deref(), Some("08"));
        // A first digit of 0 to 3 takes three, and no more
        assert_eq!(decode(r"\1011").as_deref(), Some("A1"));
        assert_eq!(decode(r"\1234").as_deref(), Some("S4"));
        // \x takes exactly two hex digits
        assert_eq!(decode(r"\x414").as_deref(), Some("A4"));
    }

    #[test]
    fn backslash_escape_copies_other_backslashes_unchanged() {
        // CyberChef agrees. Python rejects \x without two hex digits and keeps the others.
        assert_eq!(
            decode(r"\x41 \e \/ \8 \q \x4g \x \N{DASH}").as_deref(),
            Some(r"A \e \/ \8 \q \x4g \x \N{DASH}")
        );
    }

    #[test]
    fn backslash_escape_leaves_unicode_escapes_to_their_own_decoder() {
        // Deliberately unlike CyberChef, which gives "AB" and reads \u{41} too: the Unicode
        // Escapes decoder reads \u, so the search finds "AB" one step later instead of
        // twice. Python bytes literals don't read \u or \U either.
        assert_eq!(decode(r"\u0041\x42").as_deref(), Some(r"\u0041B"));
        assert_eq!(decode(r"\\u0041").as_deref(), Some(r"\u0041"));
        assert_eq!(
            decode(r"\U00000041\u{41}\x43").as_deref(),
            Some(r"\U00000041\u{41}C")
        );
    }

    #[test]
    fn backslash_escape_decodes_an_escaped_backslash_once() {
        // `\\n` is a backslash and an `n`, not a line feed
        assert_eq!(decode(r"\\n").as_deref(), Some(r"\n"));
        // An escaped backslash, then a trailing one that is copied. CyberChef agrees; Python
        // rejects a trailing backslash.
        assert_eq!(decode(r"\\\").as_deref(), Some(r"\\"));
        // Double escaping takes two passes, which the search does
        assert_eq!(decode(r"\\x41\\x42\\x43").as_deref(), Some(r"\x41\x42\x43"));
        assert_eq!(decode(r"\x41\x42\x43").as_deref(), Some("ABC"));
    }

