//! Decode backslash escapes, the way C, Python and JavaScript write bytes in string
//! literals: `\110\145\154\154\157`, `\x48\x69`, `Line one\nLine two\t\x41` and so on.
//!
//! The text is scanned once. Every well-formed escape is replaced by the byte it stands for
//! and everything else is copied unchanged, so escapes mixed with ordinary text decode too.
//!
//! | Escape                       | Byte                                                  |
//! |------------------------------|-------------------------------------------------------|
//! | `\NNN`                       | 1 to 3 octal digits, at most 2 if the first is 4 to 7 |
//! | `\xHH`                       | exactly 2 hex digits, either case                     |
//! | `\a` `\b` `\f` `\n` `\r` `\t` `\v` | BEL, BS, FF, LF, CR, TAB, VT                    |
//! | `\\` `\'` `\"`               | the character after the backslash                     |
//!
//! As in JavaScript and CyberChef, an octal escape never goes above `\377` (255): `\400`
//! is `\40` (a space) followed by `0`. Anything else after a backslash is copied as it is,
//! like Python and CyberChef do: `\e`, `\/`, `\8`, `\q`, a `\x` without two hex digits and a
//! trailing `\`. So are `\uXXXX`, `\u{…}` and `\UXXXXXXXX`, which the Unicode Escapes
//! decoder reads, so that the two decoders don't both produce the same text.
//!
//! Escapes stand for bytes, not characters: `\xc3\xa9` is `é`. The bytes are read as UTF-8,
//! falling back to Latin-1. The whole text may be a quoted literal, such as the Python bytes
//! repr `b'caf\xc3\xa9'` or `"\x48\x69"`; the quotes and the `b` are dropped.
//!
//! References:
//! * [Escape sequences in C](https://en.wikipedia.org/wiki/Escape_sequences_in_C)
//! * [Python escape sequences](https://docs.python.org/3/reference/lexical_analysis.html#escape-sequences)
//! * [ECMA-262 legacy octal escapes](https://tc39.es/ecma262/#prod-annexB-LegacyOctalEscapeSequence)
//! * [CyberChef Unescape string](https://gchq.github.io/CyberChef/#recipe=Unescape_string())
//!
//! ```
//! use ciphey::checkers::{
//!     athena::Athena,
//!     checker_type::{Check, Checker},
//!     CheckerTypes,
//! };
//! use ciphey::decoders::backslash_escape_decoder::BackslashEscapeDecoder;
//! use ciphey::decoders::interface::{Crack, Decoder};
//!
//! let decoder = Decoder::<BackslashEscapeDecoder>::new();
//! let checker = CheckerTypes::CheckAthena(Checker::<Athena>::new());
//!
//! let result = decoder.crack(r"\110\145\154\154\157\054\040\x57\x6f\x72\x6c\x64\x21", &checker);
//! assert!(result.success);
//! assert_eq!(result.unencrypted_text.unwrap()[0], "Hello, World!");
//!
//! // Text without a single escape is not decoded
//! let result = decoder.crack(r"C:\Users", &checker);
//! assert!(result.unencrypted_text.is_none());
//! ```

