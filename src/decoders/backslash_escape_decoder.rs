/// The backslash escape decoder, call:
/// `let decoder = Decoder::<BackslashEscapeDecoder>::new()` to create a new instance
/// And then call:
/// `result = decoder.crack(input, &checker)` to decode the escapes in a string
/// The struct generated by new() comes from interface.rs
pub struct BackslashEscapeDecoder;

impl Crack for Decoder<BackslashEscapeDecoder> {
    fn new() -> Decoder<BackslashEscapeDecoder> {
        Decoder {
            name: "Backslash Escapes",
            description: "C, Python and JavaScript string escapes (\\NNN in octal, \\xHH in hexadecimal, \\n, \\t, \\\\ and the other single-character escapes) mixed with literal text, optionally inside a Python b'…' repr.",
            link: "https://en.wikipedia.org/wiki/Escape_sequences_in_C",
            tags: vec!["backslash_escape", "escape", "string", "decoder"],
            popularity: 0.5,
            phantom: std::marker::PhantomData,
        }
    }

    /// Replaces every escape in `text` with its byte (see the module docs for the forms)
    /// and runs the checker on the result.
    ///
    /// Fails unless at least one escape was replaced. Trailing NULs, the terminator of a C
    /// string, are dropped; any other control character apart from tab, carriage return
    /// and line feed fails the text, and so does a result that is only whitespace.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying backslash escapes with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        // One pass over the bytes that rejects almost every input the search tries
        if !has_escape(text) {
            trace!("No backslash escape in text");
            return results;
        }

        let Some(decoded_text) = decode_backslash_escapes(text) else {
            debug!("Failed to decode backslash escapes: none replaced, or the result is not text");
            return results;
        };

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode backslash escapes because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);

        results.update_checker(&checker_result);

        results
    }
    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Whether some backslash in `text` starts a well-formed escape.
///
/// This runs on every text the search tries, and nearly all of them have no backslash at
/// all. Searching for a `char` uses `memchr`, so the common case is a fast scan with no
/// allocation.
fn has_escape(text: &str) -> bool {
    let bytes = text.as_bytes();
    text.match_indices('\\')
        .any(|(index, _)| parse_escape(&bytes[index + 1..]).is_some())
}

/// Decodes `text`, or returns `None` if it has no escape or doesn't decode to text.
fn decode_backslash_escapes(text: &str) -> Option<String> {
    let mut bytes = decode_escapes(strip_literal_quotes(text).as_bytes())?;
    // A C string ends with a NUL byte: `hello world\0`
    while bytes.last() == Some(&0) {
        bytes.pop();
    }
    let decoded = bytes_to_string(bytes);
    if decoded.trim().is_empty() || has_unexpected_control_character(&decoded) {
        return None;
    }
    Some(decoded)
}

/// The text inside a quoted string literal that makes up the whole (trimmed) text: a
/// Python bytes repr `b'…'` or `B"…"`, or a bare `'…'` or `"…"`. Returns `text` unchanged
/// if it isn't one.
fn strip_literal_quotes(text: &str) -> &str {
    let trimmed = text.trim();
    let unprefixed = trimmed.strip_prefix(['b', 'B']).unwrap_or(trimmed);
    ['\'', '"']
        .into_iter()
        .find_map(|quote| unprefixed.strip_prefix(quote)?.strip_suffix(quote))
        .unwrap_or(text)
}

/// Replaces every well-formed escape in `bytes` with the byte it stands for and copies the
/// rest unchanged, so non-ASCII text between escapes keeps its UTF-8 bytes.
///
/// Returns `None` when nothing was replaced.
fn decode_escapes(bytes: &[u8]) -> Option<Vec<u8>> {
    let mut decoded = Vec::with_capacity(bytes.len());
    let mut replaced_any = false;
    // Everything before this offset has been written to `decoded`
    let mut copied_up_to = 0;
    let mut i = 0;

    while let Some(offset) = bytes[i..].iter().position(|&byte| byte == b'\\') {
        let backslash = i + offset;
        i = backslash + 1;
        // Anything that isn't an escape, such as `\q`, `\u0041` or a trailing `\`, is
        // copied unchanged along with the text around it
        let Some((byte, len)) = parse_escape(&bytes[i..]) else {
            continue;
        };
        decoded.extend_from_slice(&bytes[copied_up_to..backslash]);
        decoded.push(byte);
        replaced_any = true;
        i += len;
        copied_up_to = i;
    }

    if !replaced_any {
        return None;
    }
    decoded.extend_from_slice(&bytes[copied_up_to..]);
    Some(decoded)
}

/// Parses the escape whose backslash comes just before `after`. Returns the byte it stands
/// for and how many bytes of `after` it uses, or `None` if the backslash doesn't start an
/// escape.
fn parse_escape(after: &[u8]) -> Option<(u8, usize)> {
    let &first = after.first()?;
    let byte = match first {
        b'\\' | b'\'' | b'"' => first,
        b'a' => 0x07,
        b'b' => 0x08,
        b'f' => 0x0c,
        b'n' => b'\n',
        b'r' => b'\r',
        b't' => b'\t',
        b'v' => 0x0b,
        b'x' => {
            let high = hex_digit_value(*after.get(1)?)?;
            let low = hex_digit_value(*after.get(2)?)?;
            return Some(((high << 4) | low, 3));
        }
        b'0'..=b'7' => {
            // `\377` is the largest byte. Like JavaScript, read a third digit only after a
            // first digit of 0 to 3, so the value always fits in a byte.
            let max_digits = if first <= b'3' { 3 } else { 2 };
            let digits = after
                .iter()
                .take(max_digits)
                .take_while(|digit| matches!(digit, b'0'..=b'7'))
                .count();
            let value = after[..digits]
                .iter()
                .fold(0, |value, &digit| value * 8 + (digit - b'0'));
            return Some((value, digits));
        }
        _ => return None,
    };
    Some((byte, 1))
}

/// The value of one ASCII hex digit, either case
fn hex_digit_value(digit: u8) -> Option<u8> {
    match digit {
        b'0'..=b'9' => Some(digit - b'0'),
        b'a'..=b'f' => Some(digit - b'a' + 10),
        b'A'..=b'F' => Some(digit - b'A' + 10),
        _ => None,
    }
}

/// Whether `text` has a control character other than tab, carriage return or line feed.
/// Plaintext doesn't contain BEL, ESC or NUL, so escapes that decode to one mean this
/// wasn't a string of escaped text.
fn has_unexpected_control_character(text: &str) -> bool {
    text.chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\r' | '\n'))
}

