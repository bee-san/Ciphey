//! Decode DTMF (touch-tone) frequency pairs, such as `852-1336` for the telephone key `8`.
//! Performs error handling and returns a string
//! Call dtmf_decoder.crack to use. It returns a `CrackResult` whose `unencrypted_text` is
//! `None` when the input isn't DTMF.
//!
//! DTMF plays each key as two tones at once: one from the low group (697, 770, 852 or 941 Hz,
//! the keypad row) and one from the high group (1209, 1336, 1477 or 1633 Hz, the column).
//!
//! ```text
//!          1209  1336  1477  1633
//!    697     1     2     3     A
//!    770     4     5     6     B
//!    852     7     8     9     C
//!    941     *     0     #     D
//! ```
//!
//! The two frequencies of a key can come in either order (dCode writes the high one first)
//! and are separated by whitespace, `-`, `/`, `+`, `,`, `;`, `:` or `|`, with or without
//! `Hz` after each one. They can also be glued together, 7 digits per key (`8521336`), the
//! form Python Ciphey decoded. The output is the keys `0`-`9`, `*`, `#` and `A`-`D`.
//!
//! A line break, a `|` or two or more whitespace characters between two keys is a word gap
//! and becomes a space, so the keys of each word stay together for decoders that read
//! them next, such as Multi-tap.

use crate::checkers::CheckerTypes;
use crate::decoders::interface::check_string_success;

