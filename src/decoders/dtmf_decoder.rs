/// The DTMF decoder, call:
/// `let dtmf_decoder = Decoder::<DtmfDecoder>::new()` to create a new instance
/// And then call:
/// `result = dtmf_decoder.crack(input)` to decode DTMF frequency pairs
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::dtmf_decoder::DtmfDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_dtmf = Decoder::<DtmfDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// let result = decode_dtmf
///     .crack("852-1336 770-1477 852-1209 770-1336 697-1477 941-1336 852-1477", &checker)
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "8675309");
///
/// // The high frequency first, as dCode writes it
/// let result = decode_dtmf
///     .crack("1633-941/1633-852/1336-941/1633-941/1477-697", &checker)
///     .unencrypted_text;
/// assert_eq!(result.unwrap()[0], "DC0D3");
/// ```
pub struct DtmfDecoder;

/// The low-group frequencies in Hz, one per keypad row.
const LOW: [u32; 4] = [697, 770, 852, 941];

/// The high-group frequencies in Hz, one per keypad column.
const HIGH: [u32; 4] = [1209, 1336, 1477, 1633];

/// The key in each row (low frequency) and column (high frequency).
const KEYPAD: [[char; 4]; 4] = [
    ['1', '2', '3', 'A'],
    ['4', '5', '6', 'B'],
    ['7', '8', '9', 'C'],
    ['*', '0', '#', 'D'],
];

/// Digits per key when the two frequencies are written with nothing between them.
const GLUED_KEY_DIGITS: usize = 7;

/// Fewer keys than this aren't worth returning: the search drops results of 2 characters
/// or fewer.
const MIN_KEYS: usize = 3;

impl Crack for Decoder<DtmfDecoder> {
    fn new() -> Decoder<DtmfDecoder> {
        Decoder {
            name: "DTMF",
            description: "DTMF (touch-tone) writes each telephone key as a pair of frequencies, one of 697/770/852/941 Hz and one of 1209/1336/1477/1633 Hz, for example 852-1336 for 8. The output is the keys 0-9, *, # and A-D.",
            link: "https://en.wikipedia.org/wiki/Dual-tone_multi-frequency_signaling",
            tags: vec!["dtmf", "phone", "telephone", "substitution", "decoder"],
            popularity: 0.3,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` as DTMF frequency pairs and checks the result with `checker`.
    /// `unencrypted_text` is `None` when `text` isn't DTMF.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying DTMF with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(decoded_text) = decode_dtmf(text) else {
            debug!("Failed to decode DTMF because the text isn't DTMF frequency pairs");
            return results;
        };
        trace!("Decoded text for DTMF: {:?}", decoded_text);

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode DTMF because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        // The keys are returned even when the checker doesn't identify them: a string of
        // digits is what decoders such as Multi-tap, T9 or A1Z26 read next.
        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// One of the two frequencies of a key.
#[derive(Clone, Copy)]
enum Tone {
    /// A low-group frequency, by keypad row
    Low(usize),
    /// A high-group frequency, by keypad column
    High(usize),
}

/// Decodes DTMF frequency pairs to keys, or returns `None` if `text` isn't DTMF.
///
/// This is a single pass over the bytes that fails at the first byte or number that can't
/// be DTMF, and allocates nothing before the first key is decoded.
fn decode_dtmf(text: &str) -> Option<String> {
    let bytes = text.trim().as_bytes();
    // DTMF starts with a frequency, so almost every other input fails here
    if !bytes.first()?.is_ascii_digit() {
        return None;
    }

    let mut keys = String::new();
    let mut key_count = 0;
    // The first frequency of a key whose second one hasn't been read yet, and whether a
    // word gap came before it
    let mut first_tone: Option<(Tone, bool)> = None;
    // Whether the separators before the current number are a word gap
    let mut gap = false;
    let mut i = 0;
    while i < bytes.len() {
        // A number. Each turn of the loop starts on a digit, so it has at least one.
        let start = i;
        while i < bytes.len() && bytes[i].is_ascii_digit() {
            i += 1;
        }
        let digits = &bytes[start..i];
        match digits.len() {
            3 | 4 => {
                let tone = tone(digits)?;
                match first_tone.take() {
                    None => first_tone = Some((tone, gap)),
                    Some((first, gap_before)) => {
                        push_key(&mut keys, key(first, tone)?, gap_before);
                        key_count += 1;
                    }
                }
            }
            length if length.is_multiple_of(GLUED_KEY_DIGITS) => {
                // A key can't be split between a lone frequency and glued digits
                if first_tone.is_some() {
                    return None;
                }
                for (index, glued) in digits.chunks(GLUED_KEY_DIGITS).enumerate() {
                    push_key(&mut keys, glued_key(glued)?, gap && index == 0);
                    key_count += 1;
                }
            }
            // Not a frequency: `8-5-12`, `104 101 108`, `555-1234`, `0697`
            _ => return None,
        }

        // The separators before the next number
        gap = false;
        let mut after_whitespace = false;
        while i < bytes.len() && !bytes[i].is_ascii_digit() {
            let byte = bytes[i];
            if !is_separator(byte) {
                return None;
            }
            let whitespace = byte.is_ascii_whitespace();
            gap |= matches!(byte, b'\n' | b'\r' | b'|') || (whitespace && after_whitespace);
            after_whitespace = whitespace;
            i += 1;
        }
    }

    // An odd number of frequencies, or too few keys to be worth returning
    if first_tone.is_some() || key_count < MIN_KEYS {
        return None;
    }
    Some(keys)
}

/// Whether `byte` can come between two frequencies: whitespace, punctuation, or a letter
/// of an `Hz` suffix.
fn is_separator(byte: u8) -> bool {
    byte.is_ascii_whitespace()
        || matches!(
            byte,
            b'-' | b'/' | b'+' | b',' | b';' | b':' | b'|' | b'H' | b'h' | b'z' | b'Z'
        )
}

/// The frequency that the ASCII digits in `digits` stand for: 3 digits for a low-group
/// one, 4 for a high-group one. A zero-padded number like `0697` isn't a frequency.
fn tone(digits: &[u8]) -> Option<Tone> {
    let position = |group: &[u32; 4]| {
        let value = digits
            .iter()
            .fold(0, |value, &digit| value * 10 + u32::from(digit - b'0'));
        group.iter().position(|&frequency| frequency == value)
    };
    match digits.len() {
        3 => position(&LOW).map(Tone::Low),
        4 => position(&HIGH).map(Tone::High),
        _ => None,
    }
}

/// The key for two frequencies in either order, or `None` unless one is from each group.
fn key(first: Tone, second: Tone) -> Option<char> {
    match (first, second) {
        (Tone::Low(row), Tone::High(column)) | (Tone::High(column), Tone::Low(row)) => {
            Some(KEYPAD[row][column])
        }
        _ => None,
    }
}

/// The key for 7 glued digits: a low frequency then a high one (`8521336`), or a high one
/// then a low one (`1336852`). At most one of them can match, because the low
/// frequencies start with 6 to 9 and the high ones with 1.
fn glued_key(digits: &[u8]) -> Option<char> {
    [3, 4].into_iter().find_map(|split| {
        let (first, second) = digits.split_at(split);
        key(tone(first)?, tone(second)?)
    })
}

/// Appends `key` to `keys`, after a space if a word gap came before it.
fn push_key(keys: &mut String, key: char, gap_before: bool) {
    if gap_before {
        keys.push(' ');
    }
    keys.push(key);
}

