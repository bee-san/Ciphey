    fn decodes_every_entry_of_the_cipheydists_table() {
        for (glued, expected) in CIPHEYDISTS_TABLE {
            let three_keys = expected.to_string().repeat(3);
            // Glued, as in the table
            assert_eq!(
                decode_dtmf(&[glued; 3].join(" ")).as_deref(),
                Some(three_keys.as_str()),
                "{glued}"
            );
            // Split into its two frequencies
            let split = if glued.starts_with('1') { 4 } else { 3 };
            let pair = format!("{}-{}", &glued[..split], &glued[split..]);
            assert_eq!(
                decode_dtmf(&[pair.as_str(); 3].join(" ")).as_deref(),
                Some(three_keys.as_str()),
                "{pair}"
            );
        }
    }

    #[test]
    fn cipheydists_table_is_the_keypad() {
        // Every key, in both orders, is in the table exactly once
        for (row, &low) in LOW.iter().enumerate() {
            for (column, &high) in HIGH.iter().enumerate() {
                let key = KEYPAD[row][column];
                for glued in [format!("{low}{high}"), format!("{high}{low}")] {
                    let matches: Vec<char> = CIPHEYDISTS_TABLE
                        .iter()
                        .filter(|(entry, _)| *entry == glued)
                        .map(|&(_, key)| key)
                        .collect();
                    assert_eq!(matches, [key], "{glued}");
                }
            }
        }
    }

