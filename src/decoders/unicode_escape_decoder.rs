    // helper for tests: the obvious way to write has_escape_marker
    fn has_escape_marker_naive(text: &str) -> bool {
        text.as_bytes()
            .windows(2)
            .any(|pair| matches!(pair, [b'\\' | b'%', b'u' | b'U'] | [b'U', b'+']))
    }

    #[test]
    fn unicode_escape_marker_check_agrees_with_the_naive_check() {
        // Every text of 1 to 6 characters made of marker parts and a filler
        let alphabet = ['\\', '%', 'u', 'U', '+', 'x'];
        let mut texts = vec![String::new()];
        for _ in 0..6 {
            texts = texts
                .iter()
                .flat_map(|text| alphabet.iter().map(move |c| format!("{text}{c}")))
                .collect();
            for text in &texts {
                assert_eq!(
                    has_escape_marker(text),
                    has_escape_marker_naive(text),
                    "{text:?}"
                );
            }
        }
    }

    #[test]
    fn unicode_escape_marker_check_finds_markers_at_any_offset() {
        // has_escape_marker works in chunks of 64; a marker can straddle two of them
        for marker in [r"\u", r"\U", "%u", "%U", "U+"] {
            for filler in ["x", "é"] {
                for count in 0..200 {
                    let text = format!("{}{marker}{}", filler.repeat(count), "x".repeat(count % 3));
                    assert!(has_escape_marker(&text), "{marker} after {count} {filler}");
                }
            }
        }
        assert!(!has_escape_marker(&r"x\x%xU-u+\ +U%+é".repeat(20)));
    }

    #[test]
    fn unicode_escape_is_registered() {
        let decoders = get_decoder_by_name("Unicode Escapes");
        assert_eq!(decoders.components.len(), 1);
        assert_eq!(decoders.components[0].get_name(), "Unicode Escapes");
    }

    #[test]
    fn unicode_escape_crack_result_round_trips_through_json() {
        // The cache stores paths as JSON and finds the decoder again through DECODER_MAP
        let decoder = Decoder::<UnicodeEscapeDecoder>::new();
        let json = CrackResult::new(&decoder, r"\u0041".to_string())
            .get_json()
            .unwrap();
        let crack_result: CrackResult = serde_json::from_str(&json).unwrap();
        assert_eq!(crack_result.decoder, "Unicode Escapes");
        assert_eq!(crack_result.link, decoder.link);
    }
