/// The Unicode escape decoder, call:
/// `let unicode_escape_decoder = Decoder::<UnicodeEscapeDecoder>::new()` to create a new instance
/// And then call:
/// `result = unicode_escape_decoder.crack(input)` to decode Unicode escape sequences
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::unicode_escape_decoder::UnicodeEscapeDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decoder = Decoder::<UnicodeEscapeDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// let result = decoder
///     .crack(r"\u0043\u0061\u0066\u00E9\u0020\u2615", &checker)
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "Café ☕");
/// ```
pub struct UnicodeEscapeDecoder;

impl Crack for Decoder<UnicodeEscapeDecoder> {
    fn new() -> Decoder<UnicodeEscapeDecoder> {
        Decoder {
            name: "Unicode Escapes",
            description: "Unicode escape sequences write each character as its code point in hexadecimal: \\u00E9 (JSON, JavaScript, Java and C#, with UTF-16 surrogate pairs above U+FFFF), \\u{1F600} (JavaScript and Rust), \\U0001F600 (Python and C), %u00E9 (JavaScript escape()) and U+00E9 (Unicode notation).",
            link: "https://en.wikipedia.org/wiki/Escape_sequences_in_C#Universal_character_names",
            tags: vec!["unicode_escape", "unicode", "escape", "decoder"],
            popularity: 0.4,
            phantom: std::marker::PhantomData,
        }
    }

    /// Replaces every escape in `text` with its character (see the module docs for the
    /// forms) and runs the checker on the result.
    ///
    /// Fails unless at least one escape was replaced. Also fails if an escape is not a
    /// character (a lone surrogate, or above U+10FFFF) or the result has control
    /// characters other than tab, carriage return and line feed.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Unicode escapes with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        // One pass over the bytes that rejects almost every input the search tries
        if !has_escape_marker(text) {
            trace!("No Unicode escape marker in text");
            return results;
        }

        let Some(decoded_text) = decode_unicode_escapes(text) else {
            debug!("Failed to decode Unicode escapes: none found, or one is not a character");
            return results;
        };

        if has_unexpected_control_character(&decoded_text) {
            debug!(
                "Failed to decode Unicode escapes: {:?} has control characters",
                decoded_text
            );
            return results;
        }

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Unicode escapes because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);

        results.update_checker(&checker_result);

        results
    }
    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// One escape sequence, as found at some position in the text
struct Escape {
    /// The escaped number: a code point, or a UTF-16 code unit for `\uXXXX` and `%uXXXX`
    value: u32,
    /// Length of the whole escape in bytes, prefix included
    len: usize,
    /// Whether this is a 4 digit `\uXXXX` or `%uXXXX` escape. Only these write UTF-16
    /// code units, so only these can hold half of a surrogate pair.
    utf16: bool,
}

/// Whether `text` contains `\u`, `\U`, `%u`, `%U` or `U+`, one of which starts every escape
fn has_escape_marker(text: &str) -> bool {
    let bytes = text.as_bytes();
    if bytes.len() < 2 {
        return false;
    }
    // This runs on every text the search tries. Checking each pair of neighbouring bytes
    // with no early exit inside a 64 pair chunk lets the compiler vectorise the loop,
    // which is about 10 times faster on long texts than stopping at the first match.
    bytes[..bytes.len() - 1]
        .chunks(64)
        .zip(bytes[1..].chunks(64))
        .any(|(firsts, seconds)| {
            firsts
                .iter()
                .zip(seconds)
                .fold(false, |found, (&first, &second)| {
                    found | is_escape_marker(first, second)
                })
        })
}

/// Whether two neighbouring bytes are `\u`, `\U`, `%u`, `%U` or `U+`. Written without
/// branches for [`has_escape_marker`]; `| 0x20` lowercases an ASCII `U`.
fn is_escape_marker(first: u8, second: u8) -> bool {
    (((first == b'\\') | (first == b'%')) & ((second | 0x20) == b'u'))
        | ((first == b'U') & (second == b'+'))
}

/// Decodes `text`, or returns `None` if it has no escape or an escape is not a character
fn decode_unicode_escapes(text: &str) -> Option<String> {
    decode_code_point_list(text).or_else(|| decode_escapes(text))
}

/// Decodes text made only of `U+XXXX` code points separated by whitespace or commas, such
/// as `U+0048 U+0069`. Each one is a whole character (a space is `U+0020`), so the
/// separators are dropped. CyberChef keeps them and gives `H i`.
///
/// Returns `None` if the text has anything else in it.
fn decode_code_point_list(text: &str) -> Option<String> {
    let mut decoded = String::new();
    for token in text
        .split(|c: char| c.is_whitespace() || c == ',')
        .filter(|token| !token.is_empty())
    {
        let digits = token.strip_prefix("U+")?.as_bytes();
        if !(4..=6).contains(&digits.len()) || hex_digit_count(digits, 6) != digits.len() {
            return None;
        }
        decoded.push(char::from_u32(hex_value(digits))?);
    }
    (!decoded.is_empty()).then_some(decoded)
}

/// Replaces every well-formed escape in `text` with its character and copies the rest
/// unchanged.
///
/// Returns `None` when nothing was replaced, or when an escape does not encode a
/// character: a lone UTF-16 surrogate, or a value above U+10FFFF.
fn decode_escapes(text: &str) -> Option<String> {
    let bytes = text.as_bytes();
    let mut decoded = String::with_capacity(text.len());
    let mut replaced_any = false;
    // Everything before this byte offset has been written to `decoded`
    let mut copied_up_to = 0;
    let mut i = 0;

    while i < bytes.len() {
        let Some(escape) = parse_escape(&bytes[i..]) else {
            i += 1;
            continue;
        };
        let (character, len) = escape_to_char(&escape, &bytes[i + escape.len..])?;
        // An escape starts and ends with an ASCII byte, so both offsets are char boundaries
        decoded.push_str(&text[copied_up_to..i]);
        decoded.push(character);
        replaced_any = true;
        i += len;
        copied_up_to = i;
    }

    if !replaced_any {
        return None;
    }
    decoded.push_str(&text[copied_up_to..]);
    Some(decoded)
}

/// The character `escape` encodes and the number of bytes used for it. A high surrogate
/// is combined with the low surrogate escape at the start of `after`.
fn escape_to_char(escape: &Escape, after: &[u8]) -> Option<(char, usize)> {
    if escape.utf16 && (0xD800..=0xDBFF).contains(&escape.value) {
        let low = parse_escape(after)
            .filter(|low| low.utf16 && (0xDC00..=0xDFFF).contains(&low.value))?;
        let code_point = 0x10000 + ((escape.value - 0xD800) << 10) + (low.value - 0xDC00);
        return char::from_u32(code_point).map(|c| (c, escape.len + low.len));
    }
    // Rejects lone low surrogates and values above U+10FFFF
    char::from_u32(escape.value).map(|c| (c, escape.len))
}

/// Parses the escape at the start of `bytes`, if there is a well-formed one there
fn parse_escape(bytes: &[u8]) -> Option<Escape> {
    match bytes {
        [b'\\', b'u', b'{', rest @ ..] => {
            let digits = hex_digit_count(rest, 7);
            ((1..=6).contains(&digits) && rest.get(digits) == Some(&b'}')).then(|| Escape {
                value: hex_value(&rest[..digits]),
                len: digits + 4,
                utf16: false,
            })
        }
        [b'\\', b'u', rest @ ..] | [b'%', b'u' | b'U', rest @ ..] => {
            (hex_digit_count(rest, 4) == 4).then(|| Escape {
                value: hex_value(&rest[..4]),
                len: 6,
                utf16: true,
            })
        }
        [b'\\', b'U', rest @ ..] => (hex_digit_count(rest, 8) == 8).then(|| Escape {
            value: hex_value(&rest[..8]),
            len: 10,
            utf16: false,
        }),
        [b'U', b'+', rest @ ..] => {
            let digits = hex_digit_count(rest, 6);
            (digits >= 4).then(|| Escape {
                value: hex_value(&rest[..digits]),
                len: digits + 2,
                utf16: false,
            })
        }
        _ => None,
    }
}

/// Number of ASCII hex digits at the start of `bytes`, counting at most `max`
fn hex_digit_count(bytes: &[u8], max: usize) -> usize {
    bytes
        .iter()
        .take(max)
        .take_while(|byte| byte.is_ascii_hexdigit())
        .count()
}

/// The value of up to 8 ASCII hex digits
fn hex_value(digits: &[u8]) -> u32 {
    digits.iter().fold(0, |value, &digit| {
        (value << 4) | char::from(digit).to_digit(16).unwrap_or(0)
    })
}

/// Whether `text` has a control character other than tab, carriage return or line feed.
/// Text whose escapes decode to one, such as `\u0000`, is not plaintext.
fn has_unexpected_control_character(text: &str) -> bool {
    text.chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\r' | '\n'))
}

