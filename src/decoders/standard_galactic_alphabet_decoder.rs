/// The Standard Galactic Alphabet decoder, call:
/// `let sga_decoder = Decoder::<StandardGalacticAlphabetDecoder>::new()` to create a new instance
/// And then call:
/// `result = sga_decoder.crack(input)` to decode Standard Galactic Alphabet text
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::standard_galactic_alphabet_decoder::StandardGalacticAlphabetDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_sga = Decoder::<StandardGalacticAlphabetDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// let result = decode_sga.crack("⍑ᒷꖎꖎ𝙹 ∴𝙹∷ꖎ↸", &checker).unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "hello world");
/// ```
pub struct StandardGalacticAlphabetDecoder;

/// U+2138 DALET SIGN, t. LingoJam follows it with ` ̣ `.
const T: char = '\u{2138}';
/// U+0323 COMBINING DOT BELOW, the dot under t
const DOT_BELOW: char = '\u{0323}';
/// U+0307 COMBINING DOT ABOVE, the dot of x
const DOT_ABOVE: char = '\u{0307}';
/// U+00A1 INVERTED EXCLAMATION MARK, the second half of LingoJam's p (`!¡`)
const INVERTED_EXCLAMATION: char = '\u{00A1}';
/// What follows `ℸ` in `ℸ ̣` and LingoJam's `ℸ ̣ `
const SPACE_DOT_BELOW: &str = " \u{0323}";
/// What follows the space in x, ` ̇/`
const DOT_ABOVE_SLASH: &str = "\u{0307}/";

impl Crack for Decoder<StandardGalacticAlphabetDecoder> {
    fn new() -> Decoder<StandardGalacticAlphabetDecoder> {
        Decoder {
            name: "Standard Galactic Alphabet",
            description: "Standard Galactic Alphabet (Minecraft enchanting table) written with look-alike Unicode symbols",
            link: "https://en.wikipedia.org/wiki/Commander_Keen#Standard_Galactic_Alphabet",
            tags: vec![
                "standard_galactic_alphabet",
                "galactic",
                "minecraft",
                "substitution",
                "decoder",
            ],
            // Rarer than Braille (0.4), but common enough in puzzle Discords. Text that
            // isn't SGA is rejected the same way whatever this is.
            popularity: 0.3,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` from the Standard Galactic Alphabet and checks the result with
    /// `checker`. `unencrypted_text` is `None` when `text` isn't mostly SGA letters.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Standard Galactic Alphabet with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(decoded_text) = decode_galactic(text) else {
            debug!("Failed to decode Standard Galactic Alphabet because too few characters are SGA letters");
            return results;
        };
        trace!(
            "Decoded text for Standard Galactic Alphabet: {:?}",
            decoded_text
        );

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Standard Galactic Alphabet because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// The letter a one-character SGA symbol stands for: 22 letters, and `ℸ` for t.
fn letter(c: char) -> Option<char> {
    Some(match c {
        '\u{1511}' => 'a',  // ᔑ
        '\u{0296}' => 'b',  // ʖ
        '\u{14F5}' => 'c',  // ᓵ
        '\u{21B8}' => 'd',  // ↸
        '\u{14B7}' => 'e',  // ᒷ
        '\u{2393}' => 'f',  // ⎓
        '\u{22A3}' => 'g',  // ⊣
        '\u{2351}' => 'h',  // ⍑
        '\u{254E}' => 'i',  // ╎
        '\u{22EE}' => 'j',  // ⋮
        '\u{A58C}' => 'k',  // ꖌ
        '\u{A58E}' => 'l',  // ꖎ
        '\u{14B2}' => 'm',  // ᒲ
        '\u{30EA}' => 'n',  // リ
        '\u{1D679}' => 'o', // 𝙹
        '\u{1451}' => 'q',  // ᑑ
        '\u{2237}' => 'r',  // ∷
        '\u{14ED}' => 's',  // ᓭ
        T => 't',           // ℸ
        '\u{268D}' => 'u',  // ⚍
        '\u{234A}' => 'v',  // ⍊
        '\u{2234}' => 'w',  // ∴
        '\u{2A05}' => 'z',  // ⨅
        _ => return None,
    })
}

/// What one pass over a text finds before anything is decoded.
#[derive(Debug, PartialEq, Eq)]
struct Census {
    /// Characters that are one of the 23 one-character letters, `ℸ` included
    letters: usize,
    /// ASCII letters, and characters outside ASCII that aren't letters or the marks of
    /// p, t and x: SGA text has few of these
    other: usize,
    /// Whether the text writes p, t, x or y with more than one character (`!¡`, a dotted
    /// `ℸ`, `̇/` or `||`). If it does, a lone `!` or `|` is punctuation.
    multi_char_letters: bool,
}

/// Counts the letters and other characters of `text` in one pass, without allocating.
fn census(text: &str) -> Census {
    let mut census = Census {
        letters: 0,
        other: 0,
        multi_char_letters: false,
    };
    let mut previous = '\0';
    for c in text.chars() {
        if letter(c).is_some() {
            census.letters += 1;
        } else if c.is_ascii_alphabetic()
            || !(c.is_ascii() || matches!(c, DOT_BELOW | DOT_ABOVE | INVERTED_EXCLAMATION))
        {
            census.other += 1;
        }
        // A bare U+0307 is the one-character x, so only the pair with `/` counts
        census.multi_char_letters |= matches!(c, INVERTED_EXCLAMATION | DOT_BELOW)
            || (c == '|' && previous == '|')
            || (c == '/' && previous == DOT_ABOVE);
        previous = c;
    }
    census
}

/// Decodes `text` from the Standard Galactic Alphabet, or returns `None` if it isn't
/// mostly SGA letters.
fn decode_galactic(text: &str) -> Option<String> {
    // Every letter except `!` and `|` is outside ASCII, so Base64, hex, English and almost
    // every other text the search tries stop here
    if text.is_ascii() {
        return None;
    }
    // Braille, CJK, emoji, Japanese (`リンゴ` has one letter and two other characters) and
    // the Latin-1 text Hexadecimal makes of random bytes stop here. Every letter is above
    // U+00FF, so Latin-1 never has one.
    let census = census(text);
    if census.letters < 2 || census.letters < census.other {
        return None;
    }
    Some(translate(text, census.multi_char_letters))
}

/// Replaces every SGA letter in `text` with its Latin letter, longest form first, and
/// copies everything else. `multi_char_letters` is [`Census::multi_char_letters`].
fn translate(text: &str, multi_char_letters: bool) -> String {
    // Every letter is at least as long in UTF-8 as its Latin letter
    let mut decoded = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(c) = rest.chars().next() {
        rest = &rest[c.len_utf8()..];
        let plain = match c {
            T => {
                if let Some(after_dot) = rest.strip_prefix(DOT_BELOW) {
                    // `ℸ̣` has no spaces of its own, so a space after it is a word space
                    rest = after_dot;
                } else if let Some(after_dot) = rest.strip_prefix(SPACE_DOT_BELOW) {
                    // `ℸ ̣` and LingoJam's `ℸ ̣ ` drop the dot and the spaces around it,
                    // so `ℸ ̣ ⍑ᒷ` is `the`
                    rest = after_dot.strip_prefix(' ').unwrap_or(after_dot);
                }
                't'
            }
            // ` ̇/` is x; any other space is a space, so `ᔑ  ̇/∷ᔑ||` is `a xray`
            ' ' => match rest.strip_prefix(DOT_ABOVE_SLASH) {
                Some(after) => {
                    rest = after;
                    'x'
                }
                None => ' ',
            },
            DOT_ABOVE => {
                rest = rest.strip_prefix('/').unwrap_or(rest);
                'x'
            }
            '!' => match rest.strip_prefix(INVERTED_EXCLAMATION) {
                Some(after) => {
                    rest = after;
                    'p'
                }
                None if multi_char_letters => '!',
                None => 'p',
            },
            '|' => match rest.strip_prefix('|') {
                Some(after) => {
                    rest = after;
                    'y'
                }
                None if multi_char_letters => '|',
                None => 'y',
            },
            _ => letter(c).unwrap_or(c),
        };
        decoded.push(plain);
    }
    decoded
}

