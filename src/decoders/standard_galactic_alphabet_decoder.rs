//! Decode the Standard Galactic Alphabet (SGA), the 26-letter alphabet of Commander Keen
//! that Minecraft's enchanting table uses, written with look-alike Unicode characters.
//! Call standard_galactic_alphabet_decoder.crack to use. It returns a `CrackResult` whose
//! `unencrypted_text` is `None` when the input isn't SGA.
//!
//! The table is the one everyone copies, LingoJam's translator, which is also Python
//! Ciphey's (`cipheydists::translate::galactic`). Twenty-two letters are one character:
//!
//! ```text
//! a ᔑ U+1511   b ʖ U+0296   c ᓵ U+14F5   d ↸ U+21B8   e ᒷ U+14B7   f ⎓ U+2393
//! g ⊣ U+22A3   h ⍑ U+2351   i ╎ U+254E   j ⋮ U+22EE   k ꖌ U+A58C   l ꖎ U+A58E
//! m ᒲ U+14B2   n リ U+30EA   o 𝙹 U+1D679  q ᑑ U+1451   r ∷ U+2237   s ᓭ U+14ED
//! u ⚍ U+268D   v ⍊ U+234A   w ∴ U+2234   z ⨅ U+2A05
//! ```
//!
//! The other four are written with ASCII punctuation and combining marks, differently by
//! different tools:
//!
//! ```text
//!     LingoJam                          others                     cipheydists
//! p   !¡    U+0021 U+00A1                                          !
//! t   ℸ ̣    U+2138 U+0020 U+0323 U+0020  ℸ ̣ (U+2138 U+0020 U+0323)  ℸ
//!                                       ℸ̣ (U+2138 U+0323)
//! x    ̇/   U+0020 U+0307 U+002F         ̇/ (U+0307 U+002F)          (none; Python Ciphey
//!                                                                  read a lone U+0307)
//! y   ||    U+007C U+007C                                          |
//! ```
//!
//! Capitals, digits and punctuation aren't letters of the alphabet: LingoJam leaves them
//! alone (`Sꖎ╎↸ᒷ` is `Slide`), and so does this decoder. The letters it outputs are lower
//! case.
//!
//! Known quirk: text written with the cipheydists table (no `!¡`, `||`, ` ̇/` or dotted
//! `ℸ`) can't tell a `!` that is p from an exclamation mark, so `⍑ᒷꖎꖎ𝙹 ∴𝙹∷ꖎ↸!` decodes to
//! `hello worldp`. When the text has any of LingoJam's forms, a lone `!` or `|` is
//! punctuation: `ᓭℸ ̣ 𝙹!¡! ||ᒷᓭ` is `stop! yes`.
//!
//! `𝙹` (U+1D679) is outside the Basic Multilingual Plane, so everything here compares
//! `char`s, never bytes or UTF-16 units. The combining marks don't compose with the
//! characters before them under NFC, so no normalisation is needed.
//!
//! References: Wikipedia <https://en.wikipedia.org/wiki/Commander_Keen#Standard_Galactic_Alphabet>,
//! LingoJam's translator <https://lingojam.com/StandardGalacticAlphabet>, cipheydists'
//! table <https://github.com/Ciphey/CipheyDists/blob/master/cipheydists/translate/galactic.json>
//! and Python Ciphey 5.14.0's decoder
//! <https://github.com/bee-san/Ciphey/blob/5.14.0/ciphey/basemods/Decoders/galactic.py>.

