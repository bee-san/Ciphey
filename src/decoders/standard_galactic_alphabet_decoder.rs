    #[test]
    fn the_table_has_23_one_character_letters() {
        // cipheydists' table, plus `ℸ`; p, x and y are ASCII or combining marks
        let letters: Vec<char> = (0..=0x10FFFF)
            .filter_map(char::from_u32)
            .filter(|&c| letter(c).is_some())
            .collect();
        assert_eq!(letters.len(), 23);
        // All of them are above U+00FF, so the Latin-1 text Hexadecimal makes never has one
        assert!(letters.iter().all(|&c| u32::from(c) > 0xFF));
    }

