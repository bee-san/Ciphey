    /// Encodes lower-case letters the way LingoJam does: `t` is `ℸ ̣ `, `x` is ` ̇/`, `p` is
    /// `!¡` and `y` is `||`. Everything else is kept.
    fn encode_lingojam(plaintext: &str) -> String {
        const SINGLE: &str = "ᔑʖᓵ↸ᒷ⎓⊣⍑╎⋮ꖌꖎᒲリ𝙹 ᑑ∷ᓭ ⚍⍊∴  ⨅";
        plaintext
            .chars()
            .map(|c| match c {
                'p' => "!\u{A1}".to_string(),
                't' => "\u{2138} \u{323} ".to_string(),
                'x' => " \u{307}/".to_string(),
                'y' => "||".to_string(),
                'a'..='z' => SINGLE
                    .chars()
                    .nth(c as usize - 'a' as usize)
                    .unwrap()
                    .to_string(),
                _ => c.to_string(),
            })
            .collect()
    }

    // helper for tests
    fn get_athena_checker() -> CheckerTypes {
        let athena_checker = Checker::<Athena>::new();
        CheckerTypes::CheckAthena(athena_checker)
    }

    // Runs the decoder with the Athena checker and returns the decoded text, if any
    fn crack(text: &str) -> Option<String> {
        let decoder = Decoder::<StandardGalacticAlphabetDecoder>::new();
        let result = decoder.crack(text, &get_athena_checker());
        if result.unencrypted_text.is_none() {
            assert!(!result.success, "{text:?} failed but was marked successful");
        }
        result.unencrypted_text.map(|texts| texts[0].clone())
    }

    // Asserts that Athena accepts what `text` decodes to and returns it
    fn crack_successfully(text: &str) -> String {
        let decoder = Decoder::<StandardGalacticAlphabetDecoder>::new();
        let result = decoder.crack(text, &get_athena_checker());
        assert!(result.success, "Athena should accept {text:?}: {result:?}");
        result.unencrypted_text.unwrap()[0].clone()
    }

