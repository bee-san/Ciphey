    #[test]
    fn census_counts_letters_and_other_characters() {
        assert_eq!(
            census("Hello ∴𝙹∷ꖎ↸!"),
            Census {
                letters: 5,
                other: 5,
                multi_char_letters: false
            }
        );
        // The marks of p, t and x are neither letters nor other characters
        assert_eq!(
            census("ℸ ̣ ⍑ᒷ ⎓𝙹 ̇/ ⋮⚍ᒲ!¡ᓭ"),
            Census {
                letters: 9,
                other: 0,
                multi_char_letters: true
            }
        );
        // A bare U+0307 is the one-character x, not a multi-character letter
        assert!(!census("∴\u{307}|").multi_char_letters);
        assert!(census("∴\u{307}/").multi_char_letters);
        assert!(census("ᒷ||").multi_char_letters);
        assert!(!census("ᒷ|").multi_char_letters);
    }

