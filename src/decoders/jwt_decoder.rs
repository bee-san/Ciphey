    fn get_athena_checker() -> CheckerTypes {
        let athena_checker = Checker::<Athena>::new();
        CheckerTypes::CheckAthena(athena_checker)
    }

    /// Runs the JWT decoder on `text` with the Athena checker
    fn crack(text: &str) -> CrackResult {
        Decoder::<JwtDecoder>::new().crack(text, &get_athena_checker())
    }

    /// Runs the JWT decoder on `text` as if a regex crib was set, with `checker` standing
    /// in for the regex checker (which reads the crib from the global config)
    fn crack_with_crib(text: &str, checker: &CheckerTypes) -> CrackResult {
        let decoder = Decoder::<JwtDecoder>::new();
        let mut results = CrackResult::new(&decoder, text.to_string());
        identify(&mut results, parse(text).expect("not a JWT"), checker, true);
        results
    }

    /// Asserts `text` is decoded to `payload` and accepted as plaintext
    fn assert_decodes_to(text: &str, payload: &str) {
        let result = crack(text);
        assert_eq!(
            result.unencrypted_text,
            Some(vec![payload.to_string()]),
            "{text:?}"
        );
        assert!(result.success, "{text:?} was not accepted: {result:?}");
    }

    /// Asserts the decoder rejects `text` without decoding anything
    fn assert_not_decoded(text: &str) {
        let result = crack(text);
        assert!(!result.success, "{text:?}");
        assert!(result.unencrypted_text.is_none(), "{text:?}: {result:?}");
        assert!(result.key.is_none(), "{text:?}");
    }

