    #[test]
    fn with_a_crib_a_string_value_must_be_identified() {
        // The LemmeKnow checker stands in for the regex checker here
        let checker = CheckerTypes::CheckLemmeKnow(Checker::<LemmeKnow>::new());

        // The flag is a value, so a crib anchored to it doesn't match the whole payload
        let result = crack_with_crib(FLAG, &checker);
        assert!(result.success);
        assert_eq!(result.checker_name, "LemmeKnow Checker");
        assert_eq!(
            result.unencrypted_text,
            Some(vec![FLAG_PAYLOAD.to_string()])
        );

        // Nothing matches, so the token is not accepted on its structure, but the payload
        // is still returned for the search to carry on from
        let result = crack_with_crib(ALG_NONE, &checker);
        assert!(!result.success);
        assert_eq!(result.checker_name, "");
        assert_eq!(
            result.unencrypted_text,
            Some(vec![ALG_NONE_PAYLOAD.to_string()])
        );
    }

    #[test]
    fn string_values_are_bounded() {
        // Values nested more than three deep are skipped, as are numbers and empty strings:
        // {"a":"one","b":{"c":"two","d":{"e":"three","f":{"g":"four"}}},
        //  "h":["five",["six",["seven"]],"",1]}
        let token = parse(
            "eyJhbGciOiJub25lIn0.eyJhIjoib25lIiwiYiI6eyJjIjoidHdvIiwiZCI6eyJlIjoidGhyZWUiLCJmIjp7ImciOiJmb3VyIn19fSwiaCI6WyJmaXZlIixbInNpeCIsWyJzZXZlbiJdXSwiIiwxXX0.",
        )
        .expect("a JWT");
        assert_eq!(
            string_values(&token.claims),
            ["one", "two", "three", "five", "six"]
        );

        // At most MAX_CRIB_VALUES of them
        let claims = (0..MAX_CRIB_VALUES + 8)
            .map(|i| format!("\"k{i}\":\"v{i}\""))
            .collect::<Vec<_>>()
            .join(",");
        let claims = serde_json::from_str(&format!("{{{claims}}}")).unwrap();
        let values = string_values(&claims);
        assert_eq!(values.len(), MAX_CRIB_VALUES);
        assert_eq!(values[0], "v0");
    }

    #[test]
    fn result_can_be_read_back_from_the_cache() {
        // The cache stores results as JSON and looks the decoder and checker up by name
        let result = crack(JWT_IO);
        let json = result.get_json().unwrap();
        let cached: CrackResult = serde_json::from_str(&json).unwrap();
        assert_eq!(cached.decoder, "JWT");
        assert_eq!(cached.checker_name, "JWT Structure");
        assert!(cached.success);
        assert_eq!(cached.key, result.key);
        assert_eq!(cached.unencrypted_text, result.unencrypted_text);
    }

    #[test]
    fn decoder_and_checker_are_registered() {
        let decoders = get_decoder_by_name("JWT");
        assert_eq!(decoders.components.len(), 1);
        assert_eq!(decoders.components[0].get_name(), "JWT");
        assert!(DECODER_MAP.contains_key("JWT"));
        assert!(CHECKER_MAP.contains_key("JWT Structure"));
    }
