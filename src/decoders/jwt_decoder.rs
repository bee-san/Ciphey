//! Decode JSON Web Tokens (JWT, [RFC 7519](https://datatracker.ietf.org/doc/html/rfc7519))
//! in JWS compact serialization
//! ([RFC 7515 §7.1](https://datatracker.ietf.org/doc/html/rfc7515#section-7.1)):
//! `BASE64URL(header).BASE64URL(payload).BASE64URL(signature)`.
//!
//! A JWT is signed, not encrypted, so the header and payload can be read without the key.
//! The payload is returned exactly as it was encoded and the decoded header becomes the
//! result's key. The signature is not verified.
//!
//! The checkers identify hardly any JSON, so a well-formed token is accepted on its
//! structure unless a regex crib is set. `identify` documents the order of the checks.

