/// With a regex crib, at most this many string values of the payload are checked
const MAX_CRIB_VALUES: usize = 32;

/// With a regex crib, string values nested deeper than this are not checked.
/// The payload's own members are at depth 1.
const MAX_CRIB_DEPTH: usize = 3;

/// The JWT decoder, call:
/// `let jwt_decoder = Decoder::<JwtDecoder>::new()` to create a new instance
/// And then call:
/// `result = jwt_decoder.crack(input)` to decode a JWT
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::jwt_decoder::JwtDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_jwt = Decoder::<JwtDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // The example token from jwt.io
/// let token = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiIxMjM0NTY3ODkwIiwibmFtZSI6IkpvaG4gRG9lIiwiaWF0IjoxNTE2MjM5MDIyfQ.SflKxwRJSMeKKF2QT4fwpMeJf36POk6yJV_adQssw5c";
/// let result = decode_jwt.crack(token, &checker);
/// assert!(result.success);
/// assert_eq!(
///     result.unencrypted_text.unwrap()[0],
///     r#"{"sub":"1234567890","name":"John Doe","iat":1516239022}"#
/// );
/// // The decoded header is kept as the key
/// assert_eq!(result.key.unwrap(), r#"{"alg":"HS256","typ":"JWT"}"#);
/// ```
pub struct JwtDecoder;

impl Crack for Decoder<JwtDecoder> {
    fn new() -> Decoder<JwtDecoder> {
        Decoder {
            name: "JWT",
            description: "A JSON Web Token (JWT) in JWS compact serialization is base64url(header).base64url(payload).base64url(signature), where the header and payload are JSON objects. It is signed, not encrypted, so the payload (the claims) can be read without the key. The signature is not verified; the decoded header is returned as the key.",
            link: "https://datatracker.ietf.org/doc/html/rfc7519",
            tags: vec!["jwt", "json", "web", "token", "decoder"],
            popularity: 0.5,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes the payload of a JWT. Text that doesn't start like one is rejected without
    /// further work, so the decoder costs the search next to nothing.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying JWT with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(token) = parse(text) else {
            trace!("Not a JWT: {:?}", text);
            return results;
        };
        identify(&mut results, token, checker, get_config().regex.is_some());

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Marker type for [`jwt_structure_checker`]
pub(crate) struct JwtStructure;

/// The checker named on results that were accepted because the token is well formed: a
/// base64url JSON header with an `alg`, and a base64url JSON payload. Random text can't
/// satisfy that. It's registered in `CHECKER_MAP` so cached results can be read back.
pub(crate) fn jwt_structure_checker() -> Checker<JwtStructure> {
    Checker {
        name: "JWT Structure",
        description: "Well-formed JWT: base64url JSON header with alg + JSON payload",
        link: "https://datatracker.ietf.org/doc/html/rfc7519",
        tags: vec!["jwt", "structure"],
        expected_runtime: 0.0,
        popularity: 0.5,
        lemmeknow_config: Identifier::default(),
        sensitivity: Sensitivity::Medium,
        enhanced_detector: None,
        _phantom: std::marker::PhantomData,
    }
}

/// The decoded parts of a JWT
struct Jwt {
    /// The header JSON, exactly as it was encoded
    header: String,
    /// The payload JSON, exactly as it was encoded
    payload: String,
    /// The payload's members
    claims: Map<String, Value>,
}

/// Parses `text` as a JWS compact serialization whose header and payload are JSON objects
/// and whose header has a string `alg`. Surrounding whitespace and a `Bearer ` prefix are
/// ignored. The cheapest checks come first, so most text is rejected straight away.
fn parse(text: &str) -> Option<Jwt> {
    let token = strip_bearer(text.trim());
    // `eyJ` is base64url for `{"`, which every header starts with
    if !token.starts_with("eyJ") {
        return None;
    }

    // Exactly three parts. A JWE has five, and its payload is encrypted.
    let mut parts = token.split('.');
    let (header, payload, signature) = (parts.next()?, parts.next()?, parts.next()?);
    if parts.next().is_some() {
        return None;
    }
    let header = base64url(header)?;
    let payload = base64url(payload)?;
    // The signature is never decoded, and is empty for `"alg":"none"`
    base64url(signature)?;
    if payload.is_empty() {
        return None;
    }

    let (header, header_fields) = decode_object(header)?;
    if !header_fields.get("alg").is_some_and(Value::is_string) {
        return None;
    }
    let (payload, claims) = decode_object(payload)?;
    Some(Jwt {
        header,
        payload,
        claims,
    })
}

/// `token` without a leading `Bearer ` (the HTTP authentication scheme for these tokens,
/// RFC 6750 §2.1), which is matched case-insensitively
fn strip_bearer(token: &str) -> &str {
    let bytes = token.as_bytes();
    if bytes.len() > 7
        && bytes[..6].eq_ignore_ascii_case(b"bearer")
        && bytes[6].is_ascii_whitespace()
    {
        // The first seven bytes are ASCII, so this slices on a character boundary
        token[7..].trim_start()
    } else {
        token
    }
}

/// `part` without trailing `=` padding, if what's left is base64url (`[A-Za-z0-9_-]*`)
fn base64url(part: &str) -> Option<&str> {
    let part = part.trim_end_matches('=');
    part.bytes()
        .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-' || byte == b'_')
        .then_some(part)
}

/// Decodes a base64url part that holds a JSON object in UTF-8. Returns the JSON text
/// and the parsed object.
fn decode_object(part: &str) -> Option<(String, Map<String, Value>)> {
    let bytes = general_purpose::URL_SAFE_NO_PAD.decode(part).ok()?;
    let json = String::from_utf8(bytes).ok()?;
    let object = serde_json::from_str(&json).ok()?;
    Some((json, object))
}

/// Fills in `results` for a decoded token. Its payload is the plaintext if, in this order:
/// 1. the checker identifies the payload;
/// 2. with a regex crib (`crib`), the checker identifies one of the payload's string
///    values, e.g. a flag that a crib anchored with `^` and `$` matches;
/// 3. without a crib, always, as the token is well formed. The human checker is asked first.
///
/// Step 3 is what lets the search finish on a JWT. It's skipped with a crib, because then
/// only text that matches the crib may end the search.
///
/// The payload is returned either way, so the search can carry on from it.
fn identify(results: &mut CrackResult, token: Jwt, checker: &CheckerTypes, crib: bool) {
    let payload_result = checker.check(&token.payload);
    if counts(&payload_result) {
        results.update_checker(&payload_result);
    } else if crib {
        let value_result = string_values(&token.claims)
            .into_iter()
            .map(|value| checker.check(value))
            .find(counts);
        if let Some(value_result) = value_result {
            results.update_checker(&value_result);
        }
    } else {
        let structure_result = structure_result(&token.payload);
        if human_checker(&structure_result) {
            results.update_checker(&structure_result);
        }
    }

    results.unencrypted_text = Some(vec![token.payload]);
    results.key = Some(token.header);
}

/// Whether a checker's result for the payload or one of its values identifies the
/// plaintext. English-checker hits don't count: the search discards English results that
/// are over a third punctuation, which JSON with short values is, and "JSON Web Token"
/// describes the payload better anyway.
fn counts(result: &CheckResult) -> bool {
    result.is_identified && result.checker_name != Checker::<EnglishChecker>::new().name
}

/// The result for a well-formed token that no checker identified
pub(crate) fn structure_result(payload: &str) -> CheckResult {
    let mut result = CheckResult::new(&jwt_structure_checker());
    result.is_identified = true;
    result.text = payload.to_string();
    result.description = "JSON Web Token".to_string();
    result
}

/// The payload's non-empty string values in document order: at most [`MAX_CRIB_VALUES`] of
/// them, nested at most [`MAX_CRIB_DEPTH`] deep
fn string_values(claims: &Map<String, Value>) -> Vec<&str> {
    let mut strings = Vec::new();
    for value in claims.values() {
        collect_strings(value, 1, &mut strings);
    }
    strings
}

/// Adds the non-empty strings in `value`, which is nested `depth` deep, to `strings`
fn collect_strings<'a>(value: &'a Value, depth: usize, strings: &mut Vec<&'a str>) {
    if strings.len() == MAX_CRIB_VALUES {
        return;
    }
    match value {
        Value::String(string) if !string.is_empty() => strings.push(string),
        Value::Array(items) if depth < MAX_CRIB_DEPTH => {
            for item in items {
                collect_strings(item, depth + 1, strings);
            }
        }
        Value::Object(members) if depth < MAX_CRIB_DEPTH => {
            for member in members.values() {
                collect_strings(member, depth + 1, strings);
            }
        }
        _ => {}
    }
}

