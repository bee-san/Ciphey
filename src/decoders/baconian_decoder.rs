//! Decode Bacon's cipher, also called the Baconian cipher.
//!
//! Each letter is written as a group of five binary symbols, traditionally `A` and `B`.
//! Read as a binary number (`A` = 0, `B` = 1), a group is the letter's index in one of
//! two alphabets:
//!
//! * standard: Bacon's original 24 letters, where I and J share a code, as do U and V,
//! * complete: all 26 letters, one code each.
//!
//! The two symbols can be any pair of characters (`A`/`B`, `a`/`b`, `0`/`1`, ...). They
//! are also often hidden in a cover text, one symbol per letter: lowercase for `A` and
//! uppercase for `B`.
//!
//! The decoder tries both alphabets and both ways of assigning the two symbols, so at
//! most 4 readings per mode, and checks the likeliest first (see `rank_candidates`):
//!
//! * Symbol mode: the input is exactly two distinct symbols in groups of five, with or
//!   without whitespace between groups. A whitespace-separated token longer than one
//!   group is a word, so a message written word by word keeps its spaces.
//! * Case mode: the input looks like a cover text, with the case changing inside words
//!   far more often than in ordinary writing. The case of ordinary text decodes to
//!   junk, so only a candidate the checker accepts is returned.
//!
//! References: <https://en.wikipedia.org/wiki/Bacon%27s_cipher>,
//! <https://www.dcode.fr/bacon-cipher> and CyberChef's "Bacon Cipher Decode".

