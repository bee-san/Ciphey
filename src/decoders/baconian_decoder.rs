    #[test]
    fn decodes_letter_case() {
        assert_cracks(HELLO_IN_CASE, "HELLO", "complete, lowercase=A uppercase=B");
        let candidates: Vec<String> = case_mode_candidates(HELLO_IN_CASE)
            .into_iter()
            .map(|c| c.text)
            .collect();
        // CyberChef's Standard reading is HEMMPAA. Swapped, the padding would be
        // BBBBB, which is why it is dropped before swapping.
        assert_eq!(candidates, ["HEMMP", "HELLO"]);
    }

    #[test]
    fn decodes_letter_case_with_uppercase_as_a() {
        // HELLO_IN_CASE's message the other way round: uppercase = A, lowercase = B.
        // CyberChef reads it as HELLO?? with the Case translation and Invert Translation.
        assert_cracks(
            "THe quICk BROwN foX jUmpS oveR the lazy dog",
            "HELLO",
            "complete, uppercase=A lowercase=B",
        );
    }

    #[test]
    fn symbol_mode_rejects_invalid_input() {
        for text in [
            "",
            " \n\t ",
            // One symbol
            "BBBBB BBBBB BBBBB",
            // Three symbols
            "ABCAB AAAAA BBBBB",
            // Not a whole group
            "AABB",
            "AABBB AABA",
            "AABBB AABAA ABABA ABABA ABBA",
            // Fewer than 3 groups
            "AABBB AABAA",
            // A token that isn't a whole number of groups, though the total is
            "AABBBA ABAAA BABAA BABAA BBAB",
            // 8-bit binary
            "01101000 01100101 01101100 01101100 01101111",
            "😀",
            "The quick brown fox jumps over the lazy dog",
        ] {
            assert!(
                scan_symbols(text).is_none(),
                "{text:?} passed the pre-check"
            );
            assert!(symbol_mode_candidates(text).is_empty(), "{text:?}");
        }
    }

    #[test]
