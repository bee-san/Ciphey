//! Decode Cisco IOS type 7 passwords, the `password 7 …` and `key 7 …` of a router or switch
//! config.
//!
//! A type 7 string is two decimal digits, the offset, and then the password in hex. Byte `i`
//! of the password is XORed with byte `(offset + i) % 53` of a fixed 53-byte key:
//!
//! ```text
//! 02050D480809   offset 2, then 0x05 ^ 'f' = 'c', 0x0D ^ 'd' = 'i', 0x48 ^ ';' = 's', ...: cisco
//! ```
//!
//! What is decoded:
//!
//! - offsets 00 to 15: every known vector has one, and passlib only generates those. Higher
//!   offsets would read the hex of ordinary text as type 7 (the hex of `Hello` is
//!   `48656C6C6F`, offset 48); with 15 at most, the first byte of such hex would have to be a
//!   control character;
//! - hex digits in either case (IOS writes upper case);
//! - the type 7 string alone, or after `password 7` or `key 7` as in a config line;
//! - passwords of at least 3 characters of printable ASCII. Type 7 is used for ASCII
//!   passwords (how IOS encodes other characters isn't known), and a search drops shorter
//!   results;
//! - not hex of only 0s and 1s: that is binary written without spaces (`0110100001101001`),
//!   and XORing the key with those pairs leaves all but two of its bytes printable.
//!
//! The password is handed on to the search whether or not the checker takes it for plaintext,
//! as the Citrix CTX1 decoder does: a password is rarely English (`Sup3rS3cret!`), and it may
//! be encoded again.
//!
//! References: <https://passlib.readthedocs.io/en/stable/lib/passlib.hash.cisco_type7.html>
//! (the key and the offsets), <https://en.wikipedia.org/wiki/Cisco_IOS#Security_and_vulnerabilities>.

use crate::checkers::CheckerTypes;
use crate::decoders::interface::check_string_success;

use super::crack_results::CrackResult;
use super::interface::Crack;
use super::interface::Decoder;

use log::{debug, trace};

/// The Cisco Type 7 decoder, call:
/// `let cisco_type7_decoder = Decoder::<CiscoType7Decoder>::new()` to create a new instance
/// And then call:
/// `result = cisco_type7_decoder.crack(input)` to decode a Cisco type 7 password
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::cisco_type7_decoder::CiscoType7Decoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_cisco_type7 = Decoder::<CiscoType7Decoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// let result = decode_cisco_type7.crack("02050D480809", &checker);
/// assert!(result.success);
/// assert_eq!(result.unencrypted_text.unwrap()[0], "cisco");
/// ```
pub struct CiscoType7Decoder;

/// The key every type 7 password is XORed with
const KEY: &[u8; 53] = b"dsfd;kfoA,.iyewrkldJKDHSUBsgvca69834ncxv9873254k;fg87";

/// The highest offset of any known vector, and of those passlib generates
const MAX_OFFSET: usize = 15;

/// Shorter passwords can't be a search result
const MIN_PASSWORD_LEN: usize = 3;

impl Crack for Decoder<CiscoType7Decoder> {
    fn new() -> Decoder<CiscoType7Decoder> {
        Decoder {
            name: "Cisco Type 7",
            description: "Cisco IOS type 7 passwords, as in `password 7 02050D480809`: two decimal digits give an offset into a fixed 53-byte key, and the rest is the password XORed with the key from there, in hex. It only hides passwords from someone reading the config.",
            link: "https://en.wikipedia.org/wiki/Cisco_IOS#Security_and_vulnerabilities",
            tags: vec!["cisco_type7", "cisco", "passwords", "decoder"],
            popularity: 0.3,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` if it is a type 7 password of printable ASCII, and returns the password
    /// whether or not the checker identifies it.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Cisco Type 7 with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(password) = decode_type7(text) else {
            debug!("Not a Cisco type 7 password of printable ASCII");
            return results;
        };
        if !check_string_success(&password, text) {
            return results;
        }

        let checker_result = checker.check(&password);
        results.unencrypted_text = Some(vec![password]);
        results.update_checker(&checker_result);
        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// The type 7 string in `text`: all of it, or what follows `password 7` or `key 7`, the way a
/// config line writes it.
fn type7_string(text: &str) -> Option<&str> {
    let mut words = text.split_ascii_whitespace();
    let first = words.next()?;
    match (words.next(), words.next(), words.next()) {
        (None, _, _) => Some(first),
        (Some("7"), Some(encoded), None)
            if first.eq_ignore_ascii_case("password") || first.eq_ignore_ascii_case("key") =>
        {
            Some(encoded)
        }
        _ => None,
    }
}

/// Decodes the type 7 password in `text` (see [`type7_string`]) if it has an offset of 15 or
/// less and is at least [`MIN_PASSWORD_LEN`] characters of printable ASCII. Nothing is checked.
fn decode_type7(text: &str) -> Option<String> {
    let encoded = type7_string(text)?.as_bytes();
    if encoded.len() < 2 + 2 * MIN_PASSWORD_LEN || !encoded.len().is_multiple_of(2) {
        return None;
    }
    let offset = match encoded[..2] {
        [tens @ b'0'..=b'9', ones @ b'0'..=b'9'] => usize::from((tens - b'0') * 10 + (ones - b'0')),
        _ => return None,
    };
    if offset > MAX_OFFSET {
        return None;
    }
    // Binary written without spaces fits the format too: 8-bit binary of ASCII starts `00` or
    // `01`, 7-bit binary `01`, `10` or `11`. Its pairs are the bytes 0x00, 0x01, 0x10 and 0x11,
    // which keep every key byte printable except `o` with 0x10 and `n` with 0x11, so 467 of
    // 2,000 English phrases written as 8-bit binary decoded to printable junk. A password only
    // gives such pairs if it is the key with bits flipped.
    if encoded[2..]
        .iter()
        .all(|&digit| matches!(digit, b'0' | b'1'))
    {
        return None;
    }
    // The length is even, so nothing is left over
    let (pairs, _) = encoded[2..].as_chunks::<2>();
    pairs
        .iter()
        .enumerate()
        .map(|(i, &[high, low])| {
            let byte = ((hex_value(high)? << 4) | hex_value(low)?) ^ KEY[(offset + i) % KEY.len()];
            matches!(byte, b' '..=b'~').then_some(char::from(byte))
        })
        .collect()
}

/// The value of a hex digit, in either case.
fn hex_value(digit: u8) -> Option<u8> {
    match digit {
        b'0'..=b'9' => Some(digit - b'0'),
        b'a'..=b'f' => Some(digit - b'a' + 10),
        b'A'..=b'F' => Some(digit - b'A' + 10),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::{decode_type7, CiscoType7Decoder, KEY};
    use crate::{
        checkers::{
            athena::Athena,
            checker_type::{Check, Checker},
            CheckerTypes,
        },
        decoders::{
            crack_results::CrackResult,
            interface::{Crack, Decoder},
        },
        filtration_system::get_decoder_by_name,
    };

    // Every vector here was made or decoded with PyPI passlib 1.7.4's cisco_type7
    // (`cisco_type7.using(salt=offset).hash(password)` and `cisco_type7.decode(text)`).

    fn get_athena_checker() -> CheckerTypes {
        let athena_checker = Checker::<Athena>::new();
        CheckerTypes::CheckAthena(athena_checker)
    }

    fn crack(text: &str) -> CrackResult {
        Decoder::<CiscoType7Decoder>::new().crack(text, &get_athena_checker())
    }

    fn assert_no_candidate(text: &str) {
        assert_eq!(decode_type7(text), None, "{text:?}");
        let result = crack(text);
        assert!(result.unencrypted_text.is_none(), "{text:?}: {result:?}");
        assert!(!result.success);
    }

    /// Encodes `password` as type 7 from `offset`, the way passlib does
    fn encode(password: &str, offset: usize) -> String {
        let hex: String = password
            .bytes()
            .enumerate()
            .map(|(i, byte)| format!("{:02X}", byte ^ KEY[(offset + i) % KEY.len()]))
            .collect();
        format!("{offset:02}{hex}")
    }

    #[test]
    fn issue_examples_decode() {
        // https://github.com/bee-san/Ciphey/issues/949: Athena doesn't take this password
        // for plaintext, so it is handed on to the search unconfirmed
        let result = crack("073C345C1D1B2A5614000E1845");
        assert_eq!(
            result.unencrypted_text.as_deref(),
            Some(&["Sup3rS3cret!".to_string()][..])
        );
        // The published vector, a common password
        let result = crack("02050D480809");
        assert!(result.success, "{result:?}");
        assert_eq!(
            result.unencrypted_text.as_deref(),
            Some(&["cisco".to_string()][..])
        );
    }

    #[test]
    fn published_vectors_decode() {
        // passlib's test vectors (passlib/tests/test_handlers_cisco.py) and Wikipedia's example
        for (text, password) in [
            ("04480E051A33490E", "secure "),
            (
                "153B1F1F443E22292D73212D5300194315591954465A0D0B59",
                "Its time to go to lunch!",
            ),
            ("08351F1B1D431516475E1B54382F", "t35t:pa55w0rd"),
            ("020E0D7206320A325847071E5F5E", "hiImTesting:)"),
            ("060506324F41584B56", "cisco123"),
            ("1511021F07257A767B", "cisco123"),
            ("06351A3149085123301517391C501918", "Supe&8ZUbeRp4SS"),
            ("0822455D0A16", "cisco"),
            ("0832585B1910010713181F", "stupidpass"),
        ] {
            assert_eq!(decode_type7(text).as_deref(), Some(password), "{text}");
        }
    }

    #[test]
    fn lower_case_hex_decodes() {
        assert_eq!(decode_type7("02050d480809").as_deref(), Some("cisco"));
        assert_eq!(decode_type7("02050D480809").as_deref(), Some("cisco"));
    }

    #[test]
    fn long_passwords_wrap_around_the_key() {
        // 61 characters from offset 15 use key bytes 15 to 75, so the key repeats after 52
        let text = "15260309443B3E2D2B3875200108010D41505640135E1B0E080519574156401540035E460B594D1D53020B5C47460E264D4707590419164B0D032B222A69";
        assert_eq!(
            decode_type7(text).as_deref(),
            Some("The quick brown fox jumps over the lazy dog, again and again!")
        );
        // Every offset, around the key several times
        let plaintext: String = (b' '..=b'~').map(char::from).collect::<String>().repeat(3);
        for offset in 0..=15 {
            assert_eq!(
                decode_type7(&encode(&plaintext, offset)).as_deref(),
                Some(plaintext.as_str()),
                "offset {offset}"
            );
        }
    }

    #[test]
    fn config_line_prefixes_are_skipped() {
        for text in [
            "password 7 02050D480809",
            "key 7 02050D480809",
            "  PASSWORD   7\t02050D480809\n",
            "Key 7 02050d480809",
        ] {
            assert_eq!(decode_type7(text).as_deref(), Some("cisco"), "{text:?}");
        }
    }

    #[test]
    fn other_config_lines_are_not_read() {
        // Type 5 is an MD5 hash and type 0 is plain text: neither is decoded here
        assert_no_candidate("password 5 02050D480809");
        assert_no_candidate("password 0 cisco");
        assert_no_candidate("secret 7 02050D480809");
        assert_no_candidate("password 7");
        assert_no_candidate("password 7 02050D480809 extra");
        assert_no_candidate("02050D480809 02050D480809");
    }

    #[test]
    fn offsets_above_15_are_rejected() {
        // passlib decodes offsets up to 52, but every known vector is 0 to 15
        assert_no_candidate(&encode("cisco", 16));
        assert_no_candidate(&encode("cisco", 52));
        // passlib's two rejected hashes: offset 99, and an offset in hex
        assert_no_candidate("99400E4812");
        assert_no_candidate("0A480E051A33490E");
    }

    #[test]
    fn hex_of_text_is_never_read_as_type7() {
        // The hex of a text starts with its first character, 20 to 7E for printable ASCII:
        // never an offset of 15 or less
        for first in b' '..=b'~' {
            let hex = format!("{first:02X}6F6F6F6F");
            assert_no_candidate(&hex);
            assert_no_candidate(&hex.to_lowercase());
        }
        // Hexadecimal's bench input, "Meet me at the old lighthouse ..."
        assert_no_candidate("4d656574206d6520617420746865206f6c64206c69676874686f757365");
    }

    #[test]
    fn unspaced_binary_is_not_read_as_type7() {
        // The two unspaced-binary inputs of tests/data/ctf_corpus.json, which decode to
        // printable junk without the rule (`cfe:{f~@=/ixuvbj}t[KUHSTR...`)
        assert_no_candidate(
            "01100001011000110111010001100110011110110011000001101110011001010101111101110100",
        );
        assert_no_candidate(
            "01000011010101000100011001111011010000100110100101110100010111110100011001101100",
        );
        // 8-bit and 7-bit binary of English, without spaces
        for text in [
            "hello world",
            "Meet me at the old lighthouse",
            "attack at dawn",
        ] {
            let eight: String = text.bytes().map(|byte| format!("{byte:08b}")).collect();
            let seven: String = text.bytes().map(|byte| format!("{byte:07b}")).collect();
            assert_no_candidate(&eight);
            assert_no_candidate(&seven);
        }
        // A 0 or 1 among other hex digits is fine
        assert_eq!(decode_type7("0822455D0A16").as_deref(), Some("cisco"));
    }

    #[test]
    fn short_passwords_are_rejected() {
        assert_no_candidate("0822");
        assert_no_candidate("082245");
        assert_eq!(decode_type7("0822455D").as_deref(), Some("cis"));
    }

    #[test]
    fn unprintable_and_non_ascii_passwords_are_rejected() {
        // 0xFF XOR any key byte is above 0x7E
        assert_no_candidate("07FFFFFFFFFF");
        // A tab: 0x09 XOR key byte 2 ('f')
        assert_no_candidate(&format!("02{:02X}0D480809", b'\t' ^ b'f'));
        // passlib's UTF-8 vector: IOS passwords are ASCII
        assert_no_candidate("0958EDC8A9F495F6F8A5FD");
    }

    #[test]
    fn malformed_input_is_rejected() {
        // An odd number of hex digits, and a digit that isn't hex
        assert_no_candidate("02050D48080");
        assert_no_candidate("02050D48080G");
        assert_no_candidate("02050D4808+9");
        assert_no_candidate("02 050D480809");
    }

    #[test]
    fn handles_panic_if_empty_string() {
        assert_no_candidate("");
        assert_no_candidate("   ");
    }

    #[test]
    fn handles_panic_if_one_character() {
        assert_no_candidate("0");
        assert_no_candidate("7");
    }

    #[test]
    fn handles_panic_if_emoji() {
        assert_no_candidate("😂");
        assert_no_candidate("07😂😂😂");
        // Full-width digits aren't ASCII digits
        assert_no_candidate("０２050D480809");
    }

    #[test]
    fn huge_input() {
        let plaintext = "Meet me at the old lighthouse after midnight. ".repeat(10_000);
        assert_eq!(
            decode_type7(&encode(&plaintext, 9)).as_deref(),
            Some(plaintext.as_str())
        );
        // Rejected at its first byte
        assert_no_candidate(&format!("07{}", "FF".repeat(500_000)));
    }

    #[test]
    fn junk_gives_no_candidates() {
        for text in [
            // benches/data/decoders.toml's miss input
            "T00 l3= ox+#G WKyV pajU6j qxH@ %B4+a 5Pn^ 7p_v1q 9sLvu *+36i R5rL&3 mVJZI iO0 Ut8_m COTV",
            "hello my name is panicky mc panic face!",
            "TWVldCBtZSBhdCB0aGUgb2xkIGxpZ2h0aG91c2U=",
            "104 101 108 108 111",
            "MNGIKIANMEGBKIANMHGCOHECJADFPPFKINCIOBEEIFCA",
        ] {
            assert_no_candidate(text);
        }
    }

    #[test]
    fn registered_once() {
        let decoders = get_decoder_by_name("Cisco Type 7");
        assert_eq!(decoders.components.len(), 1);
        assert_eq!(decoders.components[0].get_name(), "Cisco Type 7");
        assert!(decoders.components[0].get_tags().contains(&"decoder"));
        assert!(crate::decoders::DECODER_MAP.contains_key("Cisco Type 7"));
    }
}
