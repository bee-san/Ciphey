//! Decode tap code (knock code), such as `2,3 1,5 3,1 3,1 3,4` or
//! `.. ...  . .....  ... .  ... .  ... ....` for `HELLO`.
//! Call tap_code_decoder.crack to use. It returns a `CrackResult` whose `unencrypted_text` is
//! `None` when the input isn't tap code.
//!
//! Tap code sends each letter as two groups of taps: the row, then the column of the letter in
//! this 5×5 square. K has no cell of its own and is sent as C, so it decodes as C.
//!
//! ```text
//!       1 2 3 4 5
//!   1   A B C D E
//!   2   F G H I J
//!   3   L M N O P
//!   4   Q R S T U
//!   5   V W X Y Z
//! ```
//!
//! Two ways of writing it are decoded:
//! * Digit pairs, `row,col`: `2,3` is H. One space or tab separates letters; two or more, a
//!   line break, `/` or `|` separate words.
//! * Knocks: runs of one repeated symbol that isn't a letter or a digit, such as `.`, `•` or
//!   `*`, so `.. ...` is H. The narrowest gap separates the row from the column and the next
//!   one separates letters. A third, wider gap, a line break, `/` or `|` separates words.
//!
//! When every word is a single letter, the word gaps were letter gaps (`.. ... / . ..... /
//! ...`, `2,3  1,5  3,1`) and the letters are joined without spaces. The output is upper case.
//!
//! Digits without commas (`23 15 31`, `231531`) are Polybius square coordinates, not tap code,
//! and are left alone. So are knocks written with a letter or digit (`xx xxx`) and taps
//! written one at a time with spaces between them (`. .  . . .`).

