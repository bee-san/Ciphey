    #[test]
    fn fails_on_spaced_single_taps() {
        // dCode's pseudo-code puts a space between taps, so every group is one tap. The first
        // spells H, E, L with an odd number of taps; the second spells T, E, A with an even
        // number, which would otherwise pair up as eight As.
        assert_eq!(crack(". .  . . .  .  . . . . .  . . .  ."), None);
        assert_eq!(crack(". . . .  . . . .  .  . . . . .  .  ."), None);
        assert_eq!(crack(". .  . .  . ."), None);
    }

