/// The Tap Code decoder, call:
/// `let tap_code_decoder = Decoder::<TapCodeDecoder>::new()` to create a new instance
/// And then call:
/// `result = tap_code_decoder.crack(input)` to decode tap code
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::tap_code_decoder::TapCodeDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_tap_code = Decoder::<TapCodeDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// let result = decode_tap_code
///     .crack("2,3 1,5 3,1 3,1 3,4  5,2 3,4 4,2 3,1 1,4", &checker)
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "HELLO WORLD");
///
/// // The same letters as knocks
/// let result = decode_tap_code
///     .crack(".. ...  . .....  ... .  ... .  ... ....", &checker)
///     .unencrypted_text;
/// assert_eq!(result.unwrap()[0], "HELLO");
/// ```
pub struct TapCodeDecoder;

/// The square, row by row. K shares C's cell, so it isn't here.
const SQUARE: &[u8; 25] = b"ABCDEFGHIJLMNOPQRSTUVWXYZ";

/// The most taps in a group: the square has five rows and five columns.
const MAX_TAPS: u8 = 5;

/// Fewer letters than this are too likely to be something else, like the coordinates `2,3`.
const MIN_LETTERS: usize = 3;

impl Crack for Decoder<TapCodeDecoder> {
    fn new() -> Decoder<TapCodeDecoder> {
        Decoder {
            name: "Tap Code",
            description: "Tap code (knock code) sends each letter as two groups of taps, the row and column of a 5×5 Polybius square with K folded into C; written as `2,3` pairs or runs of dots.",
            link: "https://en.wikipedia.org/wiki/Tap_code",
            tags: vec!["tap_code", "knock", "polybius", "substitution", "decoder"],
            popularity: 0.3,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` as tap code and checks the result with `checker`.
    /// `unencrypted_text` is `None` when `text` isn't tap code.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Tap Code with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(decoded_text) = decode_tap_code(text) else {
            debug!("Failed to decode Tap Code because the text isn't tap code");
            return results;
        };
        trace!("Decoded text for Tap Code: {:?}", decoded_text);

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Tap Code because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Decodes tap code to upper-case text, or returns `None` if `text` isn't tap code.
fn decode_tap_code(text: &str) -> Option<String> {
    let body = text.trim();
    // The first character picks the notation, and turns away almost every other input: text,
    // Base64, hex, A1Z26, decimal and Polybius digits all fail here.
    let first = body.chars().next()?;
    if matches!(first, '1'..='5') && body.as_bytes().get(1) == Some(&b',') {
        decode_digit_pairs(body)
    } else if is_knock_symbol(first) {
        decode_knocks(body, first)
    } else {
        None
    }
}

/// Whether `c` can stand for one tap. Letters and digits would make ordinary words and numbers
/// look like knocks, and `,`, `/` and `|` are separators.
fn is_knock_symbol(c: char) -> bool {
    !c.is_ascii_alphanumeric() && !c.is_whitespace() && !matches!(c, ',' | '/' | '|')
}

/// Decodes `row,col` digit pairs such as `2,3 1,5 3,1 3,1 3,4  5,2 3,4 4,2 3,1 1,4`.
fn decode_digit_pairs(body: &str) -> Option<String> {
    let mut plaintext = Plaintext::with_capacity(body.len() / 3);
    let mut chars = body.chars().peekable();
    loop {
        let row = coordinate(chars.next()?)?;
        if chars.next()? != ',' {
            return None;
        }
        let col = coordinate(chars.next()?)?;
        plaintext.push(row, col);

        let gap = take_gap(&mut chars);
        if chars.peek().is_none() {
            break;
        }
        if gap.is_empty() {
            // Something other than a separator straight after a pair, as in `1,2,3` or `2,31,5`
            return None;
        }
        if gap.hard || gap.width >= 2 {
            plaintext.end_word();
        }
    }
    plaintext.finish()
}

/// The coordinate a digit stands for, if it is 1 to 5.
fn coordinate(c: char) -> Option<u8> {
    match c {
        '1'..='5' => Some(c as u8 - b'0'),
        _ => None,
    }
}

/// Decodes groups of `symbol`, such as `.. ...  . .....  ... .  ... .  ... ....`.
fn decode_knocks(body: &str, symbol: char) -> Option<String> {
    // First pass: every character is the symbol or a separator, no group has more than five
    // taps, and how wide the gaps are.
    let mut widths = NarrowestWidths::default();
    let mut most_taps = 0;
    for knock in Knocks::new(body, symbol) {
        match knock? {
            Knock::Taps(taps) => most_taps = most_taps.max(taps),
            Knock::Gap(gap) if !gap.hard => widths.insert(gap.width),
            Knock::Gap(_) => {}
        }
    }
    if most_taps == 1 {
        // Nothing but single taps would only spell AAA..., so these are taps written one at a
        // time with spaces between them (`. .  . . .`), which this decoder doesn't read
        return None;
    }
    // The narrowest gap is inside a letter and the next one between letters. Only a third,
    // wider one can separate words: `.. ...  . .....   ..... ..` is two words, while
    // Wikipedia's `•• •••   • •••••` (one and three spaces) is one.
    let word_gap = widths.third();

    // Second pass: pair the groups into letters, word by word
    let mut plaintext = Plaintext::with_capacity(body.len() / 3);
    let mut row = None;
    for knock in Knocks::new(body, symbol) {
        match knock? {
            Knock::Taps(taps) => match row.take() {
                None => row = Some(taps),
                Some(row) => plaintext.push(row, taps),
            },
            Knock::Gap(gap) => {
                if gap.hard || word_gap.is_some_and(|width| gap.width >= width) {
                    if row.is_some() {
                        // A word with an odd number of groups
                        return None;
                    }
                    plaintext.end_word();
                }
            }
        }
    }
    if row.is_some() {
        return None;
    }
    plaintext.finish()
}

/// A run of separators: whitespace, `/` and `|`.
#[derive(Clone, Copy, Debug, PartialEq)]
struct Gap {
    /// Spaces, tabs and other whitespace that isn't a line break.
    width: usize,
    /// Whether the run holds a line break, `/` or `|`, which always separate words.
    hard: bool,
}

impl Gap {
    /// Whether there was no separator at all.
    fn is_empty(self) -> bool {
        self.width == 0 && !self.hard
    }
}

/// Whether `c` always separates words: a line break, `/` or `|`.
fn is_hard_separator(c: char) -> bool {
    matches!(
        c,
        '/' | '|' | '\n' | '\r' | '\u{0B}' | '\u{0C}' | '\u{85}' | '\u{2028}' | '\u{2029}'
    )
}

/// Takes the separators at the front of `chars`.
fn take_gap(chars: &mut Peekable<Chars>) -> Gap {
    let mut gap = Gap {
        width: 0,
        hard: false,
    };
    while let Some(&c) = chars.peek() {
        if is_hard_separator(c) {
            gap.hard = true;
        } else if c.is_whitespace() {
            // Copied from a web page, the gaps can be no-break spaces
            gap.width += 1;
        } else {
            break;
        }
        chars.next();
    }
    gap
}

/// One piece of knock notation.
#[derive(Debug, PartialEq)]
enum Knock {
    /// A group of one to five taps.
    Taps(u8),
    /// The separators after a group.
    Gap(Gap),
}

/// Splits knock notation into groups of taps and the gaps between them. Yields `None`, and
/// then stops, at a character that is neither the symbol nor a separator, or at a group of six
/// or more taps.
struct Knocks<'a> {
    /// What is left of the text.
    chars: Peekable<Chars<'a>>,
    /// The character that stands for one tap.
    symbol: char,
    /// Whether the text turned out not to be knocks.
    failed: bool,
}

impl<'a> Knocks<'a> {
    /// Splits `body`, in which `symbol` stands for one tap.
    fn new(body: &'a str, symbol: char) -> Self {
        Knocks {
            chars: body.chars().peekable(),
            symbol,
            failed: false,
        }
    }

    /// Ends the iteration with a `None` item.
    fn fail(&mut self) -> Option<Option<Knock>> {
        self.failed = true;
        Some(None)
    }
}

impl Iterator for Knocks<'_> {
    type Item = Option<Knock>;

    fn next(&mut self) -> Option<Option<Knock>> {
        if self.failed {
            return None;
        }
        if self.chars.peek()? == &self.symbol {
            let mut taps = 0;
            while self.chars.next_if_eq(&self.symbol).is_some() {
                taps += 1;
                if taps > MAX_TAPS {
                    return self.fail();
                }
            }
            return Some(Some(Knock::Taps(taps)));
        }
        let gap = take_gap(&mut self.chars);
        if gap.is_empty() {
            return self.fail();
        }
        Some(Some(Knock::Gap(gap)))
    }
}

/// The three narrowest gap widths seen, narrowest first. Equal widths count once.
#[derive(Default)]
struct NarrowestWidths([Option<usize>; 3]);

impl NarrowestWidths {
    /// Records a gap of `width`.
    fn insert(&mut self, mut width: usize) {
        for slot in &mut self.0 {
            match *slot {
                None => {
                    *slot = Some(width);
                    return;
                }
                Some(seen) if seen == width => return,
                // Keep the narrower one here and move the wider one along
                Some(seen) if width < seen => *slot = Some(std::mem::replace(&mut width, seen)),
                Some(_) => {}
            }
        }
    }

    /// The third narrowest width, if there were three different ones.
    fn third(&self) -> Option<usize> {
        self.0[2]
    }
}

/// The decoded letters, word by word.
struct Plaintext {
    /// The letters, with one space between words.
    text: String,
    /// Letters so far.
    letters: usize,
    /// Letters in the current word.
    letters_in_word: usize,
    /// Letters in the longest word.
    longest_word: usize,
    /// Whether the next letter starts a new word.
    space_pending: bool,
}

impl Plaintext {
    /// An empty plaintext with room for `capacity` bytes.
    fn with_capacity(capacity: usize) -> Self {
        Plaintext {
            text: String::with_capacity(capacity),
            letters: 0,
            letters_in_word: 0,
            longest_word: 0,
            space_pending: false,
        }
    }

    /// Adds the letter at `row` and `col`, both 1 to 5, to the current word.
    fn push(&mut self, row: u8, col: u8) {
        if self.space_pending {
            self.text.push(' ');
            self.space_pending = false;
        }
        let cell = usize::from(row - 1) * 5 + usize::from(col - 1);
        self.text.push(char::from(SQUARE[cell]));
        self.letters += 1;
        self.letters_in_word += 1;
        self.longest_word = self.longest_word.max(self.letters_in_word);
    }

    /// Ends the current word.
    fn end_word(&mut self) {
        if self.letters_in_word > 0 {
            self.space_pending = true;
            self.letters_in_word = 0;
        }
    }

    /// The decoded text, or `None` if it is too short to be tap code.
    fn finish(mut self) -> Option<String> {
        if self.letters < MIN_LETTERS {
            return None;
        }
        if self.longest_word == 1 {
            // Every word is one letter, so the word gaps were really letter gaps
            self.text.retain(|c| c != ' ');
        }
        Some(self.text)
    }
}

