    fn assert_identified(text: &str, expected: &str) {
        let decoder = Decoder::<TapCodeDecoder>::new();
        let result = decoder.crack(text, &get_athena_checker());
        assert_eq!(
            result.unencrypted_text.as_deref(),
            Some(&[expected.to_string()][..]),
            "{text:?}"
        );
        assert!(result.success, "Athena should accept {expected:?}");
    }

