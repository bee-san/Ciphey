//! Crack single-byte XOR.
//!
//! Every byte of the plaintext is XORed with the same key byte (1 to 255), and the result
//! is usually written out as hex or Base64. It is the first "crypto" step of many CTFs
//! (Cryptopals set 1 challenge 3) and common in malware string obfuscation.
//! There are only 255 keys, so the cracker tries all of them, ranks each output by
//! English byte frequency and sends the best 5 to the checker.
//!
//! Ciphey passes text between decoders as `String`s, and the Base64 decoder drops output
//! that isn't UTF-8, so XORed bytes rarely survive an earlier decoder. Like CyberChef's
//! Magic, this cracker therefore decodes hex and Base64 itself, and also reads text that
//! an earlier decoder produced from raw bytes. Ordinary text has none of these "byte
//! views", so for it the cracker costs one scan of the text.
//! Uses Low sensitivity for gibberish detection.

