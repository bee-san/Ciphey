use log::{debug, trace};

/// A byte view shorter than this is not cracked: there is too little text to rank keys.
const MIN_BYTES: usize = 8;

/// A byte view with fewer distinct byte values than this is not cracked. XOR maps distinct
/// bytes to distinct bytes, so it can only turn such a view into text over a tiny alphabet,
/// such as the "eddedde..." that binary digits give. That text outscores English, but no
/// checker accepts it.
const MIN_DISTINCT_BYTES: usize = 5;

/// Keys are ranked on at most this many bytes of a view.
const RANK_BYTES: usize = 512;

/// A key whose output scores below this is not a candidate.
const MIN_SCORE: f32 = -6.5;

/// How many candidates are sent to the checker.
const MAX_CHECKED: usize = 5;

/// When the checker identifies no candidate, the best one is still handed to the search if
/// it scores at least this and contains a space: English the checker missed, or English
/// under another cipher.
const UNCONFIRMED_MIN_SCORE: f32 = -4.0;

/// The shortest text read as Base64 by the Base64 view.
const MIN_BASE64_VIEW_CHARS: usize = 12;

/// The shortest candidate that counts as the Base64 next layer of a chain.
const MIN_BASE64_LAYER_CHARS: usize = 16;

/// English letter frequencies in percent, `a` to `z`.
const LETTER_PERCENT: [f32; 26] = [
    8.17, 1.49, 2.78, 4.25, 12.70, 2.23, 2.02, 6.09, 6.97, 0.15, 0.77, 4.03, 2.41, 6.75, 7.51,
    1.93, 0.10, 5.99, 6.33, 9.06, 2.76, 0.98, 2.36, 0.15, 1.97, 0.07,
];

/// Bytes other than letters and space that are common in English text. They share 3% of
/// the probability mass.
const COMMON_SYMBOLS: &[u8; 24] = b".,'\"!?;:-()0123456789\n\t\r";

/// Log-probability of each byte in English text. A text's score is the mean of these over
/// its bytes, so English scores about -3.4 to -3.8 and Base64 about -5.5.
static BYTE_WEIGHTS: Lazy<[f32; 256]> = Lazy::new(|| {
    let mut weights = [1e-6_f32.ln(); 256];
    for (offset, percent) in LETTER_PERCENT.iter().enumerate() {
        let frequency = percent / 100.0;
        weights[usize::from(b'a') + offset] = (0.82 * frequency).ln();
        weights[usize::from(b'A') + offset] = (0.82 * frequency * 0.15).ln();
    }
    weights[usize::from(b' ')] = 0.15_f32.ln();
    let symbol_weight = (0.03_f32 / COMMON_SYMBOLS.len() as f32).ln();
    for &symbol in COMMON_SYMBOLS {
        weights[usize::from(symbol)] = symbol_weight;
    }
    weights
});

/// The single-byte XOR cracker, call:
/// `let xor_decoder = Decoder::<XorSingleByteDecoder>::new()` to create a new instance
/// And then call:
/// `result = xor_decoder.crack(input, &checker)` to crack hex, Base64 or raw bytes.
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::xor_single_byte_decoder::XorSingleByteDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decoder = Decoder::<XorSingleByteDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // Cryptopals set 1 challenge 3: hex of bytes XORed with 0x58
/// let result = decoder.crack(
///     "1b37373331363f78151b7f2b783431333d78397828372d363c78373e783a393b3736",
///     &checker,
/// );
/// assert!(result.success);
/// assert_eq!(result.key.as_deref(), Some("0x58"));
/// assert_eq!(result.unencrypted_text.unwrap()[0], "Cooking MC's like a pound of bacon");
/// ```
pub struct XorSingleByteDecoder;

impl Crack for Decoder<XorSingleByteDecoder> {
    fn new() -> Decoder<XorSingleByteDecoder> {
        Decoder {
            name: "Single-byte XOR",
            description: "The XOR cipher combines every byte of the plaintext with a key using the exclusive or operation. With a single-byte key there are only 255 keys, so the cracker reads hex, Base64 or raw bytes, tries every key, ranks the outputs by English byte frequency and checks the best 5. Uses Low sensitivity for gibberish detection.",
            link: "https://en.wikipedia.org/wiki/XOR_cipher",
            tags: vec!["xor", "xor_single_byte", "bitwise", "crypto"],
            popularity: 0.5,
            phantom: std::marker::PhantomData,
        }
    }

    /// Checks the 5 best candidates and returns the first one the checker identifies.
    /// If none is identified, returns the candidates worth searching further (see
    /// [`unconfirmed`]), or no text at all.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying single-byte XOR with text {:?}", text);
        let candidates = best_candidates(text);
        if candidates.is_empty() {
            debug!("Single-byte XOR found no candidate keys");
            return CrackResult::new(self, text.to_string());
        }
        let checker_with_sensitivity = checker.with_sensitivity(Sensitivity::Low);
        check_candidates(self, text, &candidates, |candidate| {
            checker_with_sensitivity.check(candidate)
        })
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// A key that turned one of the input's byte views into plausible text.
#[derive(Debug)]
struct Candidate {
    /// The key byte
    key: u8,
    /// Mean byte weight of the output, see [`BYTE_WEIGHTS`]
    score: f32,
    /// The output
    text: String,
}

/// Formats a key the way CyberChef's XOR operation takes it, e.g. `0x2a`.
fn format_key(key: u8) -> String {
    format!("0x{key:02x}")
}

/// Runs `check` on each candidate in order and returns the first one it identifies. If it
/// identifies none, returns the [`unconfirmed`] candidates, or no text at all.
fn check_candidates(
    decoder: &Decoder<XorSingleByteDecoder>,
    text: &str,
    candidates: &[Candidate],
    mut check: impl FnMut(&str) -> CheckResult,
) -> CrackResult {
    let mut results = CrackResult::new(decoder, text.to_string());
    for candidate in candidates {
        if !check_string_success(&candidate.text, text) {
            continue;
        }
        let checker_result = check(&candidate.text);
        if checker_result.is_identified {
            trace!("Found a match with single-byte XOR key {}", candidate.key);
            results.unencrypted_text = Some(vec![candidate.text.clone()]);
            results.update_checker(&checker_result);
            results.key = Some(format_key(candidate.key));
            return results;
        }
    }

    let handed_on = unconfirmed(candidates);
    if !handed_on.is_empty() {
        // One key per text, in the same order
        let keys: Vec<String> = handed_on.iter().map(|c| format_key(c.key)).collect();
        results.key = Some(keys.join(", "));
        results.unencrypted_text = Some(handed_on.iter().map(|c| c.text.clone()).collect());
    }
    results
}

/// The best [`MAX_CHECKED`] candidates from every byte view of `text`, best first, with
/// no text twice.
fn best_candidates(text: &str) -> Vec<Candidate> {
    let mut all: Vec<Candidate> = byte_views(text)
        .iter()
        .flat_map(|view| crack_bytes(view))
        .map(|(key, score, text)| Candidate { key, score, text })
        .collect();
    all.sort_by(|a, b| b.score.total_cmp(&a.score).then(a.key.cmp(&b.key)));

    let mut best: Vec<Candidate> = Vec::with_capacity(MAX_CHECKED);
    for candidate in all {
        if best.len() == MAX_CHECKED {
            break;
        }
        if !best.iter().any(|kept| kept.text == candidate.text) {
            best.push(candidate);
        }
    }
    best
}

/// The candidates handed to the search when the checker identified none of them, at most 2:
/// * the best candidate, if it reads like English (it scores at least
///   [`UNCONFIRMED_MIN_SCORE`] and contains a space), as the checker misses some English;
/// * the best candidate that is itself hex or Base64 of UTF-8, the next layer of a chain
///   such as Base64 → XOR → Base64 (#808).
///
/// Both need more than a good score: letter soup such as the "edfglnhxzw..." that a few
/// repeated accented letters XOR to scores better than English, but it has no spaces and
/// isn't Base64 of anything the Base64 decoder accepts.
fn unconfirmed(candidates: &[Candidate]) -> Vec<&Candidate> {
    let mut chosen: Vec<&Candidate> = Vec::new();
    if let Some(best) = candidates.first() {
        if best.score >= UNCONFIRMED_MIN_SCORE && best.text.contains(' ') {
            chosen.push(best);
        }
    }
    if let Some(layer) = candidates.iter().find(|c| is_encoded_layer(&c.text)) {
        if !chosen.iter().any(|kept| std::ptr::eq(*kept, layer)) {
            chosen.push(layer);
        }
    }
    chosen
}

/// Tries every key on `bytes` and returns the candidates, best first, as
/// `(key, score, plaintext)`. Views under [`MIN_BYTES`] bytes, with fewer than
/// [`MIN_DISTINCT_BYTES`] distinct byte values, or that are [`numeric_text`] have none.
///
/// Keys are scored on the first [`RANK_BYTES`] bytes, from a byte histogram, and only keys
/// that pass the score checks are applied to the whole view. A key is a candidate if its
/// output
/// * is UTF-8 without control characters other than tab, CR and LF,
/// * scores at least [`MIN_SCORE`], and
/// * scores higher than `bytes` itself when `bytes` is already printable text. This stops
///   XOR from "improving" text that was fine to begin with, such as Base64 of English.
fn crack_bytes(bytes: &[u8]) -> Vec<(u8, f32, String)> {
    if bytes.len() < MIN_BYTES || numeric_text(bytes) {
        return Vec::new();
    }
    let histogram = Histogram::new(&bytes[..bytes.len().min(RANK_BYTES)]);
    if histogram.present.len() < MIN_DISTINCT_BYTES {
        return Vec::new();
    }
    let own_score = is_printable_utf8(bytes).then(|| histogram.score(0));

    let mut ranked: Vec<(u8, f32)> = (1..=u8::MAX)
        .filter(|&key| !histogram.breaks_text(key))
        .map(|key| (key, histogram.score(key)))
        .filter(|&(_, score)| score >= MIN_SCORE && own_score.is_none_or(|own| score > own))
        .collect();
    ranked.sort_by(|a, b| b.1.total_cmp(&a.1).then(a.0.cmp(&b.0)));

    ranked
        .into_iter()
        .filter_map(|(key, score)| {
            let output = String::from_utf8(bytes.iter().map(|byte| byte ^ key).collect()).ok()?;
            is_printable(&output).then_some((key, score, output))
        })
        .collect()
}

/// Byte counts of the start of a view, so a key is scored by visiting each distinct byte
/// once instead of every byte.
struct Histogram {
    /// How often each byte value occurs
    counts: [u32; 256],
    /// The byte values that occur
    present: Vec<u8>,
    /// Number of bytes counted
    total: usize,
}

impl Histogram {
    /// Counts the bytes of `sample`, which must not be empty.
    fn new(sample: &[u8]) -> Self {
        let mut counts = [0_u32; 256];
        for &byte in sample {
            counts[usize::from(byte)] += 1;
        }
        let present = (0..=u8::MAX)
            .filter(|&byte| counts[usize::from(byte)] > 0)
            .collect();
        Histogram {
            counts,
            present,
            total: sample.len(),
        }
    }

    /// Mean byte weight of the sample XORed with `key`.
    fn score(&self, key: u8) -> f32 {
        let sum: f32 = self
            .present
            .iter()
            .map(|&byte| {
                self.counts[usize::from(byte)] as f32 * BYTE_WEIGHTS[usize::from(byte ^ key)]
            })
            .sum();
        sum / self.total as f32
    }

    /// Whether XOR with `key` turns a sampled byte into an ASCII control character other
    /// than tab, CR and LF, or into a byte that never occurs in UTF-8. Either rules the key
    /// out without building its output.
    fn breaks_text(&self, key: u8) -> bool {
        self.present.iter().any(|&byte| {
            let output = byte ^ key;
            (output.is_ascii_control() && !matches!(output, b'\t' | b'\n' | b'\r'))
                || matches!(output, 0xc0 | 0xc1 | 0xf5..=0xff)
        })
    }
}

/// Whether `text` has no control characters other than tab, CR and LF.
fn is_printable(text: &str) -> bool {
    !text
        .chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\n' | '\r'))
}

/// Whether `bytes` is text made only of hex digits (which include the decimal and octal
/// ones), whitespace and the separators `,;:.-`: decimal, octal, hex or binary codes that
/// another decoder takes off, such as Base64 of `150 145 154 154 157`. XOR turns such text
/// into letter soup like `ptqaputaptua…` that can pass the English checker, and no key
/// turns English into it: no byte maps a space, `e`, `t` and `a` all into this set.
fn numeric_text(bytes: &[u8]) -> bool {
    bytes.iter().all(|&byte| {
        byte.is_ascii_hexdigit() || byte.is_ascii_whitespace() || b",;:.-".contains(&byte)
    })
}

/// Whether `bytes` is UTF-8 without control characters other than tab, CR and LF.
fn is_printable_utf8(bytes: &[u8]) -> bool {
    std::str::from_utf8(bytes).is_ok_and(is_printable)
}

/// The byte strings `text` might stand for: its hex or Base64 decoding, and the bytes an
/// earlier decoder turned into characters. Views under [`MIN_BYTES`] bytes are dropped.
///
/// Hex digits are Base64 characters too, so text that is hex is never read as Base64.
fn byte_views(text: &str) -> Vec<Vec<u8>> {
    let mut views = Vec::new();
    match hex_view(text) {
        Some(bytes) => views.push(bytes),
        None => views.extend(base64_view(text)),
    }
    views.extend(raw_views(text));
    views.retain(|view| view.len() >= MIN_BYTES);
    views
}

/// Decodes hex. The digits may be split by whitespace or `:` into groups of whole bytes,
/// each group optionally starting with `0x`.
fn hex_view(text: &str) -> Option<Vec<u8>> {
    let mut nibbles = Vec::with_capacity(text.len());
    for group in text.split(|c: char| c.is_whitespace() || c == ':') {
        let digits = group
            .strip_prefix("0x")
            .or_else(|| group.strip_prefix("0X"))
            .unwrap_or(group);
        if digits.len() % 2 != 0 || (digits.is_empty() && !group.is_empty()) {
            return None;
        }
        for c in digits.chars() {
            nibbles.push(c.to_digit(16)? as u8);
        }
    }
    (!nibbles.is_empty()).then(|| bytes_from_nibbles(&nibbles))
}

/// Decodes text that is nothing but hex digits, at least [`MIN_BYTES`] bytes of them.
fn strict_hex(text: &str) -> Option<Vec<u8>> {
    let nibbles = text
        .chars()
        .map(|c| c.to_digit(16).map(|nibble| nibble as u8))
        .collect::<Option<Vec<u8>>>()?;
    (nibbles.len() >= 2 * MIN_BYTES && nibbles.len() % 2 == 0).then(|| bytes_from_nibbles(&nibbles))
}

/// Pairs up hex digit values into bytes. A trailing odd digit is ignored; callers check
/// the count.
fn bytes_from_nibbles(nibbles: &[u8]) -> Vec<u8> {
    let (pairs, _) = nibbles.as_chunks::<2>();
    pairs.iter().map(|&[high, low]| (high << 4) | low).collect()
}

/// Decodes Base64, ignoring surrounding whitespace.
fn base64_view(text: &str) -> Option<Vec<u8>> {
    let trimmed = text.trim();
    if trimmed.len() < MIN_BASE64_VIEW_CHARS {
        return None;
    }
    decode_base64(trimmed)
}

/// Decodes text matching `[A-Za-z0-9+/_-]+={0,2}` with the engines `base64_decoder.rs`
/// uses: standard Base64, or URL-safe Base64 if that fails.
fn decode_base64(text: &str) -> Option<Vec<u8>> {
    let body = text.trim_end_matches('=');
    let is_base64_char =
        |b: u8| b.is_ascii_alphanumeric() || matches!(b, b'+' | b'/' | b'_' | b'-');
    if body.is_empty() || text.len() - body.len() > 2 || !body.bytes().all(is_base64_char) {
        return None;
    }
    general_purpose::STANDARD_NO_PAD
        .decode(body)
        .or_else(|_| general_purpose::URL_SAFE_NO_PAD.decode(body))
        .ok()
}

/// Whether `text` is, in full, hex or Base64 of UTF-8: a layer the Hexadecimal or Base64
/// decoder can take off next. The Base64 decoder drops anything that isn't UTF-8, and
/// UTF-8 can still hold control characters, so the layer below can be XORed bytes again.
fn is_encoded_layer(text: &str) -> bool {
    let utf8 = |bytes: Vec<u8>| std::str::from_utf8(&bytes).is_ok();
    strict_hex(text).is_some_and(utf8)
        || (text.trim_end_matches('=').len() >= MIN_BASE64_LAYER_CHARS
            && decode_base64(text).is_some_and(utf8))
}

/// The bytes behind text an earlier decoder made from raw bytes, which shows as control
/// characters or Latin-1 symbols (U+0080 to U+00BF, `×` and `÷`). Other text has no raw
/// view, including text whose only non-ASCII characters are accented letters: that is
/// usually just text, such as French. English XORed with a key of 0x80 or more always has
/// one of those characters, for its spaces or for its letters: a space becomes U+0080 to
/// U+00BF for keys 0x80 to 0xBF, and the letters do for keys 0xC0 to 0xFF.
///
/// When every character is at most U+00FF the bytes are its Latin-1 values. If some of
/// those are 0x80 or more, the UTF-8 encoding is tried too: the Hexadecimal decoder turns
/// bytes that happen to be valid UTF-8 into the characters they encode, not into Latin-1.
fn raw_views(text: &str) -> Vec<Vec<u8>> {
    let carries_bytes = text.chars().any(|c| {
        (c.is_control() && !matches!(c, '\t' | '\n' | '\r'))
            || ('\u{80}'..='\u{bf}').contains(&c)
            || matches!(c, '×' | '÷')
    });
    if !carries_bytes {
        return Vec::new();
    }

    let mut views = Vec::new();
    if text.chars().all(|c| u32::from(c) <= 0xff) {
        let latin1: Vec<u8> = text.chars().map(|c| u32::from(c) as u8).collect();
        let has_high_bytes = latin1.iter().any(|&byte| byte >= 0x80);
        views.push(latin1);
        if has_high_bytes {
            views.push(text.as_bytes().to_vec());
        }
    } else {
        views.push(text.as_bytes().to_vec());
    }
    views
}

