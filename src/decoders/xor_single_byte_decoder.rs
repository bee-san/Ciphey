    #[test]
    fn checking_stops_at_the_first_identified_candidate() {
        let decoder = Decoder::<XorSingleByteDecoder>::new();
        let accepting = Checker::<Athena>::new();
        let mut calls = 0;
        let result = check_candidates(
            &decoder,
            FLAG_HEX,
            &best_candidates(FLAG_HEX),
            |candidate| {
                calls += 1;
                let mut check_result = CheckResult::new(&accepting);
                check_result.is_identified = candidate.starts_with("flag{");
                check_result
            },
        );
        assert!(result.success);
        assert_eq!(result.key.as_deref(), Some("0x5a"));
        // The flag isn't the best scoring candidate: the ones before it are checked and
        // rejected, the ones after it are never checked
        let rank = best_candidates(FLAG_HEX)
            .iter()
            .position(|c| c.key == 0x5a)
            .unwrap();
        assert!(rank > 0);
        assert_eq!(calls, rank + 1);
    }

