//! Decode a big integer: the bytes of the text read as one big-endian unsigned integer and
//! written in decimal. `126207244316550804821666916` is `hello world`.
//! Call big_integer_decoder.crack to use. It returns a `CrackResult` whose `unencrypted_text`
//! is `None` when the input isn't such an integer.
//!
//! This is what PyCryptodome's `bytes_to_long` / `long_to_bytes`, Python's
//! `int.from_bytes(data, "big")` / `n.to_bytes((n.bit_length() + 7) // 8, "big")` and
//! CyberChef's `From Base` (10) → `To Base` (16) → `From Hex` do. RSA challenges in CTFs
//! print their message this way, often as `m = 4149…` or `flag = …`, and Python 2 adds an
//! `L` to the number. The input is one run of digits, optionally after a `name =` or
//! `name:` prefix and before one `L`. Zero bytes at the start of the text can't be
//! represented, which doesn't matter for text.
//!
//! The hex form (`0x5370…`) is the Hexadecimal decoder's. Digits in groups of three
//! (`104101108…`) are the Decimal decoder's; read as one number they almost never give
//! UTF-8 text.
//!
//! References:
//! <https://pycryptodome.readthedocs.io/en/latest/src/util/util.html#Crypto.Util.number.long_to_bytes>,
//! <https://gchq.github.io/CyberChef/#recipe=From_Base(10)To_Base(16)From_Hex('Auto')>.

