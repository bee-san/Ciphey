/// The Big integer decoder, call:
/// `let big_integer_decoder = Decoder::<BigIntegerDecoder>::new()` to create a new instance
/// And then call:
/// `result = big_integer_decoder.crack(input)` to decode a big integer
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::big_integer_decoder::BigIntegerDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_big_integer = Decoder::<BigIntegerDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// let result = decode_big_integer
///     .crack("126207244316550804821666916", &checker)
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "hello world");
/// ```
pub struct BigIntegerDecoder;

/// Numbers with fewer digits than this, not counting leading zeros, are rejected. Twelve
/// digits are at least 10^11 > 2^36, so at least 5 bytes: `hello` is `448378203247`.
/// Shorter texts are too short to identify, and 10 or 11 digits are what Unix timestamps and
/// phone numbers look like.
const MIN_DIGITS: usize = 12;

/// Numbers with more digits than this are rejected. 2000 digits decode to at most 831
/// bytes, and the search drops results and candidates of 821 to 5000 bytes anyway (see
/// `calculate_string_quality`). The cap bounds the big-integer work on long runs of digits.
const MAX_DIGITS: usize = 2000;

/// The longest name accepted before the `=` or `:`, as in `m = …` or `flag = …`.
const MAX_NAME_LEN: usize = 16;

impl Crack for Decoder<BigIntegerDecoder> {
    fn new() -> Decoder<BigIntegerDecoder> {
        Decoder {
            name: "Big integer to bytes",
            description: "The bytes of the text read as one big-endian integer and written in decimal, as PyCryptodome's bytes_to_long / long_to_bytes and Python's int.from_bytes do. Common in RSA CTF challenges (m = 4149…). An optional name = prefix and Python 2's trailing L are accepted.",
            link: "https://pycryptodome.readthedocs.io/en/latest/src/util/util.html#Crypto.Util.number.long_to_bytes",
            tags: vec!["long_to_bytes", "bigint", "decimal", "decoder", "base"],
            popularity: 0.5,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` as a big integer and checks the result with `checker`.
    /// `unencrypted_text` is `None` when `text` isn't a big integer of UTF-8 text.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Big integer to bytes with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(decoded_text) = decode_big_integer(text) else {
            debug!("Failed to decode Big integer to bytes because the text isn't a big integer of UTF-8 text");
            return results;
        };
        trace!("Decoded text for Big integer to bytes: {:?}", decoded_text);

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Big integer to bytes because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Decodes a decimal big integer to text, or returns `None` if `text` isn't one integer
/// whose big-endian bytes are UTF-8 text without control characters (tabs and line breaks
/// are allowed).
fn decode_big_integer(text: &str) -> Option<String> {
    // Rejects almost every input at its first byte, before anything is allocated
    let rest = strip_name_prefix(text.trim().as_bytes())?;
    // Python 2 printed a `long` with an `L` after it
    let digits = rest.strip_suffix(b"L").unwrap_or(rest);
    if digits.len() > MAX_DIGITS {
        return None;
    }
    // A single scan that stops at the first byte that isn't a digit: a second number or a
    // line break (`n = …\ne = 65537`), the `x` of `0x…`, a `_`, a second `L`.
    if !digits.iter().all(u8::is_ascii_digit) {
        return None;
    }
    let leading_zeros = digits.iter().take_while(|&&byte| byte == b'0').count();
    let significant = &digits[leading_zeros..];
    if significant.len() < MIN_DIGITS {
        return None;
    }

    // `parse_bytes` alone isn't a validator: it also accepts a leading `+` and skips `_`.
    // The scan above has rejected both. The number starts with a non-zero digit, so it
    // isn't zero, whose `to_bytes_be()` would be `[0]`.
    let number = BigUint::parse_bytes(significant, 10)?;
    let decoded = String::from_utf8(number.to_bytes_be()).ok()?;
    if decoded
        .chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\n' | '\r'))
    {
        return None;
    }
    Some(decoded)
}

/// Returns `text` without a `name =` or `name:` prefix, the way RSA challenges print their
/// numbers (`m = …`, `c = …`, `flag = …`, `pt: …`). The name is a letter or `_` followed by
/// letters, digits and `_`, at most `MAX_NAME_LEN` of them, and spaces may surround the
/// `=` or `:`. Text that starts with a digit is returned as it is. Anything else is `None`.
fn strip_name_prefix(text: &[u8]) -> Option<&[u8]> {
    match text.first()? {
        b'0'..=b'9' => Some(text),
        b'a'..=b'z' | b'A'..=b'Z' | b'_' => {
            let name_len = text
                .iter()
                .take(MAX_NAME_LEN + 1)
                .take_while(|&&byte| byte.is_ascii_alphanumeric() || byte == b'_')
                .count();
            if name_len > MAX_NAME_LEN {
                return None;
            }
            match skip_spaces(&text[name_len..]) {
                [b'=' | b':', rest @ ..] => Some(skip_spaces(rest)),
                _ => None,
            }
        }
        _ => None,
    }
}

/// `text` without the spaces at its start.
fn skip_spaces(text: &[u8]) -> &[u8] {
    let spaces = text.iter().take_while(|&&byte| byte == b' ').count();
    &text[spaces..]
}

