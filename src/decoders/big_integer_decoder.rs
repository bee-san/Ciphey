    #[test]
    fn decode_big_integer_caps_the_length() {
        // Zero digits in front don't change the value, so both inputs are the medium
        // plaintext; only the length differs.
        let at_limit = format!("{}{MEDIUM}", "0".repeat(MAX_DIGITS - MEDIUM.len()));
        assert_eq!(at_limit.len(), 2000);
        assert_eq!(
            decode_big_integer(&at_limit).as_deref(),
            Some(MEDIUM_PLAINTEXT)
        );

        let over_limit = format!("0{at_limit}");
        assert_eq!(over_limit.len(), 2001);
        assert_eq!(decode_big_integer(&over_limit), None);
    }

