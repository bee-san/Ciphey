/// The Hexdump decoder, call:
/// `let hexdump_decoder = Decoder::<HexdumpDecoder>::new()` to create a new instance
/// And then call:
/// `result = hexdump_decoder.crack(input)` to decode a hex dump
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::hexdump_decoder::HexdumpDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_hexdump = Decoder::<HexdumpDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // xxd
/// let result = decode_hexdump
///     .crack("00000000: 4865 6c6c 6f2c 2057 6f72 6c64 21         Hello, World!", &checker)
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "Hello, World!");
///
/// // hexdump -C
/// let dump = "00000000  48 65 6c 6c 6f 2c 20 57  6f 72 6c 64 21           |Hello, World!|\n\
///             0000000d";
/// let result = decode_hexdump.crack(dump, &checker).unencrypted_text;
/// assert_eq!(result.unwrap()[0], "Hello, World!");
/// ```
pub struct HexdumpDecoder;

/// The fewest digits an offset has (`od -A x`). `hexdump` and `od` write 7, `xxd` and
/// `hexdump -C` 8.
const MIN_OFFSET_DIGITS: usize = 6;

/// The most digits an offset has.
const MAX_OFFSET_DIGITS: usize = 8;

/// Fewer bytes than this aren't worth checking: the search drops results this short.
const MIN_BYTES: usize = 3;

impl Crack for Decoder<HexdumpDecoder> {
    fn new() -> Decoder<HexdumpDecoder> {
        Decoder {
            name: "Hexdump",
            description: "The output of xxd, hexdump -C, od and plain hexdump: an offset, hex or octal bytes or 16-bit words, and an ASCII column that is ignored",
            link: "https://en.wikipedia.org/wiki/Hex_dump",
            tags: vec!["hexdump", "xxd", "hex", "decoder"],
            popularity: 0.5,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` as a hex dump and checks the result with `checker`.
    /// `unencrypted_text` is `None` when `text` isn't a hex dump.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Hexdump with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(bytes) = decode_hexdump(text) else {
            debug!("Failed to decode Hexdump because the text isn't a hex dump");
            return results;
        };
        // UTF-8, or Latin-1 when the bytes aren't UTF-8, like Hexadecimal. Bytes that
        // aren't text are kept, so a dump of compressed data can go on to Gzip or Zlib.
        let decoded_text = bytes_to_string(bytes);
        trace!("Decoded text for Hexdump: {:?}", decoded_text);

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Hexdump because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Decodes a hex dump to the bytes that were dumped, or returns `None` if `text` isn't
/// one.
fn decode_hexdump(text: &str) -> Option<Vec<u8>> {
    // `ciphey -f` keeps leading blank lines, and a copied dump can end in a blank line
    let text = text.trim();
    let offset_digits = first_offset_digits(text.as_bytes())?;
    // xxd puts a colon after the offset, hexdump and od don't. Every line has to agree.
    let colon = text.as_bytes()[offset_digits] == b':';

    let mut bytes = Vec::with_capacity(text.len() / 3);
    // What the groups hold and how many digits each has, set by the first group of the dump
    let mut format = None;
    let mut group_digits = 0;
    // Bytes on the first line. Every later line has as many, except the last data line.
    let mut line_bytes = 0;
    let mut previous_offset = None;
    // A data line with fewer bytes than the first one was the last data line
    let mut short_line_seen = false;
    // A line with only an offset ends the dump
    let mut end_seen = false;
    // xxd -b writes each byte as 8 binary digits, which read as an 8-digit hex group
    let mut only_binary_digits = true;

    for line in text.lines() {
        if end_seen {
            return None;
        }
        // hexdump pads its last data line with spaces
        let (offset, mut rest) = split_offset(line.trim_end().as_bytes(), offset_digits)?;
        // Octal and decimal offsets are compared as hex, which keeps their order
        if previous_offset.is_some_and(|previous| offset <= previous) {
            return None;
        }
        previous_offset = Some(offset);

        if rest.is_empty() {
            end_seen = true;
            continue;
        }
        if short_line_seen {
            return None;
        }
        if colon {
            rest = rest.strip_prefix(b":")?;
        }
        if rest.first() != Some(&b' ') {
            return None;
        }

        let line_start = bytes.len();
        // xxd's last group can be shorter than the others: `2e` in `2076 6f77 2e`
        let mut short_group = false;
        loop {
            let spaces = rest.iter().take_while(|&&byte| byte == b' ').count();
            rest = &rest[spaces..];
            let on_line = bytes.len() - line_start;
            let Some(&next) = rest.first() else {
                break;
            };
            if colon {
                // xxd separates groups with one space and the ASCII column with two or more
                if spaces >= 2 && on_line > 0 {
                    break;
                }
                if short_group {
                    return None;
                }
            } else if matches!(next, b'|' | b'>') || (line_bytes > 0 && on_line == line_bytes) {
                // The ASCII column of hexdump -C starts with `|`, od -z's with `>`
                break;
            }

            let digits = rest
                .iter()
                .take_while(|byte| byte.is_ascii_hexdigit())
                .count();
            let whole_token = rest.get(digits).is_none_or(|&byte| byte == b' ');
            let group_format = match format {
                Some(group_format) => group_format,
                None => {
                    // The first group of the dump sets the format
                    let group_format = whole_token
                        .then(|| Format::from_first_group(digits, colon))
                        .flatten()?;
                    format = Some(group_format);
                    group_digits = digits;
                    group_format
                }
            };
            if !whole_token || digits != group_digits {
                if !colon {
                    // Not a group, so the hex ends here and the rest of the line is ignored
                    break;
                }
                if !whole_token || digits > group_digits || digits < 2 || digits % 2 != 0 {
                    return None;
                }
                short_group = true;
            }

            let (group, after) = rest.split_at(digits);
            // An octal group with a digit that isn't octal, or too big for its size
            if !push_group(&mut bytes, group, group_format) {
                return None;
            }
            only_binary_digits &= group.iter().all(|&digit| matches!(digit, b'0' | b'1'));
            rest = after;
        }

        let on_line = bytes.len() - line_start;
        if on_line == 0 {
            return None;
        }
        if line_bytes == 0 {
            line_bytes = on_line;
        } else if on_line > line_bytes {
            return None;
        }
        short_line_seen = short_group || on_line < line_bytes;
    }

    let format = format?;
    // Octal digits are 0 to 7, so text like `HAHA` (110 101 110 101) is all 0s and 1s
    if only_binary_digits && !format.is_octal() {
        return None;
    }
    if format.is_words() && bytes.last() == Some(&0) {
        // The pad byte of a dump of an odd number of bytes
        bytes.pop();
    }
    // A text file ends in a line break, which `ciphey -f` leaves out of a file it reads
    // too, and which would stop Base64 inside the dump from decoding. Bytes that aren't
    // UTF-8, like compressed data, are kept as they are.
    if std::str::from_utf8(&bytes).is_ok() {
        let end = bytes
            .iter()
            .rposition(|&byte| !matches!(byte, b'\n' | b'\r'))
            .map_or(0, |last| last + 1);
        bytes.truncate(end);
    }
    (bytes.len() >= MIN_BYTES).then_some(bytes)
}

/// What the groups of a dump hold.
#[derive(Clone, Copy, PartialEq)]
enum Format {
    /// Bytes in hex, in order, one or more per group: xxd, `hexdump -C`, `od -t x1`
    HexBytes,
    /// 16-bit little-endian words, 4 hex digits each: plain `hexdump`, `od -x`
    HexWords,
    /// Bytes, 3 octal digits each: `od -b`, `hexdump -b`
    OctalBytes,
    /// 16-bit little-endian words, 6 octal digits each: plain `od`, `hexdump -o`
    OctalWords,
}

impl Format {
    /// The format of a dump whose first group has `digits` digits. xxd (with a colon) only
    /// writes hex bytes. 32-bit words without a colon (`od -t x4`) are out of scope: they
    /// are in the byte order of the machine that wrote them.
    fn from_first_group(digits: usize, colon: bool) -> Option<Format> {
        match (digits, colon) {
            (2 | 4 | 8, true) | (2, false) => Some(Format::HexBytes),
            (4, false) => Some(Format::HexWords),
            (3, false) => Some(Format::OctalBytes),
            (6, false) => Some(Format::OctalWords),
            _ => None,
        }
    }

    /// Whether the groups are octal.
    fn is_octal(self) -> bool {
        matches!(self, Format::OctalBytes | Format::OctalWords)
    }

    /// Whether the groups are 16-bit words, whose last one is padded with a zero byte when
    /// the dump has an odd number of bytes.
    fn is_words(self) -> bool {
        matches!(self, Format::HexWords | Format::OctalWords)
    }
}

/// Appends the bytes `group`, a run of hex digits, stands for. Returns false when it is an
/// octal group with a digit that isn't octal or a value too big for its size.
fn push_group(bytes: &mut Vec<u8>, group: &[u8], format: Format) -> bool {
    match format {
        Format::HexBytes | Format::HexWords => {
            // Groups have an even number of digits, so nothing is left over
            let (pairs, _) = group.as_chunks::<2>();
            bytes.extend(
                pairs
                    .iter()
                    .map(|&[high, low]| (hex_value(high) << 4) | hex_value(low)),
            );
            if format == Format::HexWords {
                // A little-endian 16-bit word: `7053` is the bytes `53 70`
                let len = bytes.len();
                bytes.swap(len - 2, len - 1);
            }
        }
        Format::OctalBytes | Format::OctalWords => {
            if !group.iter().all(|digit| (b'0'..=b'7').contains(digit)) {
                return false;
            }
            let value = parse_digits(group, 8);
            if format == Format::OctalBytes {
                let Ok(byte) = u8::try_from(value) else {
                    return false;
                };
                bytes.push(byte);
            } else {
                // `062510` is the word 0x6548, the bytes `48 65`
                let Ok(word) = u16::try_from(value) else {
                    return false;
                };
                bytes.extend(word.to_le_bytes());
            }
        }
    }
    true
}

/// The value of a run of at most 8 digits in base 16 or 8. Callers only pass digits.
fn parse_digits(digits: &[u8], radix: u32) -> u32 {
    digits.iter().fold(0, |value, &digit| {
        value * radix + u32::from(hex_value(digit))
    })
}

/// The cheap first check, which rejects almost every input that isn't a dump within its
/// first nine bytes, without allocating: the text has to start with an offset of 6 to 8
/// hex digits followed by `:` or a space. Returns the number of digits.
fn first_offset_digits(text: &[u8]) -> Option<usize> {
    let digits = text
        .iter()
        .take(MAX_OFFSET_DIGITS + 1)
        .take_while(|byte| byte.is_ascii_hexdigit())
        .count();
    if !(MIN_OFFSET_DIGITS..=MAX_OFFSET_DIGITS).contains(&digits) {
        return None;
    }
    matches!(text.get(digits), Some(b':' | b' ')).then_some(digits)
}

/// Splits a line into its offset, which has to be `digits` hex digits like the first
/// line's, and the rest of the line.
fn split_offset(line: &[u8], digits: usize) -> Option<(u32, &[u8])> {
    let (offset, rest) = line.split_at_checked(digits)?;
    if !offset.iter().all(u8::is_ascii_hexdigit) || rest.first().is_some_and(u8::is_ascii_hexdigit)
    {
        return None;
    }
    let offset = parse_digits(offset, 16);
    Some((offset, rest))
}

/// The value of an ASCII hex digit. Callers only pass hex digits.
fn hex_value(digit: u8) -> u8 {
    match digit {
        b'0'..=b'9' => digit - b'0',
        b'a'..=b'f' => digit - b'a' + 10,
        b'A'..=b'F' => digit - b'A' + 10,
        _ => 0,
    }
}

