    #[test]
    fn keeps_bytes_that_are_not_text() {
        // `printf Hello | gzip -n | xxd`. There is no control-character check, so the bytes
        // reach the Gzip decoder as Latin-1 text, which it reads back as bytes.
        let dump = "\
00000000: 1f8b 0800 0000 0000 0003 f348 cdc9 c907  ...........H....\n\
00000010: 0082 89d1 f705 0000 00                   .........\n";
        assert_eq!(
            decode_hexdump(dump).unwrap(),
            [
                0x1f, 0x8b, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0xf3, 0x48, 0xcd, 0xc9,
                0xc9, 0x07, 0x00, 0x82, 0x89, 0xd1, 0xf7, 0x05, 0x00, 0x00, 0x00
            ]
        );
        let gzip = crack(dump).unwrap();
        assert!(gzip.starts_with("\u{1f}\u{8b}\u{8}\0"), "{gzip:?}");
        let gunzipped = Decoder::<GzipDecoder>::new().crack(&gzip, &get_athena_checker());
        assert_eq!(gunzipped.unencrypted_text.unwrap()[0], "Hello");
    }

