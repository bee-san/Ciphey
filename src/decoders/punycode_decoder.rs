    // The comment on each test says which references give the same output:
    // * Python 3.9 codecs: `text.encode().decode("punycode")` for raw Punycode and the same
    //   label by label for `xn--` labels. Encoding the plaintext with `.encode("idna")`
    //   (bare domains) or `.encode("punycode")` gives the ciphertext back.
    // * punycode.js 2.1.0 as bundled with Node 22, the library behind CyberChef's "From
    //   Punycode": `punycode.decode` (IDN off) for raw Punycode, `punycode.toUnicode` (IDN
    //   on) for `xn--` labels. `toUnicode` only decodes bare domains and the domain part of
    //   an email address, and only a lower-case `xn--`.

    // helper for tests
    fn get_athena_checker() -> CheckerTypes {
        let athena_checker = Checker::<Athena>::new();
        CheckerTypes::CheckAthena(athena_checker)
    }

    // helper for tests: the result of cracking `text` with the Athena checker
    fn crack(text: &str) -> CrackResult {
        Decoder::<PunycodeDecoder>::new().crack(text, &get_athena_checker())
    }

    // helper for tests: the decoded candidate, if the decoder returned one
    fn decode(text: &str) -> Option<String> {
        crack(text)
            .unencrypted_text
            .and_then(|candidates| candidates.into_iter().next())
    }

    // helper for tests: asserts that Athena takes the decoding of `text` for plaintext
    fn assert_cracked(text: &str, plaintext: &str) {
        let result = crack(text);
        assert_eq!(
            result.unencrypted_text.as_deref(),
            Some([plaintext.to_string()].as_slice()),
            "{text}"
        );
        assert!(result.success, "Athena should identify {plaintext:?}");
    }

