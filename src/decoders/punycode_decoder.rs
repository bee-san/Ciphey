    #[test]
    fn punycode_fails_on_invalid_idna_labels() {
        for text in [
            // Just the prefix: not a label, and not raw Punycode either
            "xn--",
            // Decodes to "abc", which has no non-ASCII character
            "xn--abc-",
            "xn--bcher-",
            // Overflow
            "xn--99999999999",
            // `-` can't start the digits
            "xn---kva",
            // One bad label fails the whole text
            "xn--bcher-kva.xn--99999999999.com",
            "xn--bcher-kva.xn--abc-.com",
        ] {
            let result = crack(text);
            assert_eq!(result.unencrypted_text, None, "{text:?}");
            assert!(!result.success, "{text:?}");
        }
    }

    #[test]
    fn punycode_fails_on_control_characters() {
        // "xn--ab-ba" is the label "a\u{80}b", and U+0080 to U+009F are control characters
        for text in [
            "xn--ab-ba",
            "xn--caf-xa31c",
            "xn--bcher-kva\u{0}",
            "b\u{7}cher-kva",
        ] {
            assert_eq!(decode(text), None, "{text:?}");
        }
        // Tabs and line breaks are kept
        assert_eq!(
            decode("xn--bcher-kva\txn--mller-kva\r\n").as_deref(),
            Some("bücher\tmüller")
        );
    }

    #[test]
    fn punycode_limits_the_number_of_digits() {
        // Every `a` inserts a U+0080, so this is valid Punycode of 2,000 insertions
        let many_insertions = format!("x-{}", "a".repeat(2000));
        assert_eq!(decode_bounded(&many_insertions), None);
        assert_eq!(decode(&many_insertions), None);
        assert_eq!(decode(&format!("xn--{many_insertions}")), None);

        // The limit counts the digits after the last `-`, not the ASCII characters
        let long_text = format!("{} caf-pnb", "word ".repeat(500));
        assert!(decode_bounded(&long_text).is_some());
        let at_limit = format!("x-{}", "a".repeat(MAX_DIGITS));
        assert!(decode_bounded(&at_limit).is_some());
        let over_limit = format!("x-{}", "a".repeat(MAX_DIGITS + 1));
        assert_eq!(decode_bounded(&over_limit), None);
        // With no `-`, or only a leading one, the crate reads every character as a digit
        assert_eq!(decode_bounded(&"a".repeat(MAX_DIGITS + 1)), None);
        assert_eq!(
            decode_bounded(&format!("-{}", "a".repeat(MAX_DIGITS))),
            None
        );
    }

    #[test]
    fn punycode_handles_arbitrary_ascii_without_panicking() {
        // Every string of up to 5 characters over an alphabet with the delimiter, digits
        // that overflow and characters that aren't digits, on its own and as a label.
        // Without the checker, which would make this slow.
        let alphabet = ['-', 'a', 'z', '0', '9', 'X', '.', ' '];
        let mut texts = vec![String::new()];
        for _ in 0..5 {
            texts = texts
                .iter()
                .flat_map(|text| alphabet.iter().map(move |c| format!("{text}{c}")))
                .collect();
            for text in &texts {
                let _ = decode_punycode(text);
                let _ = decode_punycode(&format!("xn--{text}"));
                let _ = decode_punycode(&format!("a.xn--{text}.b"));
            }
        }
    }

