use idna::punycode;
use log::{debug, info, trace};

/// The prefix of an IDNA label that holds Punycode, the "ACE prefix" (RFC 5890 section
/// 2.3.2.5). Matched in either case.
const ACE_PREFIX: &[u8] = b"xn--";

/// The most base 36 digits after the last `-` that are decoded.
///
/// Every digit can insert a character, and the `idna` crate shifts all earlier insertions
/// for each new one, so decoding takes time quadratic in the number of insertions: about
/// 0.25 ms for 1,024 and 165 ms for 16,384 in a release build. Real text needs far fewer
/// digits (a 3,400 character German text with 176 accented letters has 303), and DNS
/// labels are at most 63 bytes, so this only stops crafted input such as `a-` followed by
/// thousands of `a`s.
const MAX_DIGITS: usize = 1024;

/// The Punycode decoder, call:
/// `let punycode_decoder = Decoder::<PunycodeDecoder>::new()` to create a new instance
/// And then call:
/// `result = punycode_decoder.crack(input)` to decode Punycode
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::punycode_decoder::PunycodeDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decoder = Decoder::<PunycodeDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// let result = decoder.crack("xn--bcher-kva", &checker).unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "bücher");
/// ```
pub struct PunycodeDecoder;

impl Crack for Decoder<PunycodeDecoder> {
    fn new() -> Decoder<PunycodeDecoder> {
        Decoder {
            name: "Punycode",
            description: "Punycode (RFC 3492) and IDNA `xn--` labels: Unicode text written in ASCII, used for internationalised domain names",
            link: "https://datatracker.ietf.org/doc/html/rfc3492",
            tags: vec!["punycode", "idna", "unicode", "web", "decoder"],
            popularity: 0.3,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes the `xn--` labels in `text` or, if it has none, all of `text` as raw
    /// Punycode (see the module docs), and runs the checker on the result.
    ///
    /// Fails on text that is not ASCII or has no `-`, on an `xn--` label that is not valid
    /// Punycode of a non-ASCII label, on raw Punycode that doesn't decode to accented
    /// Latin-script text, and on results with control characters other than tab,
    /// carriage return and line feed.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Punycode with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(decoded_text) = decode_punycode(text) else {
            trace!("Failed to decode Punycode: not Punycode, or the result is not text");
            return results;
        };

        if has_unexpected_control_character(&decoded_text) {
            debug!(
                "Failed to decode Punycode: {:?} has control characters",
                decoded_text
            );
            return results;
        }

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Punycode because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);

        results.update_checker(&checker_result);

        results
    }
    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Decodes the `xn--` labels in `text` or, if it has none, all of it as raw Punycode.
///
/// Trailing whitespace is dropped: Punycode ends in digits, but text that went through
/// another encoding often ends in a line break. Leading whitespace is kept, because it
/// belongs to the ASCII characters: `À bientôt` is ` bientt-` followed by digits.
fn decode_punycode(text: &str) -> Option<String> {
    let text = text.trim_end();
    // Rejects almost every text the search tries, with one fast pass for each check
    if !text.contains('-') || !text.is_ascii() {
        return None;
    }
    match decode_idna_labels(text) {
        Labels::Decoded(decoded) => Some(decoded),
        Labels::Invalid => None,
        Labels::NotFound => decode_raw_punycode(text),
    }
}

/// What [`decode_idna_labels`] found
enum Labels {
    /// No `xn--` label, so the text may be raw Punycode
    NotFound,
    /// An `xn--` label that is not Punycode of a label with a non-ASCII character
    Invalid,
    /// The text with every `xn--` label decoded
    Decoded(String),
}

/// Replaces every `xn--` label in `text` with its decoding and copies the rest unchanged.
///
/// A label is a maximal run of ASCII letters, digits and `-`, so the dots of a domain, the
/// `/` and `:` of a URL, the `@` of an email address and the spaces of a sentence all end
/// one. Runs that start with `xn--` (or `XN--`, in any mix of case) and have more after it
/// are decoded; all other runs are kept as they are. `text` must be ASCII.
fn decode_idna_labels(text: &str) -> Labels {
    let bytes = text.as_bytes();
    let mut decoded = String::new();
    let mut found = false;
    // Everything before this byte offset has been written to `decoded`
    let mut copied_up_to = 0;
    let mut i = 0;

    while i < bytes.len() {
        if !is_label_byte(bytes[i]) {
            i += 1;
            continue;
        }
        let start = i;
        while i < bytes.len() && is_label_byte(bytes[i]) {
            i += 1;
        }
        let label = &bytes[start..i];
        if label.len() <= ACE_PREFIX.len()
            || !label[..ACE_PREFIX.len()].eq_ignore_ascii_case(ACE_PREFIX)
        {
            continue;
        }

        // `text` is ASCII, so every byte offset is a char boundary
        let Some(unicode) = decode_bounded(&text[start + ACE_PREFIX.len()..i]) else {
            return Labels::Invalid;
        };
        // `xn--abc-` decodes to `abc`, which is not an internationalised label
        if unicode.is_ascii() {
            return Labels::Invalid;
        }
        decoded.push_str(&text[copied_up_to..start]);
        decoded.push_str(&unicode);
        copied_up_to = i;
        found = true;
    }

    if !found {
        return Labels::NotFound;
    }
    decoded.push_str(&text[copied_up_to..]);
    Labels::Decoded(decoded)
}

/// Whether `byte` can be part of a domain label: an ASCII letter, an ASCII digit or `-`
fn is_label_byte(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'-'
}

/// Decodes all of `text` (ASCII, with a `-`) as one raw Punycode string, if the result
/// looks like text in a Latin-script language with accents.
///
/// Almost every hyphenated word, date, UUID and URL-safe Base64 string is valid Punycode,
/// so the result has to pass all of these:
///
/// * the digits after the last `-` are letters and digits only (rejects Morse code,
///   `self-driving car` and `abc-`);
/// * it has at least one non-ASCII character, and every one of them is a letter from
///   Latin-1 Supplement or Latin Extended-A (`hello-world` decodes to Thai);
/// * it has no more non-ASCII characters than ASCII letters;
/// * at most 2 non-ASCII characters for every 3 digits. A real encoder spends about 2 to 6
///   digits on each inserted character, while a hyphenated English word read as Punycode
///   inserts many characters from few digits.
///
/// Vietnamese, Romanian with comma-below letters (`ș`, `ț`) and non-Latin scripts fail
/// these checks; they still decode as `xn--` labels.
fn decode_raw_punycode(text: &str) -> Option<String> {
    let (_, digits) = text.rsplit_once('-')?;
    if digits.is_empty() || !digits.bytes().all(|byte| byte.is_ascii_alphanumeric()) {
        return None;
    }
    let decoded = decode_bounded(text)?;

    // The text before the last `-` is ASCII, so every non-ASCII character was inserted
    let mut inserted = 0;
    let mut letters = 0;
    for c in decoded.chars() {
        if c.is_ascii_alphabetic() {
            letters += 1;
        } else if !c.is_ascii() {
            if !is_latin_letter(c) {
                return None;
            }
            inserted += 1;
        }
    }
    ((1..=letters).contains(&inserted) && 3 * inserted <= 2 * digits.len()).then_some(decoded)
}

/// Whether `c` is a letter from Latin-1 Supplement or Latin Extended-A (U+00C0 to U+017F
/// without `×` and `÷`): the accented letters of Western and Central European languages
/// and Turkish.
fn is_latin_letter(c: char) -> bool {
    matches!(c, '\u{C0}'..='\u{17F}') && !matches!(c, '×' | '÷')
}

/// [`punycode::decode_to_string`], or `None` if there are more than [`MAX_DIGITS`] digits
/// after the last `-`.
///
/// The crate keeps the case of the ASCII characters, reads digits in either case and
/// returns `None` on a character that isn't a digit, on overflow and on code points that
/// aren't characters.
fn decode_bounded(encoded: &str) -> Option<String> {
    // The crate reads everything after the last `-` as digits, or all of the text if the
    // only `-` is the first character
    let digits = match encoded.rfind('-') {
        Some(position) if position > 0 => encoded.len() - position - 1,
        _ => encoded.len(),
    };
    if digits > MAX_DIGITS {
        return None;
    }
    punycode::decode_to_string(encoded)
}

/// Whether `text` has a control character other than tab, carriage return or line feed.
/// The first code points Punycode can insert, U+0080 to U+009F, are control characters.
fn has_unexpected_control_character(text: &str) -> bool {
    text.chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\r' | '\n'))
}

