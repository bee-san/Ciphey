//! Decode Punycode (RFC 3492) and the IDNA `xn--` labels of internationalised domain names.
//!
//! Punycode writes Unicode text in ASCII. The ASCII characters are copied as they are, then
//! come a `-` and the other characters, written as base 36 numbers (`a` to `z` are 0 to 25,
//! `0` to `9` are 26 to 35, in either case) that say which character to insert where.
//! `bücher` becomes `bcher-kva`. Domain names apply it label by label and mark each encoded
//! label with the prefix `xn--`, so `bücher.example` is `xn--bcher-kva.example`.
//!
//! The decoder reads two forms:
//!
//! * **IDNA labels.** Every `xn--` label in the text is decoded and everything around it is
//!   kept, so domains, URLs, email addresses and sentences with `xn--` labels in them all
//!   decode: `https://xn--bcher-kva.example.com/` gives `https://bücher.example.com/`.
//! * **Raw Punycode.** Text without an `xn--` label is read as one Punycode string, which is
//!   what CyberChef's "To Punycode" writes with "Internationalised domain name" off:
//!   `Schne Gre aus Mnchen-iwb41ctei` gives `Schöne Grüße aus München`.
//!
//! Text without a `-` is never decoded: Punycode of text that has no non-ASCII character
//! is that text plus a `-`, so every word would otherwise qualify. Most text with a `-` in
//! it is valid raw Punycode too, though (`hello-world` decodes to Thai), so a raw decoding
//! is only kept if it looks like a Latin-script language with accents: see
//! [`decode_raw_punycode`].
//!
//! References:
//! * RFC 3492, Punycode: <https://datatracker.ietf.org/doc/html/rfc3492>
//! * RFC 5891 section 4.4, Punycode in IDNA labels:
//!   <https://datatracker.ietf.org/doc/html/rfc5891#section-4.4>
//! * CyberChef "From Punycode":
//!   <https://gchq.github.io/CyberChef/#recipe=From_Punycode(true)>

