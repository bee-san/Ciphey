    #[test]
    fn decodes_to_ascii_only_from_the_table() {
        // Every character the table knows is non-ASCII and decodes to printable ASCII
        for c in '\0'..=char::MAX {
            if let Some(ascii) = fancy_to_ascii(c) {
                assert!(!c.is_ascii(), "{c:?}");
                assert!(
                    ascii.is_ascii_graphic() || ascii == ' ',
                    "U+{:04X} -> {ascii:?}",
                    u32::from(c)
                );
            }
        }
        // As many as the Python prototype of the table maps: 676 mathematical letters, 2
        // dotless letters, 50 mathematical digits and 460 others
        let known = ('\0'..=char::MAX)
            .filter(|&c| fancy_to_ascii(c).is_some())
            .count();
        assert_eq!(known, 1188);
    }

