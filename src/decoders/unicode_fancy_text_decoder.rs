//! Decode Unicode "fancy text": letters and digits written with look-alike Unicode
//! characters, as the "fancy font" generators for social media bios and chat write them.
//! Every fancy character stands for one ASCII character, so decoding is a table lookup.
//! The table covers:
//! * Mathematical Alphanumeric Symbols (U+1D400 to U+1D7FF): bold `𝐡𝐞𝐥𝐥𝐨`, italic, bold
//!   italic, script, bold script, fraktur, double-struck `𝕙𝕖𝕝𝕝𝕠`, bold fraktur, sans-serif
//!   and its bold, italic and bold italic, monospace `𝚑𝚎𝚕𝚕𝚘`, and their digits. The
//!   letters the block leaves out are in Letterlike Symbols (`ℎ`, `ℋ`, `ℯ`, `ℌ`, `ℂ` and
//!   so on), which is where generators take them from.
//! * Fullwidth forms `ｈｅｌｌｏ` (U+FF01 to U+FF5E) and the ideographic space U+3000.
//! * Circled `ⓗⓔⓛⓛⓞ`, parenthesized `⒣⒠⒧⒧⒪`, squared `🄷🄴🄻🄻🄾`, negative circled
//!   `🅗🅔🅛🅛🅞` and negative squared `🅷🅴🅻🅻🅾` letters, regional indicators `🇭🇪🇱🇱🇴`, and
//!   the circled, parenthesized and dingbat digits 0 to 9 (`①`, `⑴`, `⒈`, `❶`, `➀`, `➊`).
//! * Small capitals `ʜᴇʟʟᴏ` and superscript letters `ʰᵉˡˡᵒ`, and superscript and subscript
//!   digits except `¹`, `²` and `³`, which ordinary text uses (`5 m²`).
//! * The variation selectors and combining marks that keycap digits (`1️⃣`) and struck
//!   through, underlined or slashed text (`h̶e̶l̶l̶o̶`) add. These are removed.
//!
//! Case is kept where the fancy alphabet has both cases. Squared, negative circled and
//! negative squared letters and regional indicators only exist as capitals, and small
//! capitals are written as lower case.
//!
//! Wherever Unicode's NFKC normalisation turns one of these characters into a single
//! ASCII character, the table gives the same one. The table is hand-written for the rest:
//! NFKC leaves small capitals, negative circled and squared letters, regional indicators
//! and the removed marks alone, and turns `⒜` into `(a)`. Unlike NFKC, it also leaves
//! every other character alone, so ligatures, CJK compatibility forms and accents are
//! kept: `𝐡𝐞𝐥𝐥𝐨 café` is `hello café`.
//!
//! To keep ordinary text in other scripts from being decoded (`北京大学`, `naïve résumé`,
//! `5 m²`, `你好！`), the text has to have at least two fancy characters, and at least twice
//! as many fancy characters as other non-ASCII ones.
//!
//! Not decoded: upside-down text, Zalgo text, multi-digit enclosed numbers like `⑩`,
//! ligatures like `ﬁ`, Roman numerals, and "fonts" made of Greek or Cyrillic look-alikes
//! (`ђєℓℓσ`).
//!
//! References: <https://en.wikipedia.org/wiki/Mathematical_Alphanumeric_Symbols>,
//! <https://en.wikipedia.org/wiki/Enclosed_Alphanumerics>,
//! <https://en.wikipedia.org/wiki/Enclosed_Alphanumeric_Supplement>,
//! <https://en.wikipedia.org/wiki/Halfwidth_and_Fullwidth_Forms_(Unicode_block)> and
//! Unicode's NFKC, <https://unicode.org/reports/tr15/>.
//!
//! Call unicode_fancy_text_decoder.crack to use. It returns a `CrackResult` whose
//! `unencrypted_text` is `None` when the input isn't fancy text.

