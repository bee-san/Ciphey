    #[test]
    fn runs_before_rot47() {
        // rot47 reads each character as its low byte, so it turns fullwidth and negative
        // circled letters into ASCII too. When two decoders find plaintext in the same
        // search step, the search reports the one listed first.
        let decoders = get_all_decoders();
        let names: Vec<&str> = decoders
            .components
            .iter()
            .map(|decoder| decoder.get_name())
            .collect();
        let position = |name| names.iter().position(|&n| n == name).unwrap();
        assert!(position("Unicode Fancy Text") < position("rot47"));
    }
