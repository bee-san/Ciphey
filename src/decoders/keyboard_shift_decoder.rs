//! Crack the keyboard shift cipher, where every key was replaced by a neighbouring key on
//! the same keyboard: one or two keys to the right or left in its row, or the key above or
//! below it. `hello world` shifted one key to the right on US QWERTY is `jr;;p ept;f`.
//! Case is kept (`H` becomes `J`), spaces are kept, and a key at the end of a row wraps
//! round to the other end, as on dCode.
//! References: <https://www.dcode.fr/keyboard-shift-cipher>, and the key rows of
//! xkeyboard-config's `symbols/us`, `symbols/fr` and `symbols/de`
//! (<https://gitlab.freedesktop.org/xkeyboard-config/xkeyboard-config>).
//!
//! The decoder undoes 14 shifts, each of them a fixed table:
//! * US QWERTY, every key of the four rows (`` `1234567890-= ``, `qwertyuiop[]\`,
//!   `asdfghjkl;'`, `zxcvbnm,./` and the same keys with Shift): 1 or 2 keys to the right
//!   or left.
//! * US QWERTY, the key above or below, in the 4 × 10 grid `1234567890` / `qwertyuiop` /
//!   `asdfghjkl;` / `zxcvbnm,./` (and with Shift). Columns wrap round too, so `z` up is
//!   `a` and `1` up is `z`. The keys outside the grid stay as they are.
//! * US QWERTY letters only (dCode's "no symbols"), rows `qwertyuiop` / `asdfghjkl` /
//!   `zxcvbnm`: 1 or 2 keys to the right or left, so `p` right is `q`.
//! * The letters of AZERTY (`azertyuiop` / `qsdfghjklm` / `wxcvbn`) and of QWERTZ
//!   (`qwertzuiop` / `asdfghjkl` / `yxcvbnm`): 1 key to the right or left.
//!
//! Reading the keys typed on one layout as another (QWERTY typed, Dvorak read) is a
//! different cipher, and not this decoder's.
//!
//! All 14 decodings are cheap byte lookups, but checking each of them for plaintext isn't,
//! so they are ranked first, best first, by how English their pairs of adjacent characters
//! look, and only the best two are checked, with Low sensitivity for gibberish detection.
//! The key of a result is the name of the shift that encrypted it, such as
//! `QWERTY right 1`. Ciphey runs every decoder on every text the search expands, so text
//! that can't be a shift of English (non-ASCII text, Base64 and the other encodings, text
//! that changes case inside its words) is turned away first, in one pass over its bytes.

