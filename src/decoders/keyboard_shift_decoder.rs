    #[test]
    fn every_table_is_a_permutation_that_moves_every_letter() {
        for table in TABLES.iter() {
            let mut decoded = table.decode;
            decoded.sort_unstable();
            let identity: Vec<u8> = (0u8..128).collect();
            assert_eq!(decoded.to_vec(), identity, "{}", table.name);
            for letter in (b'a'..=b'z').chain(b'A'..=b'Z') {
                let plain = table.decode[usize::from(letter)];
                assert_ne!(plain, letter, "{} keeps {}", table.name, char::from(letter));
                // Case is kept: a letter decodes to a letter of the same case, or to the
                // punctuation key next to it
                if plain.is_ascii_alphabetic() {
                    assert_eq!(
                        plain.is_ascii_uppercase(),
                        letter.is_ascii_uppercase(),
                        "{}",
                        table.name
                    );
                }
            }
            // Whitespace and control characters are never keys
            for byte in [b' ', b'\t', b'\n', b'\r', 0, 0x7F] {
                assert_eq!(table.decode[usize::from(byte)], byte, "{}", table.name);
            }
        }
    }

