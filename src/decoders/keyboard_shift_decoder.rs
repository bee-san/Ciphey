    #[test]
    fn english_score_counts_letter_pairs_and_penalises_the_rest() {
        let log_probs = &*BIGRAM_LOG_PROBS;
        let th = log_probs[usize::from(b't' - b'a')][usize::from(b'h' - b'a')];
        let he = log_probs[usize::from(b'h' - b'a')][usize::from(b'e' - b'a')];
        assert!((english_score("the") - (th + he) / 2.0).abs() < 1e-5);
        // Case doesn't matter, and pairs with a space don't count
        assert!((english_score("THE") - english_score("the")).abs() < 1e-6);
        assert!((english_score("th he") - (th + he) / 2.0).abs() < 1e-5);
        // `t;` and `;h` are not letter pairs
        assert!((english_score("t;h") - OTHER_PAIR_LOG_PROB).abs() < 1e-6);
        assert!((english_score("a b c") - OTHER_PAIR_LOG_PROB).abs() < 1e-6);
        assert!(english_score("hello world") > english_score("he;;o wor;d"));
    }

