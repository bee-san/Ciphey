/// The Keyboard shift cracker, call:
/// `let keyboard_shift_decoder = Decoder::<KeyboardShiftDecoder>::new()` to create a new
/// instance
/// And then call:
/// `result = keyboard_shift_decoder.crack(input, &checker)` to crack a keyboard shift
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::keyboard_shift_decoder::KeyboardShiftDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_keyboard_shift = Decoder::<KeyboardShiftDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // `hello world`, every key moved one to the right on a US QWERTY keyboard
/// let result = decode_keyboard_shift.crack("jr;;p ept;f", &checker);
/// assert!(result.success);
/// // If it succeeds, the 0th element is the plaintext, else it contains up to 3
/// // decodings with the best-ranked shifts
/// assert_eq!(result.unencrypted_text.unwrap()[0], "hello world");
/// assert_eq!(result.key.unwrap(), "QWERTY right 1");
/// ```
pub struct KeyboardShiftDecoder;

/// US QWERTY, every key of each row from left to right, without Shift.
const QWERTY_ROWS: [&str; 4] = [
    "`1234567890-=",
    "qwertyuiop[]\\",
    "asdfghjkl;'",
    "zxcvbnm,./",
];

/// [`QWERTY_ROWS`] with Shift held.
const QWERTY_SHIFTED_ROWS: [&str; 4] = [
    "~!@#$%^&*()_+",
    "QWERTYUIOP{}|",
    "ASDFGHJKL:\"",
    "ZXCVBNM<>?",
];

/// The 4 × 10 grid of US QWERTY keys that shift up and down, top row first.
const QWERTY_GRID: [&str; 4] = ["1234567890", "qwertyuiop", "asdfghjkl;", "zxcvbnm,./"];

/// [`QWERTY_GRID`] with Shift held.
const QWERTY_SHIFTED_GRID: [&str; 4] = ["!@#$%^&*()", "QWERTYUIOP", "ASDFGHJKL:", "ZXCVBNM<>?"];

/// The letter rows of US QWERTY, in both cases.
const QWERTY_LETTERS: [&str; 6] = [
    "qwertyuiop",
    "asdfghjkl",
    "zxcvbnm",
    "QWERTYUIOP",
    "ASDFGHJKL",
    "ZXCVBNM",
];

/// The letter rows of French AZERTY, in both cases.
const AZERTY_LETTERS: [&str; 6] = [
    "azertyuiop",
    "qsdfghjklm",
    "wxcvbn",
    "AZERTYUIOP",
    "QSDFGHJKLM",
    "WXCVBN",
];

/// The letter rows of German QWERTZ, in both cases.
const QWERTZ_LETTERS: [&str; 6] = [
    "qwertzuiop",
    "asdfghjkl",
    "yxcvbnm",
    "QWERTZUIOP",
    "ASDFGHJKL",
    "YXCVBNM",
];

/// How many of the best-ranked decodings are run through the checker. A Python prototype
/// of this ranking put the plaintext first for 139 and second for 1 of 140 ciphertexts
/// (10 English texts under each of the 14 shifts, see #976).
const CANDIDATES_CHECKED: usize = 2;

/// How many decodings are returned for the search to keep exploring when none of the
/// checked ones is plaintext.
const CANDIDATES_RETURNED: usize = 3;

/// Pre-check: the fewest ASCII letters worth cracking. Every shift moves every letter.
const MIN_LETTERS: usize = 1;

/// Pre-check: the fewest characters other than whitespace worth cracking. Shorter text
/// can't be ranked, and the search drops results that short anyway.
const MIN_NON_WHITESPACE: usize = 4;

/// Pre-check: with at least this many pairs of adjacent ASCII letters, at most one pair in
/// [`MAX_LOWER_UPPER_PAIRS_ONE_IN`] may be a lowercase letter followed by an uppercase one
/// (`aB`). Fewer pairs say too little to tell.
const MIN_PAIRS_FOR_CASE_CHECK: usize = 20;

/// A shift keeps the case of every letter, and English almost never changes case inside a
/// word, so a keyboard shift of English doesn't either: at most one pair in 11 in Project
/// Gutenberg books and Ciphey's docs (see the Affine cracker, which has the same check).
/// Base64 and its Caesar and rot47 shifts, the commonest text the search hands every
/// decoder, do it about one pair in four, and so does the gibberish of the benchmarks.
const MAX_LOWER_UPPER_PAIRS_ONE_IN: usize = 8;

/// One word at least this long, made only of the characters of Base64 and with a digit in
/// it (see [`is_encoded_word`]), is far more often Base64, Base32, Base36, Base58 or hex,
/// which the search sees all the time, than a keyboard shift. Its decodings are still
/// checked, so a shifted flag or password in one word is found, but the ones the checker
/// doesn't accept aren't handed back: they would look like encodings too and send the
/// search down dead ends, which costs far more than the decodings themselves.
const MIN_ENCODED_WORD_LEN: usize = 16;

/// The score of a pair of adjacent characters that aren't both letters, such as `;` or `[`
/// inside a word, which a shift that went the wrong way leaves behind. It is about the
/// `ln P` of a rare English letter pair, so a flag's `_` and `{}` don't drown it.
const OTHER_PAIR_LOG_PROB: f32 = -10.0;

/// A keyboard shift this decoder undoes.
struct Table {
    /// The layout and the way the encoder moved each key, such as `QWERTY right 1`. It is
    /// the key of the results this table decodes.
    name: &'static str,
    /// The byte each ASCII byte decodes to. Bytes that aren't keys of the table decode to
    /// themselves.
    decode: [u8; 128],
}

/// Every shift this decoder undoes. When two give the same decoding, or tie in the
/// ranking, the one listed first wins, so the commoner shifts come first.
static TABLES: Lazy<Vec<Table>> = Lazy::new(|| {
    let qwerty_rows: Vec<&str> = QWERTY_ROWS
        .iter()
        .chain(QWERTY_SHIFTED_ROWS.iter())
        .copied()
        .collect();
    let mut qwerty_columns = columns(&QWERTY_GRID);
    qwerty_columns.extend(columns(&QWERTY_SHIFTED_GRID));
    let qwerty_columns: Vec<&str> = qwerty_columns.iter().map(String::as_str).collect();

    vec![
        Table::new("QWERTY right 1", &qwerty_rows, 1),
        Table::new("QWERTY left 1", &qwerty_rows, -1),
        Table::new("QWERTY right 2", &qwerty_rows, 2),
        Table::new("QWERTY left 2", &qwerty_rows, -2),
        // Columns run from the top row down, so moving up is moving back one
        Table::new("QWERTY up", &qwerty_columns, -1),
        Table::new("QWERTY down", &qwerty_columns, 1),
        Table::new("QWERTY letters right 1", &QWERTY_LETTERS, 1),
        Table::new("QWERTY letters left 1", &QWERTY_LETTERS, -1),
        Table::new("QWERTY letters right 2", &QWERTY_LETTERS, 2),
        Table::new("QWERTY letters left 2", &QWERTY_LETTERS, -2),
        Table::new("AZERTY letters right 1", &AZERTY_LETTERS, 1),
        Table::new("AZERTY letters left 1", &AZERTY_LETTERS, -1),
        Table::new("QWERTZ letters right 1", &QWERTZ_LETTERS, 1),
        Table::new("QWERTZ letters left 1", &QWERTZ_LETTERS, -1),
    ]
});

impl Table {
    /// The table that undoes an encoder which replaced every key in `cycles` by the key
    /// `offset` places further along its cycle, wrapping round at the end. A cycle is a row
    /// of keys from left to right, or a column from top to bottom.
    fn new(name: &'static str, cycles: &[&str], offset: isize) -> Self {
        let mut decode = [0u8; 128];
        for (byte, plain) in (0u8..).zip(decode.iter_mut()) {
            *plain = byte;
        }
        for cycle in cycles {
            let keys = cycle.as_bytes();
            let len = keys.len() as isize;
            for (position, &key) in (0isize..).zip(keys) {
                let cipher = keys[(position + offset).rem_euclid(len) as usize];
                decode[usize::from(cipher)] = key;
            }
        }
        Table { name, decode }
    }
}

/// The columns of `grid`, each read from the top row down.
fn columns(grid: &[&str]) -> Vec<String> {
    let width = grid.iter().map(|row| row.len()).min().unwrap_or(0);
    (0..width)
        .map(|column| {
            grid.iter()
                .map(|row| char::from(row.as_bytes()[column]))
                .collect()
        })
        .collect()
}

impl Crack for Decoder<KeyboardShiftDecoder> {
    fn new() -> Decoder<KeyboardShiftDecoder> {
        Decoder {
            name: "Keyboard shift",
            description: "Keyboard shift cipher: every key replaced by a neighbouring key (left, right, up or down, 1–2 keys) on a US QWERTY, AZERTY or QWERTZ keyboard. Uses Low sensitivity for gibberish detection.",
            link: "https://www.dcode.fr/keyboard-shift-cipher",
            tags: vec!["keyboard", "substitution", "decryption", "classic"],
            popularity: 0.4,
            phantom: std::marker::PhantomData,
        }
    }

    /// Ranks the 14 decodings, then checks the best `CANDIDATES_CHECKED` in order and stops
    /// at the first one the checker identifies, reporting the name of its shift as the key.
    /// Otherwise returns the best `CANDIDATES_RETURNED` decodings, unidentified, unless the
    /// text looks like an encoding (see [`MIN_ENCODED_WORD_LEN`]).
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Keyboard shift with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let ranked = rank_candidates(text);
        if ranked.is_empty() {
            trace!("Failed to crack keyboard shift: the text is not worth trying");
            return results;
        }

        // Use the checker with Low sensitivity, like the Caesar cracker
        let checker_with_sensitivity = checker.with_sensitivity(Sensitivity::Low);
        for (_, table, candidate) in ranked.iter().take(CANDIDATES_CHECKED) {
            let checker_result = checker_with_sensitivity.check(candidate);
            if checker_result.is_identified {
                trace!("Found a match with keyboard shift {}", table);
                results.unencrypted_text = Some(vec![candidate.clone()]);
                results.update_checker(&checker_result);
                results.key = Some(table.to_string());
                return results;
            }
        }

        if is_encoded_word(text) {
            trace!("Keyboard shift: the text looks like an encoding, so nothing is handed on");
            return results;
        }
        results.unencrypted_text = Some(
            ranked
                .into_iter()
                .take(CANDIDATES_RETURNED)
                .map(|(_, _, candidate)| candidate)
                .collect(),
        );
        results
    }
    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Whether `text` could be a keyboard shift worth cracking, in one pass over its bytes
/// without allocating:
/// * printable ASCII, tabs and line breaks only, which rejects emoji and any non-ASCII text,
/// * at least [`MIN_LETTERS`] ASCII letters and at least [`MIN_NON_WHITESPACE`] other
///   characters than whitespace,
/// * few lowercase letters followed by uppercase ones (see
///   [`MAX_LOWER_UPPER_PAIRS_ONE_IN`]).
fn passes_pre_checks(text: &str) -> bool {
    let mut letters = 0usize;
    let mut non_whitespace = 0usize;
    let mut letter_pairs = 0usize;
    let mut lower_upper_pairs = 0usize;
    let mut previous = b' ';
    for &byte in text.as_bytes() {
        match byte {
            b' ' | b'\t' | b'\n' | b'\r' => {}
            0x21..=0x7E => {
                non_whitespace += 1;
                if byte.is_ascii_alphabetic() {
                    letters += 1;
                    if previous.is_ascii_alphabetic() {
                        letter_pairs += 1;
                        if previous.is_ascii_lowercase() && byte.is_ascii_uppercase() {
                            lower_upper_pairs += 1;
                        }
                    }
                }
            }
            _ => return false,
        }
        previous = byte;
    }
    letters >= MIN_LETTERS
        && non_whitespace >= MIN_NON_WHITESPACE
        && (letter_pairs < MIN_PAIRS_FOR_CASE_CHECK
            || lower_upper_pairs * MAX_LOWER_UPPER_PAIRS_ONE_IN <= letter_pairs)
}

/// Whether `text`, leading and trailing whitespace aside, is one word of at least
/// [`MIN_ENCODED_WORD_LEN`] characters of Base64's alphabet (`A-Z`, `a-z`, `0-9`, `+`, `/`,
/// `=`) with a digit in it: Base64, Base32, Base36, Base58 or hex, more likely than a
/// keyboard shift.
fn is_encoded_word(text: &str) -> bool {
    let word = text.trim_matches(|c: char| c.is_ascii_whitespace());
    word.len() >= MIN_ENCODED_WORD_LEN
        && word.bytes().any(|byte| byte.is_ascii_digit())
        && word
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'+' | b'/' | b'='))
}

/// Decodes `text` with `table`. Bytes that aren't keys of the table, and anything that
/// isn't ASCII, are copied.
fn decode_with(text: &str, table: &Table) -> String {
    let bytes: Vec<u8> = text
        .bytes()
        .map(|byte| table.decode.get(usize::from(byte)).copied().unwrap_or(byte))
        .collect();
    // ASCII bytes decode to ASCII bytes and every other byte is copied, so this is UTF-8
    match String::from_utf8(bytes) {
        Ok(decoded) => decoded,
        Err(error) => String::from_utf8_lossy(error.as_bytes()).into_owned(),
    }
}

/// Every decoding of `text`, best first, as `(score, shift, decoding)`, or nothing if `text`
/// fails the pre-checks (see [`passes_pre_checks`]). Decodings that leave the text as it
/// is, or repeat an earlier shift's decoding (the US QWERTY and QWERTZ letter shifts agree
/// on text without `y` and `z`), are left out.
///
/// The score is [`english_score`]. The sort is stable, so ties keep the order of
/// [`TABLES`].
fn rank_candidates(text: &str) -> Vec<(f32, &'static str, String)> {
    if !passes_pre_checks(text) {
        return Vec::new();
    }
    let mut ranked: Vec<(f32, &'static str, String)> = Vec::with_capacity(TABLES.len());
    for table in TABLES.iter() {
        let candidate = decode_with(text, table);
        if !check_string_success(&candidate, text)
            || ranked.iter().any(|(_, _, seen)| *seen == candidate)
        {
            continue;
        }
        ranked.push((english_score(&candidate), table.name, candidate));
    }
    ranked.sort_by(|left, right| right.0.total_cmp(&left.0));
    ranked
}

/// How English `text` looks: the mean score of its pairs of adjacent characters. A pair of
/// ASCII letters scores its English `ln P` from [`BIGRAM_LOG_PROBS`], in either case; a
/// pair with whitespace in it doesn't count; any other pair scores
/// [`OTHER_PAIR_LOG_PROB`]. Text without a pair that counts scores
/// [`OTHER_PAIR_LOG_PROB`].
fn english_score(text: &str) -> f32 {
    let log_probs = &*BIGRAM_LOG_PROBS;
    let mut total = 0.0f32;
    let mut pairs = 0u32;
    for pair in text.as_bytes().windows(2) {
        let (first, second) = (pair[0], pair[1]);
        if first.is_ascii_whitespace() || second.is_ascii_whitespace() {
            continue;
        }
        pairs += 1;
        total += match (letter_index(first), letter_index(second)) {
            (Some(first), Some(second)) => log_probs[first][second],
            _ => OTHER_PAIR_LOG_PROB,
        };
    }
    if pairs == 0 {
        OTHER_PAIR_LOG_PROB
    } else {
        total / pairs as f32
    }
}

/// The position in the alphabet (0..26) of an ASCII letter, in either case.
fn letter_index(byte: u8) -> Option<usize> {
    if byte.is_ascii_alphabetic() {
        Some(usize::from(byte.to_ascii_lowercase() - b'a'))
    } else {
        None
    }
}

