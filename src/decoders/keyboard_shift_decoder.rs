    /// The table called `name`.
    fn table(name: &str) -> &'static Table {
        TABLES
            .iter()
            .find(|table| table.name == name)
            .unwrap_or_else(|| panic!("no table named {name:?}"))
    }

    /// The rows of keys an encoder table moves, and how far: written out again from the
    /// plan in #976, independently of `TABLES`, so the tests check the tables against it.
    fn encoder_cycles(name: &str) -> (Vec<String>, isize) {
        let all_rows = || -> Vec<String> {
            [
                "`1234567890-=",
                "qwertyuiop[]\\",
                "asdfghjkl;'",
                "zxcvbnm,./",
                "~!@#$%^&*()_+",
                "QWERTYUIOP{}|",
                "ASDFGHJKL:\"",
                "ZXCVBNM<>?",
            ]
            .map(String::from)
            .to_vec()
        };
        // The grid's columns, top to bottom: `1qaz`, `2wsx`, ... and with Shift `!QAZ`, ...
        let grid_columns = || -> Vec<String> {
            let mut columns = Vec::new();
            for grid in [
                ["1234567890", "qwertyuiop", "asdfghjkl;", "zxcvbnm,./"],
                ["!@#$%^&*()", "QWERTYUIOP", "ASDFGHJKL:", "ZXCVBNM<>?"],
            ] {
                for column in 0..10 {
                    columns.push(grid.iter().map(|row| &row[column..=column]).collect());
                }
            }
            columns
        };
        let letters = |rows: [&str; 3]| -> Vec<String> {
            rows.iter()
                .map(|row| row.to_string())
                .chain(rows.iter().map(|row| row.to_ascii_uppercase()))
                .collect()
        };
        let qwerty = ["qwertyuiop", "asdfghjkl", "zxcvbnm"];
        let azerty = ["azertyuiop", "qsdfghjklm", "wxcvbn"];
        let qwertz = ["qwertzuiop", "asdfghjkl", "yxcvbnm"];
        match name {
            "QWERTY right 1" => (all_rows(), 1),
            "QWERTY left 1" => (all_rows(), -1),
            "QWERTY right 2" => (all_rows(), 2),
            "QWERTY left 2" => (all_rows(), -2),
            "QWERTY up" => (grid_columns(), -1),
            "QWERTY down" => (grid_columns(), 1),
            "QWERTY letters right 1" => (letters(qwerty), 1),
            "QWERTY letters left 1" => (letters(qwerty), -1),
            "QWERTY letters right 2" => (letters(qwerty), 2),
            "QWERTY letters left 2" => (letters(qwerty), -2),
            "AZERTY letters right 1" => (letters(azerty), 1),
            "AZERTY letters left 1" => (letters(azerty), -1),
            "QWERTZ letters right 1" => (letters(qwertz), 1),
            "QWERTZ letters left 1" => (letters(qwertz), -1),
            _ => panic!("no encoder for {name:?}"),
        }
    }

    /// Encrypts `text` with the shift called `name`, walking its rows of keys.
    fn encode(text: &str, name: &str) -> String {
        let (cycles, offset) = encoder_cycles(name);
        text.chars()
            .map(|c| {
                for cycle in &cycles {
                    let keys: Vec<char> = cycle.chars().collect();
                    if let Some(position) = keys.iter().position(|&key| key == c) {
                        let len = keys.len() as isize;
                        return keys[(position as isize + offset).rem_euclid(len) as usize];
                    }
                }
                c
            })
            .collect()
    }

