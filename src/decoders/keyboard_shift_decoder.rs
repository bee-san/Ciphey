    #[test]
    fn identical_decodings_are_kept_once() {
        // `jraap eptaf` has no `u`, `x`, `y` or `z`, the keys where one key to the right
        // differs between the US QWERTY and QWERTZ letter rows, so both decode it to
        // `hello world`; the decoding is kept once, under the shift listed first
        let ciphertext = encode("hello world", "QWERTY letters right 1");
        assert_eq!(ciphertext, "jraap eptaf");
        assert_eq!(
            decode_with(&ciphertext, table("QWERTZ letters right 1")),
            "hello world"
        );
        let ranked = rank_candidates(&ciphertext);
        let names: Vec<&str> = ranked.iter().map(|(_, name, _)| *name).collect();
        assert!(names.contains(&"QWERTY letters right 1"), "{names:?}");
        assert!(!names.contains(&"QWERTZ letters right 1"), "{names:?}");
        assert_eq!(ranked[0].1, "QWERTY letters right 1");
        let mut texts: Vec<&String> = ranked.iter().map(|(_, _, text)| text).collect();
        let count = texts.len();
        texts.sort();
        texts.dedup();
        assert_eq!(texts.len(), count, "a decoding is listed twice");
        assert!(ranked.iter().all(|(_, _, text)| *text != ciphertext));
        // With a `y` in the plaintext (`u` in the ciphertext) they differ, and both are
        // kept. `urd dot` has none of the keys at the ends of the rows either, so the
        // letter-only US QWERTY shift gives what the full-row one gives, and only the
        // full-row one, listed first, is kept.
        let ciphertext = encode("yes sir", "QWERTY letters right 1");
        assert_eq!(ciphertext, "urd dot");
        let ranked = rank_candidates(&ciphertext);
        let names: Vec<&str> = ranked.iter().map(|(_, name, _)| *name).collect();
        assert_eq!(ranked[0].1, "QWERTY right 1");
        assert_eq!(ranked[0].2, "yes sir");
        assert!(names.contains(&"QWERTZ letters right 1"), "{names:?}");
        assert!(!names.contains(&"QWERTY letters right 1"), "{names:?}");
    }

