    #[test]
    fn the_issue_key_cracks_other_digit_orders() {
        // The issue's example picks a class's digits in another order; any order works
        let ciphertext = encrypt("HELLO WORLD", &[1, 4, 7], &[2, 5, 8], &[3, 6, 9, 0]);
        assert_ne!(ciphertext, ISSUE);
        let result = crack(&ciphertext);
        assert!(result.success, "{result:?}");
        assert_eq!(result.unencrypted_text.unwrap(), ["HELLO WORLD"]);
        assert_eq!(result.key.as_deref(), Some(ISSUE_KEY));
    }

    #[test]
    fn digits_split_into_letters_at_one_or_two_separators() {
        // 1 = dot, 2 = dash, 3 = separator: `.- -..` then a word break, `.`
        let digits = [1, 2, 3, 2, 1, 1, 3, 3, 1, 3];
        let groups = split_into_letters(&digits, 1 << 3).unwrap();
        assert_eq!(
            groups,
            [
                Group {
                    start: 0,
                    end: 2,
                    word_end: false
                },
                Group {
                    start: 3,
                    end: 6,
                    word_end: true
                },
                Group {
                    start: 8,
                    end: 9,
                    word_end: false
                },
            ]
        );
        let mut text = Vec::new();
        assert!(read_letters(&digits, &groups, 1 << 2, &mut text));
        assert_eq!(text, b"AD E");
        // Three separators in a row, or seven symbols without one, aren't Pollux
        assert!(split_into_letters(&[1, 3, 3, 3, 1], 1 << 3).is_none());
        assert!(split_into_letters(&[1, 2, 1, 2, 1, 2, 1, 3, 1], 1 << 3).is_none());
    }

    #[test]
    fn symbols_that_are_not_morse_are_rejected() {
        // `..--` isn't a Morse character
        let mut text = Vec::new();
        let digits = [1, 1, 2, 2];
        let groups = split_into_letters(&digits, 0).unwrap();
        assert!(!read_letters(&digits, &groups, 1 << 2, &mut text));
        // `.-.-.-` is a full stop
        let digits = [1, 2, 1, 2, 1, 2];
        let groups = split_into_letters(&digits, 0).unwrap();
        assert!(read_letters(&digits, &groups, 1 << 2, &mut text));
        assert_eq!(text, b".");
    }

