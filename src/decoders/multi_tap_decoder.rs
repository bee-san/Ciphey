/// The Multi-tap decoder, call:
/// `let multi_tap_decoder = Decoder::<MultiTapDecoder>::new()` to create a new instance
/// And then call:
/// `result = multi_tap_decoder.crack(input)` to decode a Multi-tap string
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::multi_tap_decoder::MultiTapDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_multi_tap = Decoder::<MultiTapDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// let result = decode_multi_tap
///     .crack("44 33 555 555 666 0 9 666 777 555 3", &checker)
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "HELLO WORLD");
///
/// // dCode's form: letters joined by hyphens, words separated by spaces
/// let result = decode_multi_tap
///     .crack("44-33-555-555-666 9-666-777-555-3", &checker)
///     .unencrypted_text;
/// assert_eq!(result.unwrap()[0], "HELLO WORLD");
/// ```
pub struct MultiTapDecoder;

/// The letters on keys 2 to 9 (ITU-T E.161). Pressing key `k` `n` times types
/// `KEYS[k - 2][n - 1]`.
const KEYS: [&str; 8] = ["ABC", "DEF", "GHI", "JKL", "MNO", "PQRS", "TUV", "WXYZ"];

/// Fewer letters than this are too likely to be something else, like a score or a date.
const MIN_LETTERS: usize = 3;

impl Crack for Decoder<MultiTapDecoder> {
    fn new() -> Decoder<MultiTapDecoder> {
        Decoder {
            name: "Multi-tap",
            description: "Multi-tap (ABC mode) SMS text: each letter is its phone keypad key pressed once per position, 2=ABC … 9=WXYZ, so 44 is H and 7777 is S; letters are separated by spaces or hyphens and 0 is a space.",
            link: "https://en.wikipedia.org/wiki/Multi-tap",
            tags: vec![
                "multi-tap",
                "multitap",
                "sms",
                "phone",
                "keypad",
                "substitution",
                "decoder",
            ],
            popularity: 0.3,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` as Multi-tap and checks the result with `checker`.
    /// `unencrypted_text` is `None` when `text` isn't Multi-tap.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Multi-tap with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(decoded_text) = decode_multi_tap(text) else {
            debug!("Failed to decode Multi-tap because the text isn't Multi-tap key presses");
            return results;
        };
        trace!("Decoded text for Multi-tap: {:?}", decoded_text);

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Multi-tap because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Decodes Multi-tap key presses to text, or returns `None` if `text` isn't Multi-tap.
fn decode_multi_tap(text: &str) -> Option<String> {
    let bytes = text.trim().as_bytes();
    // Rejects almost every input, on its first byte
    if !bytes.first()?.is_ascii_digit() {
        return None;
    }

    // Pass 1 checks every token without allocating
    let mut tokens = 0;
    let mut letters = 0;
    let mut pressed_twice = false;
    let mut letters_joined = false;
    for token in Tokens::new(bytes) {
        let Token { gap, press } = token.ok()?;
        tokens += 1;
        if let Press::Letter { presses, .. } = press {
            letters += 1;
            pressed_twice |= presses >= 2;
        }
        // A separator on its own between two tokens, as in `44-33`
        letters_joined |= gap.letter_separator && !gap.whitespace && !gap.word_break;
    }
    // Text averages about two presses a letter. Short runs of single digits like `2 3 4 5`
    // are much more likely to be something else.
    if letters < MIN_LETTERS || !pressed_twice {
        return None;
    }

    // Pass 2 writes the text. When separators join the letters of a word (`44-33-555`),
    // whitespace separates words; otherwise whitespace separates letters.
    let mut decoded = String::with_capacity(2 * tokens);
    let mut space = false;
    for Token { gap, press } in Tokens::new(bytes).flatten() {
        space |= gap.word_break || (gap.whitespace && letters_joined);
        match press {
            Press::Space => space = true,
            Press::Letter { letter, .. } => {
                if space && !decoded.is_empty() {
                    decoded.push(' ');
                }
                space = false;
                decoded.push(char::from(letter));
            }
        }
    }
    Some(decoded)
}

/// What one token types.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Press {
    /// An upper-case ASCII letter, and how many times its key was pressed
    Letter {
        /// The letter
        letter: u8,
        /// How many times the key was pressed, 1 to 4
        presses: usize,
    },
    /// `0` or `1`: a space
    Space,
}

/// The separators and whitespace between a token and the one before it.
#[derive(Clone, Copy, Debug, Default)]
struct Gap {
    /// Has `-`, `,`, `;`, `:` or `.`
    letter_separator: bool,
    /// Has a space, tab or form feed
    whitespace: bool,
    /// Has `/`, `|` or a line break
    word_break: bool,
}

/// A token and the gap before it. The first token's gap is empty.
#[derive(Clone, Copy, Debug)]
struct Token {
    /// The gap before the token
    gap: Gap,
    /// What the token types
    press: Press,
}

/// The text has a byte or a token that Multi-tap doesn't write.
#[derive(Debug)]
struct NotMultiTap;

/// Splits Multi-tap text into tokens: a run of one digit (`555`), or a digit with a count
/// (`5*3`). After the first error it returns `None`.
struct Tokens<'a> {
    /// The text
    bytes: &'a [u8],
    /// Where the next gap starts
    pos: usize,
}

impl<'a> Tokens<'a> {
    /// Tokens of `bytes`
    fn new(bytes: &'a [u8]) -> Self {
        Tokens { bytes, pos: 0 }
    }

    /// Reads the next gap and token, or returns `Ok(None)` at the end of the text.
    fn read(&mut self) -> Result<Option<Token>, NotMultiTap> {
        let mut gap = Gap::default();
        let key = loop {
            let Some(&byte) = self.bytes.get(self.pos) else {
                // Separators after the last token, like a final `.`, aren't a gap
                return Ok(None);
            };
            self.pos += 1;
            match byte {
                b'0'..=b'9' => break byte,
                b'-' | b',' | b';' | b':' | b'.' => gap.letter_separator = true,
                b'/' | b'|' | b'\n' | b'\r' => gap.word_break = true,
                b' ' | b'\t' | b'\x0c' => gap.whitespace = true,
                _ => return Err(NotMultiTap),
            }
        };

        // `self.pos` is one past the token's first digit
        let mut presses = 1;
        while self.bytes.get(self.pos) == Some(&key) {
            presses += 1;
            self.pos += 1;
        }
        let press = match self.bytes.get(self.pos) {
            // dCode's count notation: `2*3` or `2^3` is `222`
            Some(b'*' | b'^') if presses == 1 => {
                let count = *self.bytes.get(self.pos + 1).ok_or(NotMultiTap)?;
                if !count.is_ascii_digit() {
                    return Err(NotMultiTap);
                }
                self.pos += 2;
                letter(key, usize::from(count - b'0'))
            }
            _ if matches!(key, b'0' | b'1') => (presses == 1).then_some(Press::Space),
            _ => letter(key, presses),
        };
        // A token ends at a separator or at the end of the text, so mixed digits like `23`
        // and longer counts like `2*33` aren't tokens
        if matches!(self.bytes.get(self.pos), Some(b'0'..=b'9' | b'*' | b'^')) {
            return Err(NotMultiTap);
        }
        let press = press.ok_or(NotMultiTap)?;
        Ok(Some(Token { gap, press }))
    }
}

impl Iterator for Tokens<'_> {
    type Item = Result<Token, NotMultiTap>;

    fn next(&mut self) -> Option<Self::Item> {
        let token = self.read();
        if token.is_err() {
            self.pos = self.bytes.len();
        }
        token.transpose()
    }
}

/// The letter typed by pressing `key` (an ASCII digit) `presses` times, if there is one.
fn letter(key: u8, presses: usize) -> Option<Press> {
    let letters = KEYS.get(usize::from(key.checked_sub(b'2')?))?.as_bytes();
    let letter = *letters.get(presses.checked_sub(1)?)?;
    Some(Press::Letter { letter, presses })
}

