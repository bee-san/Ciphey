//! Decode Multi-tap, the "ABC" text entry of keypad phones. Each letter is written as its
//! ITU-T E.161 key pressed once per position on the key: `2` is ABC, `3` DEF, `4` GHI, `5`
//! JKL, `6` MNO, `7` PQRS, `8` TUV and `9` WXYZ, so `44` is H, `555` is L and `7777` is S.
//! References: <https://en.wikipedia.org/wiki/Multi-tap>,
//! <https://www.dcode.fr/multitap-abc-cipher> and <https://www.dcode.fr/phone-keypad-cipher>.
//!
//! The letters can be written as:
//! * key presses separated by whitespace, with `0` (or `1`, as on some phones) for a space:
//!   `44 33 555 555 666 0 9 666 777 555 3` is `HELLO WORLD`. Python Ciphey and most CTF
//!   writeups use this form.
//! * key presses joined by `-`, `,`, `;`, `:` or `.`, with whitespace between words, as dCode
//!   writes them: `222-666-3-33 9-666-777-555-3` is `CODE WORLD`.
//! * dCode's count notation, `4*2` or `4^2` for `44`.
//!
//! `/`, `|` and line breaks always separate words. The output is upper case, with one space
//! between words and none at either end.
//!
//! Key presses written without separators (`3222666333`) can't be split without a
//! dictionary, so they aren't decoded. Neither is T9 predictive text (one press per
//! letter, `43556` for HELLO), which also needs a dictionary.
//!
//! Call multi_tap_decoder.crack to use. It returns a `CrackResult` whose `unencrypted_text`
//! is `None` when the input isn't Multi-tap.

use crate::checkers::CheckerTypes;
use crate::decoders::interface::check_string_success;

