//! Run an [Ook!](https://esolangs.org/wiki/Ook!) program and return what it prints.
//! Call ook_decoder.crack to use. It returns a `CrackResult` whose `unencrypted_text` is
//! `None` when the input isn't an Ook! program this decoder can run.
//!
//! Ook! (David Morgan-Mar, 2001) is Brainfuck with each instruction written as a pair of
//! the tokens `Ook.`, `Ook?` and `Ook!`:
//!
//! ```text
//! Ook. Ook?  >     Ook? Ook.  <     Ook. Ook.  +     Ook! Ook!  -
//! Ook! Ook.  .     Ook. Ook!  ,     Ook! Ook?  [     Ook? Ook!  ]
//! Ook? Ook?  does nothing
//! ```
//!
//! "Short Ook!" leaves out the `Ook`s and keeps the punctuation (`. ? . .`). Both are read,
//! also mixed, in any case (`ook.`), with any whitespace or none between the tokens
//! (`Ook.Ook?`). The program is translated to Brainfuck and run with the same interpreter
//! and instruction limit as the [Brainfuck decoder](super::brainfuck_interpreter); what it
//! prints is the plaintext.
//!
//! Programs that read input (`Ook. Ook!`), have unmatched loops, print nothing printable,
//! print more than 10,000 bytes or don't stop within the instruction limit are not decoded.

