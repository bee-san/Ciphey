    #[test]
    fn text_is_turned_away_at_its_first_byte_that_isnt_ook() {
        assert_eq!(count_symbols(BENCH_MISS.as_bytes()), None);
        assert_eq!(count_symbols(b"hello world"), None);
        // Morse stops at its first `-`, Brainfuck at its first `+`
        assert_eq!(count_symbols(b".... . .-.. .-.. ---"), None);
        assert_eq!(count_symbols(b"++++++++[>+++++++++++++<-]>.+."), None);
        assert_eq!(count_symbols(b"Ook. Ook, Ook. Ook."), None);
        assert_eq!(count_symbols(b"Ook. Ook"), None);
        // Morse with only dots is all symbols, but too short to run
        assert_eq!(count_symbols(b"... . ..."), Some(7));
        assert_eq!(count_symbols(b".... ...."), Some(8));
        assert_eq!(count_symbols(ISSUE_EXAMPLE.as_bytes()), Some(60));
    }

