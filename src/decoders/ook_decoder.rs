/// The Ook! decoder, call:
/// `let ook_decoder = Decoder::<OokDecoder>::new()` to create a new instance
/// And then call:
/// `result = ook_decoder.crack(input)` to run an Ook! program
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::ook_decoder::OokDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let ook_decoder = Decoder::<OokDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // The Brainfuck program `++++++++[>+++++++++++++<-]>.+.`, from issue #984
/// let program = "Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. \
///     Ook! Ook? Ook. Ook? Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. \
///     Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook. Ook? Ook. \
///     Ook! Ook! Ook? Ook! Ook. Ook? Ook! Ook. Ook. Ook. Ook! Ook.";
/// let result = ook_decoder.crack(program, &checker).unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "hi");
///
/// // The same program in short Ook!, with only the punctuation
/// let short = program.replace("Ook", "");
/// let result = ook_decoder.crack(&short, &checker).unencrypted_text;
/// assert_eq!(result.unwrap()[0], "hi");
/// ```
pub struct OokDecoder;

/// Programs with fewer symbols than this, 8 instructions, aren't run. The shortest useful
/// one, issue #984's `hi`, has 60.
const MIN_SYMBOLS: usize = 16;

/// Output longer than this, in bytes, isn't checked, which keeps the checker call cheap.
/// The instruction limit already bounds it at about 1 MB.
const MAX_OUTPUT_BYTES: usize = 10_000;

impl Crack for Decoder<OokDecoder> {
    fn new() -> Decoder<OokDecoder> {
        Decoder {
            name: "Ook!",
            description: "Ook! is Brainfuck written as pairs of Ook. Ook? Ook! tokens (also the short form with only . ? !). The program is run with the Brainfuck interpreter and its output is the plaintext.",
            link: "https://esolangs.org/wiki/Ook!",
            tags: vec!["ook", "brainfuck", "esoteric", "decoder", "program"],
            popularity: 0.2,
            phantom: std::marker::PhantomData,
        }
    }

    /// Runs `text` as an Ook! program and checks what it prints with `checker`.
    /// `unencrypted_text` is `None` when `text` isn't a program this decoder runs.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Ook! with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(program) = to_brainfuck(text) else {
            debug!("Failed to decode Ook! because the text isn't an Ook! program it can run");
            return results;
        };

        let mut output = Vec::new();
        if let Err(e) = Brainfuck::new(&program)
            .with_instructions_limit(BRAINFUCK_INSTRUCTION_LIMIT)
            .with_output_ref(&mut output)
            .execute()
        {
            debug!("Failed to run Ook! because of error {:?}", e);
            return results;
        }

        // `.` prints every cell, control characters too: output with nothing printable in
        // it, such as the NULs of a program that never sets a cell, isn't text
        if output.len() > MAX_OUTPUT_BYTES || !output.iter().any(|b| (b' '..=b'~').contains(b)) {
            debug!(
                "Failed to decode Ook! because its {} byte output has nothing printable or is too long",
                output.len()
            );
            return results;
        }
        // brainfuck-exe writes each cell as a UTF-8 char, so this is always UTF-8 and cells
        // 128 to 255 come out as U+0080 to U+00FF
        let decoded_text = bytes_to_string(output);

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Ook! because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Translates an Ook! program into Brainfuck. `None` if `text` isn't a program this
/// decoder runs: it isn't made of Ook! tokens, is too short, reads input, has an unmatched
/// loop or never prints.
fn to_brainfuck(text: &str) -> Option<String> {
    let bytes = text.as_bytes();
    let count = count_symbols(bytes)?;
    if count % 2 != 0 || count < MIN_SYMBOLS {
        return None;
    }

    // Every byte is whitespace, part of an `Ook` or a symbol, so the symbols are the bytes
    // that are `.`, `?` or `!`
    let mut symbols = bytes
        .iter()
        .copied()
        .filter(|&b| matches!(b, b'.' | b'?' | b'!'));
    let mut program = String::with_capacity(count / 2);
    let mut depth: usize = 0;
    let mut prints = false;
    while let (Some(first), Some(second)) = (symbols.next(), symbols.next()) {
        let instruction = match (first, second) {
            (b'.', b'?') => '>',
            (b'?', b'.') => '<',
            (b'.', b'.') => '+',
            (b'!', b'!') => '-',
            (b'!', b'.') => {
                prints = true;
                '.'
            }
            (b'!', b'?') => {
                depth += 1;
                '['
            }
            (b'?', b'!') => {
                // A `]` before its `[`. brainfuck-exe only checks that the counts match, and
                // would step back past the start of the program looking for the `[`.
                depth = depth.checked_sub(1)?;
                ']'
            }
            (b'?', b'?') => continue,
            // `Ook. Ook!`, `,`, reads input, which there is none of. The Brainfuck decoder
            // doesn't run such programs either.
            _ => return None,
        };
        program.push(instruction);
    }
    (depth == 0 && prints).then_some(program)
}

/// Counts the symbols (`.`, `?` and `!`) in `text`, written as long tokens (`Ook.`), short
/// ones (`.`) or both. `None` at the first byte that isn't whitespace, an `Ook` followed by
/// a symbol, or a symbol, so most text is turned away at its first byte. Allocates nothing.
fn count_symbols(text: &[u8]) -> Option<usize> {
    let mut count = 0;
    let mut i = 0;
    while i < text.len() {
        if text[i].is_ascii_whitespace() {
            i += 1;
            continue;
        }
        if text
            .get(i..i + 3)
            .is_some_and(|word| word.eq_ignore_ascii_case(b"ook"))
        {
            i += 3;
        }
        match text.get(i) {
            Some(b'.' | b'?' | b'!') => {
                count += 1;
                i += 1;
            }
            _ => return None,
        }
    }
    Some(count)
}

