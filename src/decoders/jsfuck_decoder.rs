    #[test]
    fn strings_are_read_as_javascript_reads_them() {
        let number = |text: &str| string_to_number(&utf16(text));
        assert_eq!(number(""), Ok(0.0));
        assert_eq!(number(" \n\t12\u{a0}"), Ok(12.0));
        assert_eq!(number("1e1000"), Ok(f64::INFINITY));
        assert_eq!(number(".0000000001"), Ok(1e-10));
        assert_eq!(number("0000000001"), Ok(1.0));
        assert_eq!(number("+Infinity"), Ok(f64::INFINITY));
        assert_eq!(number("0x10"), Ok(16.0));
        assert_eq!(number("0o17"), Ok(15.0));
        for text in [
            "inf", "infinity", "nan", "NaN", "1e", "e5", "1_0", "--1", "-0x10", "0x", "0x1g", "1 2",
        ] {
            assert!(number(text).unwrap().is_nan(), "{text:?}");
        }
        assert_eq!(number("0x20000000000001"), Err(Error::Unsupported));

        let literal = |text: &str| {
            string_literal(&utf16(text)).map(|units| String::from_utf16(&units).unwrap())
        };
        assert_eq!(
            literal(r#""\570\101\40\1011\u0041\x41\u{1F600}\8\q\'\"""#).as_deref(),
            Some("/0A A1AA😀8q'\"")
        );
        assert_eq!(literal("\"a\\\nb\\\r\nc\"").as_deref(), Some("abc"));
        assert_eq!(
            literal(r#""\0\b\f\n\r\t\v""#).as_deref(),
            Some("\0\u{8}\u{c}\n\r\t\u{b}")
        );
        // jsfuck.js 0.5.0 writes an emoji as its two surrogates
        assert_eq!(literal(r#""\ud83d\ude00""#).as_deref(), Some("😀"));
        for bad in [
            r#""\x4""#,
            r#""\u004""#,
            r#""\u{}""#,
            r#""\u{110000}""#,
            r#""a"b""#,
            "\"a",
        ] {
            assert_eq!(literal(bad), None, "{bad:?}");
        }
    }

    #[test]
    fn escape_and_unescape_match_javascript() {
        let text = utf16("Az09@*_+-./ <é€~");
        assert_eq!(
            String::from_utf16(&escape(&text)).unwrap(),
            "Az09@*_+-./%20%3C%E9%u20AC%7E"
        );
        assert_eq!(escaped_len(&text), escape(&text).len());
        assert_eq!(unescape(&escape(&text)), text);
        assert_eq!(
            String::from_utf16(&unescape(&utf16("%4b%u20Ac%%2%u12%"))).unwrap(),
            "K€%%2%u12%"
        );
    }

