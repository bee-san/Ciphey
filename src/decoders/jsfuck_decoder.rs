/// The JSFuck decoder, call:
/// `let jsfuck_decoder = Decoder::<JsFuckDecoder>::new()` to create a new instance
/// And then call:
/// `result = jsfuck_decoder.crack(input)` to evaluate a JSFuck expression
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::jsfuck_decoder::JsFuckDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_jsfuck = Decoder::<JsFuckDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // "false"[0] + "undefined"[0] + "undefined"[1]
/// let text = "(![]+[])[+[]]+([][[]]+[])[+[]]+([][[]]+[])[+!+[]]";
/// let result = decode_jsfuck.crack(text, &checker).unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "fun");
/// ```
pub struct JsFuckDecoder;

/// Texts with fewer symbols than this are not worth evaluating. `(![]+[])[+[]]`, one
/// letter, has 13, and jsfuck.js needs at least 33 for two characters.
const MIN_SYMBOLS: usize = 20;

/// Brackets and parentheses nested deeper than this are rejected before parsing. jsfuck.js
/// never nests deeper than 12.
const MAX_NESTING: usize = 64;

/// The most steps the evaluator takes: one per symbol, one per character of every string
/// it makes and [`STEPS_PER_ELEMENT`] per array element. That is about two per symbol of
/// what jsfuck.js writes: the longest test vector, 260,869 symbols, takes 531,422.
const MAX_STEPS: usize = 5_000_000;

/// What making one array element costs in steps. Elements take far more memory than
/// characters, and `split` makes one per character.
const STEPS_PER_ELEMENT: usize = 16;

/// The longest string the evaluator makes, in UTF-16 code units.
const MAX_STRING_LEN: usize = 1_000_000;

impl Crack for Decoder<JsFuckDecoder> {
    fn new() -> Decoder<JsFuckDecoder> {
        Decoder {
            name: "JSFuck",
            description: "JSFuck writes JavaScript with only the six characters []()!+. The expression is evaluated by a small built-in evaluator (no JavaScript engine); code wrapped in Function()() is returned as source, never run.",
            link: "https://github.com/aemkei/jsfuck",
            tags: vec!["jsfuck", "javascript", "esoteric", "decoder", "program"],
            popularity: 0.2,
            phantom: std::marker::PhantomData,
        }
    }

    /// Evaluates `text` as a JSFuck expression and checks the string it gives with
    /// `checker`. The source of a program handed to `Function(...)()` or `eval(...)` is
    /// returned as it is, without running it.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying JSFuck with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let decoded = match decode(text) {
            Ok(decoded) => decoded,
            Err(Error::NotJsFuck) => return results,
            Err(error) => {
                debug!("Failed to decode JSFuck because {error}");
                return results;
            }
        };
        if !check_string_success(&decoded, text) {
            debug!("Failed to decode JSFuck because it evaluates to an empty string");
            return results;
        }

        let checker_result = checker.check(&decoded);
        results.unencrypted_text = Some(vec![decoded]);
        results.update_checker(&checker_result);
        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Why a text didn't decode
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Error {
    /// Rejected without parsing: a character other than `[]()!+` and whitespace, unbalanced
    /// brackets, `++`, nesting deeper than [`MAX_NESTING`] or under [`MIN_SYMBOLS`] symbols
    NotJsFuck,
    /// Not one expression: `([)]`, `()`, `[]+`, `[](`, or more after the expression
    Syntax,
    /// JavaScript the evaluator doesn't know, or that would throw, like calling `undefined`
    Unsupported,
    /// Over [`MAX_STEPS`] steps, or a string over [`MAX_STRING_LEN`] characters
    TooBig,
    /// The value isn't text: an array, a function, `undefined` and so on
    NotText,
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Error::NotJsFuck => "it isn't JSFuck",
            Error::Syntax => "it isn't one JavaScript expression",
            Error::Unsupported => "it uses JavaScript the evaluator doesn't know",
            Error::TooBig => "it takes too long to evaluate or makes too long a string",
            Error::NotText => "its value isn't a string",
        })
    }
}

/// The text `text` evaluates to as a JSFuck expression: the string it gives, or the source
/// of the program it hands to `Function(...)()` or `eval(...)`.
fn decode(text: &str) -> Result<String, Error> {
    let code = symbols(text)?;
    match Evaluator::new(&code).program()? {
        Value::Str(units) | Value::Code(units) => Ok(String::from_utf16_lossy(&units)),
        Value::Num(number) => Ok(number_to_string(number)),
        Value::Bool(boolean) => Ok(boolean.to_string()),
        _ => Err(Error::NotText),
    }
}

/// The symbols of `text` without its whitespace, if one pass over its bytes finds nothing
/// that rules out JSFuck. Text that isn't JSFuck is rejected at its first byte that isn't
/// one of `[]()!+` or whitespace, without allocating.
fn symbols(text: &str) -> Result<Cow<'_, [u8]>, Error> {
    let bytes = text.as_bytes();
    let (mut count, mut square, mut round) = (0usize, 0usize, 0usize);
    let mut spaces = false;
    let mut previous = 0u8;
    for &byte in bytes {
        match byte {
            b'[' => square += 1,
            b'(' => round += 1,
            b']' => square = square.checked_sub(1).ok_or(Error::NotJsFuck)?,
            b')' => round = round.checked_sub(1).ok_or(Error::NotJsFuck)?,
            // `++` is the increment operator, which JSFuck never uses
            b'+' if previous == b'+' => return Err(Error::NotJsFuck),
            b'!' | b'+' => {}
            b' ' | b'\t' | b'\n' | b'\r' | 0x0B | 0x0C => {
                spaces = true;
                previous = byte;
                continue;
            }
            _ => return Err(Error::NotJsFuck),
        }
        if square + round > MAX_NESTING {
            return Err(Error::NotJsFuck);
        }
        previous = byte;
        count += 1;
    }
    if square != 0 || round != 0 || count < MIN_SYMBOLS {
        return Err(Error::NotJsFuck);
    }
    Ok(if spaces {
        Cow::Owned(
            bytes
                .iter()
                .copied()
                .filter(|byte| b"[]()!+".contains(byte))
                .collect(),
        )
    } else {
        Cow::Borrowed(bytes)
    })
}

/// A JavaScript value, as far as JSFuck needs them
#[derive(Debug, PartialEq)]
enum Value {
    /// `undefined`
    Undefined,
    /// `true` or `false`
    Bool(bool),
    /// A number
    Num(f64),
    /// A string, in UTF-16 code units as JavaScript keeps it
    Str(Vec<u16>),
    /// An array
    Arr(Vec<Value>),
    /// A built-in function. A method keeps the value it was read from, which it is called on.
    Native(Builtin, Option<Box<Value>>),
    /// A function made by `Function(body)`, with its body, not run
    Func(Vec<u16>),
    /// What running this JavaScript source gives: unknown, since it is never run. Only the
    /// value of the whole expression may be one.
    Code(Vec<u16>),
    /// A regular expression with this source, from `/0/` or `RegExp("/")`
    RegExp(Vec<u16>),
    /// A `Date`, in milliseconds since 1970
    Date(i64),
    /// What `[]["entries"]()` gives
    ArrayIterator,
    /// An empty object, from `Function("return{}")()` or `Object()`
    Object,
    /// The global object, from `Function("return this")()`
    Global,
}

