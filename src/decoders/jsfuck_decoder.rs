//! Decode JSFuck: JavaScript written with only the six characters `[]()!+`.
//! Call jsfuck_decoder.crack to use. It returns a `CrackResult` whose `unencrypted_text` is
//! `None` unless the text is a JSFuck expression the evaluator understands, and otherwise
//! holds the one string it evaluates to.
//!
//! JSFuck builds values out of almost nothing: `[]` is an array, `![]` is `false`, `+[]` is
//! `0`, `[][[]]` is `undefined` and `[]+[]` is `""`. Characters are picked out of the strings
//! of those values and of built-in functions (`(![]+[])[+[]]` is `"false"[0]`, `f`) and
//! joined with `+`. Characters with no such source come from `String.fromCharCode`,
//! `unescape("%48")` or escapes in `Function('return"\110"')()`. With "Eval Source" the
//! string is a program handed to `Function(...)()` to run.
//!
//! **No JavaScript is ever run.** A small evaluator works out the value of the expression,
//! knowing only the parts of JavaScript that JSFuck uses. A string handed to `Function(...)()`
//! or `eval(...)` comes back as the source it is, so a JSFuck'd program decodes to its
//! source. The function bodies jsfuck.js writes to reach a built-in (`return escape`,
//! `return/0/`, `return"\110"` and so on) are read by a fixed table, not run.
//!
//! It reads the output of every version of [jsfuck.js], the encoder behind
//! <https://jsfuck.com>. They differ in where they get the `Function` constructor and the
//! characters the basic values don't spell:
//!
//! | jsfuck.js | `Function` from | Other characters |
//! | --- | --- | --- |
//! | npm 0.4.0 (2015) | `[]["filter"]` | `unescape("%48")`, `String.fromCharCode`, `new Date(…)` |
//! | 2018 | `[]["fill"]` | `slice("-1")`, `[]["slice"]["call"]`, `link`, `Function("return{}")()` |
//! | 2019 | `[]["fill"]` | `\uXXXX` escapes in `Function('return"…"')()` |
//! | 2020 to 2024 | `[]["flat"]` | `[]["entries"]()["constructor"]` read as `Object` |
//! | 0.5.0 (2025, jsfuck.com today) | `[]["at"]` | `at("-1")`, `\ooo` escapes, `split` and `join` |
//!
//! Anything else is out of scope: other built-ins or property names, `Function` bodies
//! outside the table (they come back as source), `new`, assignment, `toString` with a radix
//! of a fraction. The evaluator gives up on them instead of guessing, so hand-written
//! JSFuck (such as JScrewIt's) that uses other built-ins fails cleanly.
//!
//! The values follow V8 and a browser: built-in functions read as
//! `function at() { [native code] }`, `Function("return this")()` is `[object Window]` and
//! dates are in UTC. `Date()` is always 1 January 1970 rather than the time of the run;
//! jsfuck.js only reads the `GMT` in it. Since engines added Iterator helpers (ES2025)
//! `[]["entries"]()["constructor"]` is `Iterator`; jsfuck.js read `Object` there until 2024,
//! so the evaluator gives `Object`, as the engines of that time did.
//!
//! Before anything is parsed, one pass over the bytes rejects text with any other character,
//! unbalanced brackets, `++` (the increment operator) or nesting deeper than
//! [`MAX_NESTING`]. Every text a search sees that isn't JSFuck stops at its first byte that
//! isn't one of `[]()!+` or whitespace. The evaluator stops after [`MAX_STEPS`] steps or at
//! a string over [`MAX_STRING_LEN`] characters.
//!
//! References: [jsfuck.js] (its `MAPPING`, `SIMPLE` and `CONSTRUCTORS` tables list what has
//! to be modelled), [ECMA-262](https://tc39.es/ecma262/) and
//! <https://github.com/bee-san/Ciphey/issues/987>.
//!
//! [jsfuck.js]: https://github.com/aemkei/jsfuck/blob/6f8fdf31f18a4f2df3bf2576f313b3abeca4c89d/jsfuck.js

