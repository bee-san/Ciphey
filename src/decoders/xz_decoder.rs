    #[test]
    fn long_output_is_only_kept_if_the_checker_accepts_it() {
        let crack_xz = |data: &[u8]| crack(&general_purpose::STANDARD.encode(xz(data)));

        // Not plaintext: handed on for more decoding up to the limit, dropped above it
        let result = crack_xz(&vec![b'A'; MAX_CANDIDATE]);
        assert!(!result.success);
        assert_eq!(result.unencrypted_text.unwrap()[0].len(), MAX_CANDIDATE);
        assert!(crack_xz(&vec![b'A'; MAX_CANDIDATE + 1])
            .unencrypted_text
            .is_none());

        // Plaintext is returned whatever its length (up to MAX_OUTPUT)
        let english = format!("{FOX}. ").repeat(MAX_CANDIDATE / FOX.len() + 1);
        assert!(english.len() > MAX_CANDIDATE);
        let result = crack_xz(english.as_bytes());
        assert!(result.success, "Athena should identify the plaintext");
        assert_eq!(result.unencrypted_text.unwrap(), [english]);
    }

    #[test]
    fn long_nested_files_are_not_handed_on() {
        // Pseudo-random bytes (xorshift64) don't compress, so the inner XZ file is longer
        // than the limit
        let mut state = 0x2545_f491_4f6c_dd1d_u64;
        let noise: Vec<u8> = (0..MAX_CANDIDATE)
            .map(|_| {
                state ^= state << 13;
                state ^= state >> 7;
                state ^= state << 17;
                state as u8
            })
            .collect();
        let inner = xz(&noise);
        assert!(inner.len() > MAX_CANDIDATE);
        let nested = general_purpose::STANDARD.encode(xz(&inner));
        assert!(crack(&nested).unencrypted_text.is_none());
    }

    #[test]
    fn checks_the_lzma_alone_header() {
        let fox = base64_bytes(FOX_LZMA);
        assert_eq!(Container::of(&fox), Some(Container::LzmaAlone));
        assert_eq!(Container::of(&base64_bytes(FOX_XZ)), Some(Container::Xz));

        let with = |position: usize, bytes: &[u8]| {
            let mut header = fox.clone();
            header[position..position + bytes.len()].copy_from_slice(bytes);
            header
        };
        // The smallest dictionary the format allows, and a known size at the limit
        assert!(Container::of(&with(1, &4096u32.to_le_bytes())).is_some());
        assert!(Container::of(&with(5, &(MAX_OUTPUT as u64).to_le_bytes())).is_some());
        for (case, header) in [
            // lc = 0, lp = 2, pb = 0 (xz --lzma1=lc=0,lp=2,pb=0): not recognised
            ("other properties", with(0, &[0x12])),
            ("dictionary under 4 KiB", with(1, &4095u32.to_le_bytes())),
            (
                "size over the limit",
                with(5, &(MAX_OUTPUT as u64 + 1).to_le_bytes()),
            ),
            ("size u64::MAX - 1", with(5, &(u64::MAX - 1).to_le_bytes())),
            ("range coder start", with(13, &[0x80])),
            ("too short", fox[..17].to_vec()),
        ] {
            assert_eq!(Container::of(&header), None, "{case}");
        }
        // An XZ file can't be shorter than a header, an empty index and a footer
        assert_eq!(Container::of(&base64_bytes(FOX_XZ)[..31]), None);
    }

