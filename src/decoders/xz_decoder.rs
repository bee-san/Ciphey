    fn crack(text: &str) -> CrackResult {
        Decoder::<XzDecoder>::new().crack(text, &get_athena_checker())
    }

    /// Runs the decoder and returns the first decoded string, if any
    fn decode(text: &str) -> Option<String> {
        crack(text).unencrypted_text.map(|texts| texts[0].clone())
    }

    fn base64_bytes(text: &str) -> Vec<u8> {
        general_purpose::STANDARD
            .decode(text)
            .expect("valid Base64")
    }

    fn to_hex(bytes: &[u8]) -> String {
        bytes.iter().map(|byte| format!("{byte:02x}")).collect()
    }

    /// `data` as an XZ file made by lzma-rust2's encoder, at preset 0 (a 256 KiB
    /// dictionary) to keep the tests fast
    fn xz(data: &[u8]) -> Vec<u8> {
        let mut writer = XzWriter::new(Vec::new(), XzOptions::with_preset(0)).unwrap();
        writer.write_all(data).unwrap();
        writer.finish().unwrap()
    }

    /// `data` as an LZMA-alone file of unknown size, made by lzma-rust2's encoder
    fn lzma_alone(data: &[u8]) -> Vec<u8> {
        let options = LzmaOptions::with_preset(0);
        let mut writer = LzmaWriter::new_use_header(Vec::new(), &options, None).unwrap();
        writer.write_all(data).unwrap();
        writer.finish().unwrap()
    }

