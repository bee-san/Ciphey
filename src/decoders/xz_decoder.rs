/// Decompressed output above this many bytes is rejected rather than truncated: a
/// fragment of the plaintext isn't the plaintext.
const MAX_OUTPUT: usize = 1024 * 1024;

/// Output the checker didn't accept is only handed on for more decoding up to this many
/// bytes, as in the Gzip decoder: decompressed output isn't bounded by the input's size,
/// and every decoder runs on every node of the search, so a few hundred bytes of XZ could
/// otherwise make a node of a megabyte.
const MAX_CANDIDATE: usize = 16 * 1024;

/// The most memory, in KiB, a file may need to be decompressed, as lzma-rust2 estimates
/// it from the header before allocating anything. It is almost all dictionary: about
/// 8,300 KiB for the default 8 MiB dictionary and 65,640 KiB for the 64 MiB one of
/// `xz -9`, the largest preset, so every preset fits and a header that claims a larger
/// dictionary (96 MiB is already 98,408 KiB) is refused.
const MEM_LIMIT_KB: u32 = 80 * 1024;

/// The magic bytes that start every XZ stream.
const XZ_MAGIC: [u8; 6] = [0xFD, 0x37, 0x7A, 0x58, 0x5A, 0x00];

/// The XZ magic in standard Base64. Six bytes fill exactly eight characters.
const XZ_MAGIC_BASE64: &str = "/Td6WFoA";

/// The XZ magic in URL-safe Base64.
const XZ_MAGIC_BASE64_URL: &str = "_Td6WFoA";

/// The smallest XZ stream: the 12-byte stream header, an index without records (8
/// bytes) and the 12-byte stream footer. `lzma.compress(b"")` is exactly this long.
const MIN_XZ_LEN: usize = 32;

/// The properties byte of an LZMA-alone file this decoder recognises: lc = 3, lp = 0 and
/// pb = 2, the default of every common encoder.
const LZMA_ALONE_PROPS: u8 = 0x5D;

/// The properties byte in Base64: `X` and the first character of the dictionary size,
/// whose low byte is zero for every dictionary size encoders use.
const LZMA_ALONE_BASE64: &str = "XQ";

/// The 13-byte LZMA-alone header and the 5 bytes that start the range decoder.
const MIN_LZMA_ALONE_LEN: usize = 18;

/// The XZ decoder, call:
/// `let xz_decoder = Decoder::<XzDecoder>::new()` to create a new instance
/// And then call:
/// `result = xz_decoder.crack(input)` to decompress XZ or LZMA-alone given as Base64, hex
/// or raw bytes
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::xz_decoder::XzDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_xz = Decoder::<XzDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // Python: base64.b64encode(lzma.compress(b"The quick brown fox jumps over the lazy dog"))
/// let result = decode_xz
///     .crack(
///         "/Td6WFoAAATm1rRGAgAhARYAAAB0L+WjAQAqVGhlIHF1aWNrIGJyb3duIGZveCBqdW1wcyBvdmVyIHRoZSBsYXp5IGRvZwAAxKFK5cK4XlsAAUMrrVBuVx+2830BAAAAAARZWg==",
///         &checker,
///     )
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "The quick brown fox jumps over the lazy dog");
/// ```
pub struct XzDecoder;

impl Crack for Decoder<XzDecoder> {
    fn new() -> Decoder<XzDecoder> {
        Decoder {
            name: "XZ",
            description: "XZ and legacy .lzma files compress data with LZMA. XZ starts with FD 37 7A 58 5A 00, which is /Td6WFo in Base64; .lzma starts with 5D and a dictionary size, XQAA in Base64. Ciphey reads the bytes from Base64, hex or raw text and decompresses them.",
            link: "https://tukaani.org/xz/xz-file-format.txt",
            tags: vec!["xz", "lzma", "compression", "decoder"],
            popularity: 0.4,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decompresses `text` if it is an XZ or LZMA-alone file as Base64, hex or raw bytes,
    /// and checks the decompressed text. Fails (with `unencrypted_text` set to `None`) if
    /// `text` isn't one, doesn't decompress, decompresses to something that is neither
    /// text nor another compressed file, or decompresses to more than [`MAX_CANDIDATE`]
    /// bytes that the checker doesn't accept.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying XZ with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some((container, compressed)) = compressed_bytes(text) else {
            debug!("XZ failed: input is not XZ or LZMA-alone as Base64, hex or raw bytes");
            return results;
        };
        let Some(decompressed) = decompress_bounded(&compressed) else {
            debug!("XZ failed: the data did not decompress");
            return results;
        };

        let Some(decoded_text) = as_plaintext(&decompressed) else {
            // Another compressed file inside: hand it on as raw bytes for the next step
            // (this decoder again, or Gzip, Zlib, Bzip2). It is binary, so there is
            // nothing for the checker to look at.
            if is_compressed(&decompressed) && decompressed.len() <= MAX_CANDIDATE {
                debug!("XZ output is another compressed file; returning it unchecked");
                results.unencrypted_text = Some(vec![latin1_to_string(&decompressed)]);
                results.key = container.key();
            } else {
                info!("Failed to decode XZ: the output is binary, not text");
            }
            return results;
        };
        if !check_string_success(decoded_text, text) {
            info!(
                "Failed to decode XZ because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(decoded_text);
        if !checker_result.is_identified && decoded_text.len() > MAX_CANDIDATE {
            debug!(
                "XZ output is not plaintext and too long ({} bytes) to decode further",
                decoded_text.len()
            );
            return results;
        }
        results.unencrypted_text = Some(vec![decoded_text.to_string()]);
        results.key = container.key();
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// The two file formats this decoder reads.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Container {
    /// An `.xz` file: one or more XZ streams.
    Xz,
    /// A legacy `.lzma` file: the LZMA-alone header and LZMA data.
    LzmaAlone,
}

impl Container {
    /// Which format `bytes` are in, judged from their header without decompressing
    /// anything, or `None` if they are in neither.
    ///
    /// An XZ file has to be long enough for a stream header, an index and a stream
    /// footer and start with the XZ magic; lzma-rust2 checks the rest. An LZMA-alone file
    /// has no magic, so its header is checked instead: the properties byte `5D`, a
    /// dictionary of at least 4 KiB (the format's minimum), an uncompressed size that is
    /// unknown (`u64::MAX`) or at most [`MAX_OUTPUT`], and the zero byte every LZMA range
    /// coder starts with.
    fn of(bytes: &[u8]) -> Option<Container> {
        if bytes.len() >= MIN_XZ_LEN && bytes.starts_with(&XZ_MAGIC) {
            return Some(Container::Xz);
        }
        if bytes.len() < MIN_LZMA_ALONE_LEN || bytes[0] != LZMA_ALONE_PROPS {
            return None;
        }
        let dict_size = u32::from_le_bytes([bytes[1], bytes[2], bytes[3], bytes[4]]);
        let mut size = [0; 8];
        size.copy_from_slice(&bytes[5..13]);
        let size = u64::from_le_bytes(size);
        let plausible = dict_size >= lzma_rust2::DICT_SIZE_MIN
            && (size == u64::MAX || size <= MAX_OUTPUT as u64)
            && bytes[13] == 0x00;
        plausible.then_some(Container::LzmaAlone)
    }

    /// The key for a result from this format. XZ has no key; an LZMA-alone file says so,
    /// so the search path shows which of the two formats it was.
    fn key(self) -> Option<String> {
        match self {
            Container::Xz => None,
            Container::LzmaAlone => Some("LZMA-alone".to_string()),
        }
    }
}

/// Finds XZ or LZMA-alone bytes in `text`: Base64, hex, or raw bytes as Latin-1
/// characters. Only the first few characters are looked at unless they spell the start
/// of one of the two formats.
fn compressed_bytes(text: &str) -> Option<(Container, Vec<u8>)> {
    let trimmed = text.trim();
    let bytes = base64_view(trimmed)
        .or_else(|| hex_view(trimmed))
        .or_else(|| raw_view(text))?;
    let container = Container::of(&bytes)?;
    Some((container, bytes))
}

/// Base64, standard or URL-safe, that starts with the XZ magic (`/Td6WFoA`) or the
/// LZMA-alone properties byte (`XQ`). Whitespace (line breaks) is ignored and padding is
/// optional. `text` is already trimmed.
fn base64_view(text: &str) -> Option<Vec<u8>> {
    if ![XZ_MAGIC_BASE64, XZ_MAGIC_BASE64_URL, LZMA_ALONE_BASE64]
        .iter()
        .any(|prefix| text.starts_with(prefix))
    {
        return None;
    }
    let body: String = text.chars().filter(|c| !c.is_whitespace()).collect();
    let unpadded = body.trim_end_matches('=');
    if body.len() - unpadded.len() > 2 {
        return None;
    }
    // The Base64 decoder's engines. Both reject '=' inside the text.
    general_purpose::STANDARD_NO_PAD
        .decode(unpadded)
        .or_else(|_| general_purpose::URL_SAFE_NO_PAD.decode(unpadded))
        .ok()
}

/// Hex that starts with the XZ magic (`fd377a585a00`) or the LZMA-alone properties byte
/// (`5d`), in any case. Bytes can be separated by whitespace, `:`, `,`, `;`, `-` or `%`,
/// and each can have a `0x` or `\x` prefix. `text` is already trimmed.
fn hex_view(text: &str) -> Option<Vec<u8>> {
    // Cheap gate: the first digits have to spell one of the two starts
    if !starts_with_hex(text, &XZ_MAGIC) && !starts_with_hex(text, &[LZMA_ALONE_PROPS]) {
        return None;
    }

    let mut bytes = Vec::with_capacity(text.len() / 2);
    let mut digits = HexDigits::new(text.as_bytes());
    while let Some(high) = digits.next() {
        // A character that isn't hex or a separator, or an odd number of digits
        let (high, low) = (high?, digits.next()??);
        bytes.push((high << 4) | low);
    }
    Some(bytes)
}

/// Whether the hex digits at the start of `text` spell `prefix`. Reads no further than
/// that, and allocates nothing.
fn starts_with_hex(text: &str, prefix: &[u8]) -> bool {
    let mut digits = HexDigits::new(text.as_bytes());
    prefix.iter().all(|&byte| {
        digits.next() == Some(Some(byte >> 4)) && digits.next() == Some(Some(byte & 0x0F))
    })
}

/// XZ or LZMA-alone bytes as Latin-1 text, one character per byte. The Hexadecimal and
/// Binary decoders turn bytes that aren't UTF-8 (these formats never are) into this, and
/// so does this decoder for a compressed file inside a compressed file. Not trimmed: the
/// bytes can end with what looks like whitespace.
fn raw_view(text: &str) -> Option<Vec<u8>> {
    if !starts_with_latin1(text, &XZ_MAGIC) && !starts_with_latin1(text, &[LZMA_ALONE_PROPS]) {
        return None;
    }
    text.chars().map(|c| u8::try_from(c).ok()).collect()
}

/// Whether `text` starts with `prefix`, one Latin-1 character per byte.
fn starts_with_latin1(text: &str, prefix: &[u8]) -> bool {
    let mut chars = text.chars();
    prefix
        .iter()
        .all(|&byte| chars.next() == Some(char::from(byte)))
}

/// Iterates over the hex digits of a hex string, skipping the separators and prefixes
/// [`hex_view`] allows. Yields `Some(digit)` for each digit, and `None` for a character
/// that doesn't belong in hex. Separators and prefixes are only allowed between bytes.
/// The same as the Gzip decoder's.
struct HexDigits<'a> {
    /// The text being read.
    bytes: &'a [u8],
    /// Index of the next unread byte.
    position: usize,
    /// Whether the last digit read was the first half of a byte.
    mid_byte: bool,
}

impl<'a> HexDigits<'a> {
    /// Starts reading at the beginning of `bytes`.
    fn new(bytes: &'a [u8]) -> Self {
        HexDigits {
            bytes,
            position: 0,
            mid_byte: false,
        }
    }
}

impl Iterator for HexDigits<'_> {
    type Item = Option<u8>;

    fn next(&mut self) -> Option<Self::Item> {
        loop {
            let byte = *self.bytes.get(self.position)?;
            let next = self.bytes.get(self.position + 1).copied();
            if let Some(digit) = char::from(byte).to_digit(16) {
                if !self.mid_byte && byte == b'0' && matches!(next, Some(b'x' | b'X')) {
                    // A 0x prefix
                    self.position += 2;
                    continue;
                }
                self.position += 1;
                self.mid_byte = !self.mid_byte;
                return Some(Some(digit as u8));
            }
            let is_prefix = byte == b'\\' && matches!(next, Some(b'x' | b'X'));
            let is_separator = byte.is_ascii_whitespace() || b":,;-%".contains(&byte);
            if self.mid_byte || !(is_prefix || is_separator) {
                // Stop for good after the first bad character
                self.position = self.bytes.len();
                return Some(None);
            }
            self.position += if is_prefix { 2 } else { 1 };
        }
    }
}

/// Decompresses an XZ or LZMA-alone file, the way `xz -d` does.
///
/// The whole input has to be one file: for XZ, one or more complete streams, optionally
/// with stream padding (groups of four zero bytes) between and after them, each passing
/// its checks; for LZMA-alone, the header and LZMA data that ends exactly where the input
/// does. Returns `None` if the bytes are in neither format, are corrupt or truncated, have
/// anything after the end, need more than [`MEM_LIMIT_KB`] of memory (checked against
/// the header before the dictionary is allocated) or decompress to more than
/// [`MAX_OUTPUT`] bytes. Decompression stops at that limit, so a bomb costs about as much
/// as decompressing [`MAX_OUTPUT`] bytes.
fn decompress_bounded(compressed: &[u8]) -> Option<Vec<u8>> {
    match Container::of(compressed)? {
        Container::Xz => {
            // Concatenated streams are one file to `xz -d`, so they are here too. Anything
            // after the last stream that isn't stream padding or another stream is an
            // error.
            let mut stream = XzStream::new_mem_limit(true, MEM_LIMIT_KB);
            decompress_with(compressed, |input, output| {
                stream.process(input, output, Action::Finish)
            })
        }
        Container::LzmaAlone => {
            let mut stream = LzmaStream::new_mem_limit(MEM_LIMIT_KB, None);
            let output = decompress_with(compressed, |input, output| {
                stream.process(input, output, Action::Finish)
            })?;
            // The decoder takes in up to 40 bytes past the end of the LZMA data and hands
            // them back here. Like `xz -d`, a file with anything after its end is refused.
            if !stream.unused_input().is_empty() {
                debug!("LZMA-alone data is followed by trailing bytes");
                return None;
            }
            Some(output)
        }
    }
}

/// Feeds all of `input` to a sans-I/O lzma-rust2 decoder through `process`, collecting at
/// most [`MAX_OUTPUT`] bytes of output.
///
/// The output buffer starts at four times the input's size and doubles when the decoder
/// fills it, up to one byte over the limit, which tells an output of exactly
/// [`MAX_OUTPUT`] bytes apart from a longer one. Fails if the decoder reports an error,
/// stops making progress before the end of the stream (truncated input), stops before the
/// end of the input, or writes more than [`MAX_OUTPUT`] bytes.
fn decompress_with(
    input: &[u8],
    mut process: impl FnMut(&[u8], &mut [u8]) -> lzma_rust2::Result<StreamResult>,
) -> Option<Vec<u8>> {
    const CAPACITY: usize = MAX_OUTPUT + 1;
    let mut output = vec![0; input.len().saturating_mul(4).clamp(64, CAPACITY)];
    let (mut consumed, mut produced) = (0, 0);
    loop {
        let result = match process(&input[consumed..], &mut output[produced..]) {
            Ok(result) => result,
            Err(error) => {
                debug!("XZ data failed to decompress: {}", error);
                return None;
            }
        };
        consumed += result.bytes_consumed;
        produced += result.bytes_produced;
        if result.status == Status::StreamEnd {
            break;
        }
        if produced == output.len() {
            if produced > MAX_OUTPUT {
                debug!("XZ output is over {} bytes, giving up", MAX_OUTPUT);
                return None;
            }
            output.resize((output.len() * 2).min(CAPACITY), 0);
        } else if result.bytes_consumed == 0 && result.bytes_produced == 0 {
            // The decoder has all of the input and room for output, and is stuck
            debug!("XZ data ends before its stream does");
            return None;
        }
    }
    if produced > MAX_OUTPUT {
        debug!("XZ output is over {} bytes, giving up", MAX_OUTPUT);
        return None;
    }
    if consumed != input.len() {
        debug!("XZ data is followed by trailing bytes");
        return None;
    }
    output.truncate(produced);
    Some(output)
}

/// Whether binary output is itself a compressed file that a decoder reads from raw
/// bytes: XZ or LZMA-alone again (as [`Container::of`] judges it), gzip (`1F 8B 08`),
/// bzip2 (`BZh` and a block size digit) or zlib (`78` and a valid RFC 1950 header, the
/// first byte the Zlib decoder's raw view wants).
fn is_compressed(bytes: &[u8]) -> bool {
    let is_bzip2 = bytes.len() > 3 && bytes.starts_with(b"BZh") && matches!(bytes[3], b'1'..=b'9');
    let is_zlib = bytes.len() >= 8
        && bytes[0] == 0x78
        && u16::from_be_bytes([bytes[0], bytes[1]]).is_multiple_of(31)
        && bytes[1] & 0x20 == 0;
    Container::of(bytes).is_some() || bytes.starts_with(&[0x1F, 0x8B, 0x08]) || is_bzip2 || is_zlib
}

/// The decompressed bytes as text, if they are UTF-8 text without control characters
/// other than tab, line feed and carriage return. Binary files are rejected.
fn as_plaintext(data: &[u8]) -> Option<&str> {
    let text = std::str::from_utf8(data).ok()?;
    let is_text = !text
        .chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\n' | '\r'));
    is_text.then_some(text)
}

/// One character per byte, U+0000 to U+00FF. The inverse of [`raw_view`].
fn latin1_to_string(bytes: &[u8]) -> String {
    bytes.iter().map(|&byte| char::from(byte)).collect()
}

