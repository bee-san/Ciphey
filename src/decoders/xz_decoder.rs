//! Decompress XZ (`.xz`) and legacy LZMA (`.lzma`, "LZMA-alone") files.
//!
//! Both are containers for LZMA-compressed data:
//! * XZ (xz-utils, 7-Zip, Python's `lzma.compress`) starts with the stream header magic
//!   `FD 37 7A 58 5A 00`, which is `/Td6WFoA` in Base64. Its blocks hold LZMA2 data and a
//!   CRC-32, CRC-64 or SHA-256 check of it (or no check), and streams can be concatenated.
//! * LZMA-alone (`xz --format=lzma`, Python's `FORMAT_ALONE`, the LZMA SDK) is a 13-byte
//!   header, a properties byte, the dictionary size and the uncompressed size (all `FF` if
//!   it isn't known), followed by LZMA data without a checksum. The properties byte is
//!   almost always `5D`, so these files start with `XQ` in Base64 (`XQAAgAD/////////` with
//!   the default 8 MiB dictionary).
//!
//! Ciphey passes text between decoders, and compressed data is binary, so this decoder
//! reads the bytes itself from three textual forms:
//! * Base64 (standard or URL-safe, line breaks allowed),
//! * hex (optionally split into bytes by whitespace, `:`, `,`, `;`, `-` or `%`, or
//!   prefixed with `0x` or `\x`),
//! * the raw bytes as Latin-1 text, which is what the Hexadecimal and Binary decoders
//!   emit for bytes that aren't UTF-8, and what this decoder hands on when an XZ file
//!   holds another compressed file.
//!
//! Each form is recognised from its first few characters, so other text is rejected
//! without decoding or copying it. Decompression refuses dictionaries that need more than
//! [`MEM_LIMIT_KB`] before allocating them and stops at [`MAX_OUTPUT`] bytes, so a bomb
//! fails quickly instead of eating memory, and output the checker doesn't accept is only
//! passed on for more decoding up to [`MAX_CANDIDATE`] bytes.
//!
//! `.lzma` files with a properties byte other than `5D` (other lc/lp/pb settings) are not
//! recognised. xz, 7-Zip, Python and lzma-rust2 all write `5D` unless told otherwise, and
//! accepting any first byte would let far more text that isn't LZMA past the first check.
//!
//! Call `xz_decoder.crack` to use. It returns a [`CrackResult`]; check
//! `result.unencrypted_text.is_some()` to see if it decoded.

