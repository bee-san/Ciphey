    #[test]
    fn django_style_cookie_decodes() {
        // django.core.signing.dumps(compress=True) uses the same "." marker with ":" as the
        // separator: .<base64url(zlib(json))>:<timestamp>:<signature>
        let json = r#"{"message":"attack at dawn, attack at dawn, attack at dawn"}"#;
        let payload = general_purpose::URL_SAFE_NO_PAD.encode(compress(json.as_bytes()));
        let cookie = format!(".{payload}:1u5PcM:Z2o3cWdQb1dGb2V5aWxqbnJ0eF9fc2lnbmF0dXJl");
        assert_eq!(decoded(&cookie).as_deref(), Some(json));
        // and with nothing after the payload
        assert_eq!(decoded(&format!(".{payload}")).as_deref(), Some(json));
    }

