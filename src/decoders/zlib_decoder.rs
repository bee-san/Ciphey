    #[test]
    fn nested_zlib_is_passed_on_as_raw_bytes() {
        // base64.b64encode(zlib.compress(zlib.compress(FOX)))
        let outer = crack(
            "eJwBMgDN/3icC8lIVSgszUzOVkgqyi/PU0jLr1DIKs0tKFbIL0stUigBSuckVlUqpOSnAwBb3A/aExYUhg==",
        );
        assert!(!outer.success);
        let inner = outer.unencrypted_text.unwrap().remove(0);
        // one Latin-1 character per byte of the inner stream
        let inner_bytes: Vec<u8> = inner.chars().map(|c| u8::try_from(c).unwrap()).collect();
        assert_eq!(inner_bytes, hex_to_bytes(FOX_HEX));

        let result = crack(&inner);
        assert_eq!(result.unencrypted_text.unwrap()[0], FOX);
        assert!(result.success);
    }

    #[test]
    fn hexadecimal_output_is_read_as_raw_bytes() {
        // The Hexadecimal decoder turns the stream into Latin-1 text, which Zlib reads back
        let hexadecimal = Decoder::<HexadecimalDecoder>::new();
        let latin1 = hexadecimal
            .crack(FOX_HEX, &get_athena_checker())
            .unencrypted_text
            .unwrap()
            .remove(0);
        assert!(latin1.starts_with('x'));
        assert_eq!(decoded(&latin1).as_deref(), Some(FOX));

        // zlib.compress(b"data fox", 1) happens to be valid UTF-8 ("˯" is U+02EF), so the
        // Hexadecimal decoder returns it as UTF-8 instead of Latin-1
        let utf8 = hexadecimal
            .crack("78014b492c495448cbaf00000d740308", &get_athena_checker())
            .unencrypted_text
            .unwrap()
            .remove(0);
        assert!(utf8.contains('\u{2EF}'));
        assert_eq!(decoded(&utf8).as_deref(), Some("data fox"));
    }

