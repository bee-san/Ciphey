/// Largest output we inflate, in bytes. Anything longer is treated as a failure (a zip
/// bomb, or text far too long to be the answer) instead of being truncated.
const MAX_OUTPUT: u64 = 1 << 20;

/// The shortest zlib stream: 2 header bytes, an empty final DEFLATE block (2 bytes) and
/// the 4-byte Adler-32 checksum. `zlib.compress(b"")` is exactly this long.
const MIN_STREAM_LEN: usize = 8;

/// Most JSON string values the checker is run on.
const MAX_JSON_VALUES: usize = 32;

/// How deep into nested JSON objects and arrays we look for string values.
const MAX_JSON_DEPTH: usize = 3;

/// Shorter JSON string values (`"admin"`, `"true"`) are not worth checking.
const MIN_JSON_VALUE_CHARS: usize = 6;

/// The Zlib decoder, call:
/// `let zlib_decoder = Decoder::<ZlibDecoder>::new()` to create a new instance
/// And then call:
/// `result = zlib_decoder.crack(input)` to inflate a zlib stream
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::zlib_decoder::ZlibDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_zlib = Decoder::<ZlibDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // Python: base64.b64encode(zlib.compress(b"The quick brown fox jumps over the lazy dog"))
/// let result = decode_zlib
///     .crack("eJwLyUhVKCzNTM5WSCrKL89TSMuvUMgqzS0oVsgvSy1SKAFK5yRWVSqk5KcDAFvcD9o=", &checker)
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "The quick brown fox jumps over the lazy dog");
/// ```
pub struct ZlibDecoder;

impl Crack for Decoder<ZlibDecoder> {
    fn new() -> Decoder<ZlibDecoder> {
        Decoder {
            name: "Zlib",
            description: "Zlib (RFC 1950) wraps DEFLATE-compressed data in a two-byte header and an Adler-32 checksum. It is used in PDF and PNG streams, git objects and Flask session cookies. Ciphey reads the compressed bytes from Base64, hex or raw text and inflates them.",
            link: "https://datatracker.ietf.org/doc/html/rfc1950",
            tags: vec!["zlib", "deflate", "compression", "decoder"],
            popularity: 0.5,
            phantom: std::marker::PhantomData,
        }
    }

    /// Inflates the zlib stream in `text` and runs the checker on the output.
    /// The result has no text unless `text` holds one complete, valid zlib stream that
    /// inflates to text, or to another compressed stream.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Zlib with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(inflated) = inflate_text(text) else {
            trace!("Zlib: the input is not a zlib stream");
            return results;
        };

        // A git loose object is "<type> <size>\0<body>": the body is the content.
        let (body, git_type) = match split_git_object(&inflated) {
            Some((git_type, body)) => (body, Some(git_type)),
            None => (inflated.as_slice(), None),
        };

        let Some(plaintext) = as_text(body) else {
            if is_compressed(body) {
                // Compressed twice. Pass the inner stream on one character per byte
                // (Latin-1), which the next Zlib step reads back as raw bytes.
                debug!("Zlib output is another compressed stream");
                results.unencrypted_text =
                    Some(vec![body.iter().copied().map(char::from).collect()]);
                results.key = git_type.map(String::from);
            } else {
                debug!("Zlib output is binary, not text");
            }
            return results;
        };

        if !check_string_success(plaintext, text) {
            debug!("Zlib output is empty");
            return results;
        }
        results.key = git_type.map(String::from);

        let mut checker_result = checker.check(plaintext);
        if !checker_result.is_identified {
            // A Flask session is JSON, which the checkers don't recognise as a whole,
            // but a value inside it (a flag, a URL, an email address) they may.
            if let Some(hit) = check_json_values(plaintext, checker) {
                checker_result = hit;
            }
        }
        results.unencrypted_text = Some(vec![plaintext.to_string()]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Finds a zlib stream in `text` (cookie, Base64, hex or raw bytes) and inflates it.
///
/// Which view applies is decided by the first characters, before anything is allocated.
fn inflate_text(text: &str) -> Option<Vec<u8>> {
    let trimmed = text.trim();
    if let Some(cookie) = trimmed.strip_prefix('.') {
        // itsdangerous (Flask) and Django mark a compressed payload with a leading `.`
        let payload = cookie.split(['.', ':']).next()?;
        if !starts_like_zlib_base64(payload) {
            return None;
        }
        return inflate_bounded(&base64_bytes(payload)?);
    }
    if starts_like_zlib_base64(trimmed) {
        return inflate_bounded(&base64_bytes(trimmed)?);
    }
    if starts_like_zlib_hex(trimmed) {
        return inflate_bounded(&hex_bytes(trimmed)?);
    }
    // Raw bytes are not trimmed: the stream can end with bytes that look like whitespace.
    if text.starts_with('x') && looks_binary(text) {
        if let Some(stream) = latin1_bytes(text) {
            if let Some(inflated) = inflate_bounded(&stream) {
                return Some(inflated);
            }
        }
        // Hexadecimal and Binary return UTF-8 instead of Latin-1 when the bytes are UTF-8
        if !text.is_ascii() {
            return inflate_bounded(text.as_bytes());
        }
    }
    None
}

/// Whether `text` starts with the Base64 of a `78 01`, `78 5E`, `78 9C` or `78 DA` header.
fn starts_like_zlib_base64(text: &str) -> bool {
    matches!(text.as_bytes(), [b'e', b'A' | b'F' | b'J' | b'N', ..])
}

/// Whether `text` starts with the hex of a `78` header byte, after an optional `0x` / `\x`.
fn starts_like_zlib_hex(text: &str) -> bool {
    let digits = ["0x", "0X", "\\x", "\\X"]
        .iter()
        .find_map(|prefix| text.strip_prefix(prefix))
        .unwrap_or(text);
    digits.starts_with("78")
}

/// Whether `text` contains a character that ordinary text doesn't but compressed bytes
/// almost always do: a control character other than tab and line breaks, or non-ASCII.
/// This keeps plain text that starts with an `x` ("xylophone") away from the raw view.
fn looks_binary(text: &str) -> bool {
    text.chars()
        .any(|c| !c.is_ascii() || (c.is_ascii_control() && !matches!(c, '\t' | '\n' | '\r')))
}

/// One byte per character, if every character is at most U+00FF (Latin-1).
fn latin1_bytes(text: &str) -> Option<Vec<u8>> {
    text.chars().map(|c| u8::try_from(c).ok()).collect()
}

/// Decodes standard or URL-safe Base64, ignoring whitespace and up to two `=` of padding.
/// Uses the same engines as the Base64 decoder.
fn base64_bytes(text: &str) -> Option<Vec<u8>> {
    let mut compact = String::with_capacity(text.len());
    for c in text.chars().filter(|c| !c.is_ascii_whitespace()) {
        if !(c.is_ascii_alphanumeric() || matches!(c, '+' | '/' | '-' | '_' | '=')) {
            return None;
        }
        compact.push(c);
    }
    let unpadded = compact.trim_end_matches('=');
    if compact.len() - unpadded.len() > 2 || unpadded.contains('=') {
        return None;
    }
    let engine = if unpadded.contains(['-', '_']) {
        &general_purpose::URL_SAFE_NO_PAD
    } else {
        &general_purpose::STANDARD_NO_PAD
    };
    engine.decode(unpadded).ok()
}

/// Decodes hex, ignoring whitespace, `:` and `,` between bytes and `0x` / `\x` prefixes.
fn hex_bytes(text: &str) -> Option<Vec<u8>> {
    let mut nibbles = Vec::with_capacity(text.len());
    let mut rest = text.as_bytes();
    while let Some((&first, tail)) = rest.split_first() {
        if matches!(first, b'0' | b'\\') && matches!(tail.first(), Some(b'x' | b'X')) {
            rest = &tail[1..];
            continue;
        }
        match first {
            b'0'..=b'9' => nibbles.push(first - b'0'),
            b'a'..=b'f' => nibbles.push(first - b'a' + 10),
            b'A'..=b'F' => nibbles.push(first - b'A' + 10),
            b':' | b',' => {}
            _ if first.is_ascii_whitespace() => {}
            _ => return None,
        }
        rest = tail;
    }
    if nibbles.is_empty() || nibbles.len() % 2 != 0 {
        return None;
    }
    let (pairs, _) = nibbles.as_chunks::<2>();
    Some(pairs.iter().map(|&[high, low]| (high << 4) | low).collect())
}

/// The RFC 1950 header check (section 2.2): compression method 8 (DEFLATE), a window of
/// at most 32 KiB (CINFO <= 7), the two header bytes a multiple of 31 as a big-endian
/// number, and no preset dictionary (FDICT), which we wouldn't have.
fn has_zlib_header(stream: &[u8]) -> bool {
    let &[cmf, flg, ..] = stream else {
        return false;
    };
    stream.len() >= MIN_STREAM_LEN
        && cmf & 0x0F == 8
        && cmf >> 4 <= 7
        && u16::from_be_bytes([cmf, flg]) % 31 == 0
        && flg & 0x20 == 0
}

/// Inflates `stream` if it is exactly one complete zlib stream: a valid header, a DEFLATE
/// body that inflates without error to at most `MAX_OUTPUT` bytes, a matching Adler-32
/// checksum and nothing after it.
fn inflate_bounded(stream: &[u8]) -> Option<Vec<u8>> {
    if !has_zlib_header(stream) {
        return None;
    }
    let mut inflater = Inflater::new(stream);
    let mut output = Vec::new();
    // flate2 reports a bad checksum, a truncated stream or a preset dictionary as an
    // error. Reading one byte past the cap tells "exactly MAX_OUTPUT" from "more".
    inflater
        .by_ref()
        .take(MAX_OUTPUT + 1)
        .read_to_end(&mut output)
        .ok()?;
    if output.len() as u64 > MAX_OUTPUT {
        debug!("Zlib output is over {MAX_OUTPUT} bytes");
        return None;
    }
    // flate2 stops at the end of the stream without looking at what follows it, so
    // check that the stream used up the whole input.
    if inflater.total_in() != stream.len() as u64 {
        return None;
    }
    Some(output)
}

/// Splits a git loose object, `<type> <size>\0<body>`, into a name for its type and its
/// body. The size has to match the body.
fn split_git_object(object: &[u8]) -> Option<(&'static str, &[u8])> {
    // The longest header is "commit " and a 20 digit size
    let nul = object.iter().take(32).position(|&byte| byte == 0)?;
    let header = std::str::from_utf8(&object[..nul]).ok()?;
    let body = &object[nul + 1..];
    let (object_type, size) = header.split_once(' ')?;
    let name = match object_type {
        "blob" => "git blob",
        "tree" => "git tree",
        "commit" => "git commit",
        "tag" => "git tag",
        _ => return None,
    };
    // parse() would also accept a leading `+`
    if size.is_empty() || !size.bytes().all(|byte| byte.is_ascii_digit()) {
        return None;
    }
    (size.parse::<usize>().ok()? == body.len()).then_some((name, body))
}

/// `bytes` as text, if they are UTF-8 without control characters other than tab and line
/// breaks.
fn as_text(bytes: &[u8]) -> Option<&str> {
    let text = std::str::from_utf8(bytes).ok()?;
    text.chars()
        .all(|c| !c.is_control() || matches!(c, '\t' | '\n' | '\r'))
        .then_some(text)
}

/// Whether binary output is itself compressed: another zlib stream (starting with `78`,
/// like the raw view expects), or a gzip member (`1F 8B 08`).
fn is_compressed(bytes: &[u8]) -> bool {
    (bytes.first() == Some(&0x78) && has_zlib_header(bytes))
        || bytes.starts_with(&[0x1F, 0x8B, 0x08])
}

/// If `text` is a JSON object, runs the checker on its string values (up to
/// `MAX_JSON_VALUES` of them, `MAX_JSON_DEPTH` deep, each at least `MIN_JSON_VALUE_CHARS`
/// long) and returns the first one it identifies.
fn check_json_values(text: &str, checker: &CheckerTypes) -> Option<CheckResult> {
    if !text.trim_start().starts_with('{') {
        return None;
    }
    let json: Value = serde_json::from_str(text).ok()?;
    let mut values = Vec::new();
    collect_json_strings(&json, 0, &mut values);
    values
        .into_iter()
        .map(|value| checker.check(value))
        .find(|result| result.is_identified)
}

/// Collects the string values worth checking in `value`, which is `depth` levels deep.
fn collect_json_strings<'a>(value: &'a Value, depth: usize, strings: &mut Vec<&'a str>) {
    if strings.len() >= MAX_JSON_VALUES {
        return;
    }
    match value {
        Value::String(string) if string.chars().count() >= MIN_JSON_VALUE_CHARS => {
            strings.push(string)
        }
        Value::Array(items) if depth < MAX_JSON_DEPTH => {
            for item in items {
                collect_json_strings(item, depth + 1, strings);
            }
        }
        Value::Object(map) if depth < MAX_JSON_DEPTH => {
            for item in map.values() {
                collect_json_strings(item, depth + 1, strings);
            }
        }
        _ => {}
    }
}

