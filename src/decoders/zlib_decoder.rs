//! Decode zlib streams (RFC 1950): a 2-byte header, a DEFLATE body (RFC 1951) and a
//! big-endian Adler-32 checksum of the uncompressed data.
//! Call zlib_decoder.crack to use. It returns a `CrackResult`; check
//! `result.unencrypted_text.is_some()` to see if it decoded.
//!
//! Zlib turns up in PDF `FlateDecode` streams, git loose objects, Flask session cookies
//! (`.eJ…`) and many CTF challenges. Compressed data is binary and Ciphey passes text
//! between decoders (the Base64 decoder drops output that isn't UTF-8), so this decoder
//! reads the compressed bytes itself, from one of these views of its input:
//!
//! * a signed cookie, `.<payload>.<timestamp>.<signature>` (Flask/itsdangerous) or
//!   `.<payload>:<timestamp>:<signature>` (Django): only the Base64url payload is read,
//!   the signature is not checked,
//! * Base64, standard or URL-safe, with or without padding and line breaks,
//! * hex, optionally split by whitespace, `:` or `,`, with or without `0x` / `\x` prefixes,
//! * raw bytes, as the text the Hexadecimal and Binary decoders produce for binary data
//!   (one Latin-1 character per byte, or UTF-8 when the bytes happen to be UTF-8).
//!
//! Each view has to start with a zlib header, which in practice is `78 01`, `78 5E`,
//! `78 9C` or `78 DA` (`eA`, `eF`, `eJ`, `eN` in Base64), so other text is rejected after
//! looking at its first characters. The stream then has to pass the RFC 1950 header
//! check, inflate without error, match its Adler-32 checksum and end exactly where the
//! input ends, so random text that happens to start like a zlib stream is not "decoded".

