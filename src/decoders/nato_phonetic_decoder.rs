    // helper for tests
    fn get_athena_checker() -> CheckerTypes {
        let athena_checker = Checker::<Athena>::new();
        CheckerTypes::CheckAthena(athena_checker)
    }

    /// Runs the decoder with the Athena checker
    fn crack(text: &str) -> CrackResult {
        let result = Decoder::<NatoPhoneticDecoder>::new().crack(text, &get_athena_checker());
        if result.unencrypted_text.is_none() {
            assert!(!result.success, "{text:?} failed but was marked successful");
        }
        result
    }

    /// Asserts that Athena identifies what `text` decodes to, and that it is `expected`
    fn assert_identified(text: &str, expected: &str) {
        let result = crack(text);
        assert_eq!(
            result.unencrypted_text.as_deref(),
            Some(&[expected.to_string()][..]),
            "decoding {text:?}"
        );
        assert!(result.success, "Athena should identify {expected:?}");
    }

    /// Asserts that `text` decodes to `expected`, whether or not Athena identifies it
    fn assert_decodes(text: &str, expected: &str) {
        assert_eq!(
            crack(text).unencrypted_text.as_deref(),
            Some(&[expected.to_string()][..]),
            "decoding {text:?}"
        );
    }

    /// Asserts that `text` isn't decoded at all
    fn assert_rejected(text: &str) {
        assert_eq!(crack(text).unencrypted_text, None, "decoding {text:?}");
    }

