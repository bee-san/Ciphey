    #[test]
    fn two_word_code_words_need_both_halves() {
        assert_rejected("Alfa Bravo X");
        assert_rejected("Alfa Bravo Full");
        assert_rejected("Alfa Bravo Fraction");
        assert_rejected("Alfa Bravo Ray");
        assert_rejected("Alfa Bravo Full / stop");
        // A joined word's halves have to be in the same word: in a joined text `stop` is
        // the next word and `Full` on its own isn't a code word
        assert_rejected("Tango-Oscar-Romeo-Charlie-Hotel-Full stop");
        assert_decodes("Tango-Oscar-Romeo-Charlie-Hotel-Full-stop", "torch.");
        assert_decodes("Alfa-Bravo-Fraction-Bar", "ab/");
    }

