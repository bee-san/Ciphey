//! Decode text spelled out with the NATO phonetic alphabet, the ICAO radiotelephony
//! spelling alphabet: `Hotel Echo Lima Lima Oscar` is `hello`.
//! Call nato_phonetic_decoder.crack to use. It returns a `CrackResult` whose
//! `unencrypted_text` is `None` when the input isn't NATO text.
//!
//! Every code word stands for one character: the first letter of the 26 letter words, the
//! digit of the digit words. These spellings are read, in any case:
//! * letters: the ICAO words, plus `Alpha`, `Juliet`, `Whisky`, and `Xray` or `X-ray`;
//! * digits: the ICAO words (`Zero` … `Nine`), the ITU/IMO compounds (`Nadazero`, `Unaone`,
//!   `Bissotwo`, `Terrathree`, `Kartefour`, `Pantafive`, `Soxisix`, `Setteseven`,
//!   `Oktoeight`, `Novenine`) and the spoken forms (`Wun`, `Too`, `Tree`, `Fower`, `Fife`,
//!   `Ait`, `Niner`);
//! * punctuation: `Comma` is `,`; `Stop`, `Full stop`, `Decimal` and `Point` are `.`;
//!   `Hyphen` and `Dash` are `-`; `Slant` and `Fraction bar` are `/`; `Space` is a space.
//!
//! Two layouts are read:
//! * Code words separated by single spaces or tabs, with a wider gap between words: two or
//!   more spaces, a line break, or a `/`, `|` or `(space)` on its own. CyberChef's
//!   `Convert to NATO alphabet` writes `Hotel Echo Lima Lima Oscar  Whiskey Oscar Romeo
//!   Lima Delta `, other translators `Hotel India / Two Five` and
//!   `Hotel Echo Lima Lima Oscar (space) Whiskey Oscar Romeo Lima Delta`.
//! * The code words of each word joined with `-`, `/` or `|`, and whitespace between words:
//!   `Hotel-Echo-Lima-Lima-Oscar Whiskey-Oscar-Romeo-Lima-Delta`.
//!
//! When every word would be one character long and there is no `/` or `(space)` gap, the
//! gaps were between letters: `Hotel  Echo  Lima  Lima  Oscar` is `hello`.
//!
//! The decoded text is lower case. Any other token, or any other character, means the text
//! isn't NATO, so ordinary English is rejected at its first word.

use crate::checkers::CheckerTypes;
use crate::decoders::interface::check_string_success;

