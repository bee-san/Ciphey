/// The NATO phonetic alphabet decoder, call:
/// `let nato_decoder = Decoder::<NatoPhoneticDecoder>::new()` to create a new instance
/// And then call:
/// `result = nato_decoder.crack(input)` to decode text spelled with the NATO alphabet
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::nato_phonetic_decoder::NatoPhoneticDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_nato = Decoder::<NatoPhoneticDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // CyberChef's `Convert to NATO alphabet`: two spaces between words
/// let result = decode_nato
///     .crack("Hotel Echo Lima Lima Oscar  Whiskey Oscar Romeo Lima Delta", &checker)
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "hello world");
///
/// // The code words of each word joined with hyphens
/// let result = decode_nato
///     .crack("Hotel-Echo-Lima-Lima-Oscar Whiskey-Oscar-Romeo-Lima-Delta", &checker)
///     .unencrypted_text;
/// assert_eq!(result.unwrap()[0], "hello world");
/// ```
pub struct NatoPhoneticDecoder;

/// The longest code words, `terrathree` and `setteseven`. A longer run of letters isn't a
/// code word, so the scan stops there.
const MAX_CODE_WORD_LEN: usize = 10;

/// Decoded texts shorter than this are dropped by the search anyway, and two code words
/// are as likely to be two ordinary words (`Golf Hotel`, `Romeo Juliet`).
const MIN_DECODED_LEN: usize = 3;

// Markers between the characters decoded from two tokens, replaced once the whole text has
// been read. No code word decodes to one of these bytes.
/// A single space or tab
const LETTER_GAP: u8 = 1;
/// Any other run of whitespace: two or more spaces or tabs, or a line break
const WIDE_GAP: u8 = 2;
/// A `/`, `|` or `(space)` on its own, which only ever separates words
const WORD_GAP: u8 = 3;

impl Crack for Decoder<NatoPhoneticDecoder> {
    fn new() -> Decoder<NatoPhoneticDecoder> {
        Decoder {
            name: "NATO Phonetic Alphabet",
            description: "Text spelled out with the NATO/ICAO radiotelephony alphabet (Alfa Bravo Charlie …), one code word per letter or digit; decodes to the first letter of each word.",
            link: "https://en.wikipedia.org/wiki/NATO_phonetic_alphabet",
            tags: vec!["nato", "phonetic", "spelling_alphabet", "decoder"],
            popularity: 0.4,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` as NATO phonetic alphabet code words and checks the result with
    /// `checker`. `unencrypted_text` is `None` when `text` isn't NATO text.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying NATO Phonetic Alphabet with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(decoded_text) = decode_nato(text) else {
            debug!("Failed to decode NATO Phonetic Alphabet because the text isn't code words");
            return results;
        };
        trace!(
            "Decoded text for NATO Phonetic Alphabet: {:?}",
            decoded_text
        );

        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode NATO Phonetic Alphabet because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Decodes NATO phonetic alphabet code words to lower-case text, or returns `None` if
/// `text` isn't NATO text.
fn decode_nato(text: &str) -> Option<String> {
    let mut tokens = Tokens {
        rest: text.as_bytes(),
    }
    .peekable();
    // The decoded characters, with a gap marker between the characters of two tokens
    let mut decoded: Vec<u8> = Vec::new();
    // Whether the code words of a word are joined with `-`, `/` or `|`
    let mut joined = false;
    // The widest gap since the last code word
    let mut gap = 0;

    while let Some(token) = tokens.next() {
        let token = token.ok()?;
        gap = gap.max(if token.narrow_gap_before {
            LETTER_GAP
        } else {
            WIDE_GAP
        });
        if token.kind == TokenKind::WordGap {
            gap = WORD_GAP;
            continue;
        }
        if !decoded.is_empty() {
            decoded.push(gap);
        }
        gap = 0;

        if token.kind == TokenKind::Letters {
            let next = tokens
                .peek()
                .and_then(|next| next.as_ref().ok())
                .filter(|next| next.kind == TokenKind::Letters)
                .map(|next| next.text);
            let (character, used_next) = decode_code_word(token.text, next)?;
            decoded.push(character);
            if used_next {
                tokens.next();
            }
        } else if token.text.eq_ignore_ascii_case(b"x-ray") {
            // One code word, not two joined ones, so it doesn't make the text a joined one
            decoded.push(b'x');
        } else {
            joined = true;
            decode_joined(token.text, &mut decoded)?;
        }
    }

    // A joined text has whitespace only between words. Otherwise a single space or tab
    // separates two letters of a word.
    let is_word_gap = |byte: u8| match byte {
        WIDE_GAP | WORD_GAP => true,
        LETTER_GAP => joined,
        _ => false,
    };
    // Every word one character long: the wide gaps were between letters. Not with a `/`
    // or `(space)`, which always separates words.
    let gaps_are_letter_gaps = !decoded.contains(&WORD_GAP)
        && decoded.split(|&byte| is_word_gap(byte)).all(|word| {
            word.iter()
                .filter(|&&byte| byte != LETTER_GAP)
                .take(2)
                .count()
                == 1
        });

    let mut plaintext = String::with_capacity(decoded.len());
    for &byte in &decoded {
        if is_word_gap(byte) {
            if !gaps_are_letter_gaps {
                plaintext.push(' ');
            }
        } else if byte != LETTER_GAP {
            plaintext.push(char::from(byte));
        }
    }
    // `Space` code words at either end
    let plaintext = plaintext.trim_matches(' ');
    (plaintext.len() >= MIN_DECODED_LEN).then(|| plaintext.to_string())
}

/// Decodes code words joined with `-`, `/` or `|`, such as `Hotel-Echo`, onto `decoded`.
/// Returns `None` if a piece isn't a code word, including the empty pieces of `--`.
fn decode_joined(token: &[u8], decoded: &mut Vec<u8>) -> Option<()> {
    let mut pieces = token.split(|&byte| is_separator(byte));
    let mut piece = pieces.next();
    while let Some(word) = piece {
        let next = pieces.next();
        let (character, used_next) = decode_code_word(word, next)?;
        decoded.push(character);
        piece = if used_next { pieces.next() } else { next };
    }
    Some(())
}

/// Decodes one code word of ASCII letters. `next` is the code word after it at the same
/// level: the next piece of a joined token, or the next token of letters. When `word` and
/// `next` are the two halves of `X ray`, `Full stop` or `Fraction bar`, the second value
/// returned is `true`.
fn decode_code_word(word: &[u8], next: Option<&[u8]>) -> Option<(u8, bool)> {
    let mut buffer = [0; MAX_CODE_WORD_LEN];
    let lower = buffer.get_mut(..word.len())?;
    for (lower, byte) in lower.iter_mut().zip(word) {
        *lower = byte.to_ascii_lowercase();
    }
    if let Some(character) = code_word(lower) {
        return Some((character, false));
    }
    let (second_half, character): (&[u8], u8) = match &*lower {
        b"x" => (b"ray", b'x'),
        b"full" => (b"stop", b'.'),
        b"fraction" => (b"bar", b'/'),
        _ => return None,
    };
    next.filter(|next| next.eq_ignore_ascii_case(second_half))
        .map(|_| (character, true))
}

/// The character a lower-case code word stands for.
/// Sources: <https://en.wikipedia.org/wiki/NATO_phonetic_alphabet> (the ICAO letters and
/// digits, the ITU/IMO digit compounds, the spoken digit forms and the CCEB punctuation),
/// CyberChef's `Convert to NATO alphabet` and <https://www.dcode.fr/nato-phonetic-alphabet>.
fn code_word(word: &[u8]) -> Option<u8> {
    let character = match word {
        b"alfa" | b"alpha" => b'a',
        b"bravo" => b'b',
        b"charlie" => b'c',
        b"delta" => b'd',
        b"echo" => b'e',
        b"foxtrot" => b'f',
        b"golf" => b'g',
        b"hotel" => b'h',
        b"india" => b'i',
        b"juliett" | b"juliet" => b'j',
        b"kilo" => b'k',
        b"lima" => b'l',
        b"mike" => b'm',
        b"november" => b'n',
        b"oscar" => b'o',
        b"papa" => b'p',
        b"quebec" => b'q',
        b"romeo" => b'r',
        b"sierra" => b's',
        b"tango" => b't',
        b"uniform" => b'u',
        b"victor" => b'v',
        b"whiskey" | b"whisky" => b'w',
        // `X-ray` and `X ray` are read as two halves, see `decode_code_word`
        b"xray" => b'x',
        b"yankee" => b'y',
        b"zulu" => b'z',
        // The ICAO word, the ITU/IMO compound and the way it's said
        b"zero" | b"nadazero" => b'0',
        b"one" | b"unaone" | b"wun" => b'1',
        b"two" | b"bissotwo" | b"too" => b'2',
        b"three" | b"terrathree" | b"tree" => b'3',
        b"four" | b"kartefour" | b"fower" => b'4',
        b"five" | b"pantafive" | b"fife" => b'5',
        b"six" | b"soxisix" => b'6',
        b"seven" | b"setteseven" => b'7',
        b"eight" | b"oktoeight" | b"ait" => b'8',
        b"nine" | b"novenine" | b"niner" => b'9',
        b"comma" => b',',
        // `Full stop` is read as two halves, see `decode_code_word`
        b"stop" | b"decimal" | b"point" => b'.',
        b"hyphen" | b"dash" => b'-',
        // `Fraction bar` is read as two halves, see `decode_code_word`
        b"slant" => b'/',
        b"space" => b' ',
        _ => return None,
    };
    Some(character)
}

/// Whether `byte` joins the code words of a word, as in `Hotel-Echo`
fn is_separator(byte: u8) -> bool {
    matches!(byte, b'-' | b'/' | b'|')
}

/// What a token is made of
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum TokenKind {
    /// Only letters: one code word, or one half of `X ray`, `Full stop` or `Fraction bar`
    Letters,
    /// Letters joined with `-`, `/` or `|`, like `Hotel-Echo`. Also `-` on its own, which
    /// has only empty pieces and so fails to decode.
    Joined,
    /// A `/`, `|` or `(space)` on its own: the gap between two words
    WordGap,
}

/// A run of bytes between two runs of whitespace
#[derive(Debug)]
struct Token<'a> {
    /// The bytes of the token
    text: &'a [u8],
    /// What the token is made of
    kind: TokenKind,
    /// Whether the whitespace before the token is a single space or tab
    narrow_gap_before: bool,
}

/// The text can't be NATO text: it has a byte no code word or separator has, or a run of
/// letters longer than any code word
#[derive(Debug)]
struct NotNato;

/// Splits text into tokens. It stops with `Err(NotNato)` as soon as it reaches a byte that
/// can't be in NATO text, or a run of letters too long to be a code word, so most text
/// is rejected within its first few bytes.
struct Tokens<'a> {
    /// The text after the last token
    rest: &'a [u8],
}

impl<'a> Iterator for Tokens<'a> {
    type Item = Result<Token<'a>, NotNato>;

    fn next(&mut self) -> Option<Self::Item> {
        let gap_len = self
            .rest
            .iter()
            .take_while(|byte| byte.is_ascii_whitespace())
            .count();
        let (gap, rest) = self.rest.split_at(gap_len);
        if rest.is_empty() {
            self.rest = rest;
            return None;
        }
        let narrow_gap_before = matches!(gap, b" " | b"\t");

        match scan_token(rest) {
            Ok((len, kind)) => {
                let (text, rest) = rest.split_at(len);
                self.rest = rest;
                Some(Ok(Token {
                    text,
                    kind,
                    narrow_gap_before,
                }))
            }
            Err(not_nato) => {
                self.rest = &[];
                Some(Err(not_nato))
            }
        }
    }
}

/// Measures the token at the start of `text` and works out its kind. Fails at the first
/// byte that can't be in NATO text, and at the first run of letters too long to be a
/// code word.
fn scan_token(text: &[u8]) -> Result<(usize, TokenKind), NotNato> {
    const SPACE_WORD: &[u8] = b"(space)";
    if text
        .get(..SPACE_WORD.len())
        .is_some_and(|start| start.eq_ignore_ascii_case(SPACE_WORD))
        && text
            .get(SPACE_WORD.len())
            .is_none_or(|byte| byte.is_ascii_whitespace())
    {
        return Ok((SPACE_WORD.len(), TokenKind::WordGap));
    }

    let mut len = 0;
    // Letters since the last separator
    let mut run = 0;
    let mut has_letters = false;
    let mut has_hyphen = false;
    let mut has_separator = false;
    for &byte in text {
        if byte.is_ascii_alphabetic() {
            run += 1;
            if run > MAX_CODE_WORD_LEN {
                return Err(NotNato);
            }
            has_letters = true;
        } else if is_separator(byte) {
            run = 0;
            has_separator = true;
            has_hyphen |= byte == b'-';
        } else if byte.is_ascii_whitespace() {
            break;
        } else {
            return Err(NotNato);
        }
        len += 1;
    }

    let kind = if !has_separator {
        TokenKind::Letters
    } else if !has_letters && !has_hyphen {
        TokenKind::WordGap
    } else {
        TokenKind::Joined
    };
    Ok((len, kind))
}

