/// The Base64 Alt decoder, call:
/// `let base64_alt_decoder = Decoder::<Base64AltDecoder>::new()` to create a new instance
/// And then call:
/// `result = base64_alt_decoder.crack(input)` to decode Base64 with a non-standard alphabet
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::base64_alt_decoder::Base64AltDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_base64_alt = Decoder::<Base64AltDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // The crypt(3) / itoa64 alphabet: ./0-9A-Za-z
/// let result = decode_base64_alt.crack(
///     "J4VZ653pOKBf647mPrRi64NjS0/eRKpkQm/jRaJm65FcNG/gMLdt64FjNk==",
///     &checker,
/// );
/// assert!(result.success);
/// assert_eq!(
///     result.unencrypted_text.unwrap()[0],
///     "The quick brown fox jumps over the lazy dog"
/// );
/// assert_eq!(result.key.as_deref(), Some("itoa64 / crypt(3)"));
/// ```
pub struct Base64AltDecoder;

/// Shorter text decodes to printable junk with too many alphabets. 12 symbols are 9 bytes.
const MIN_LEN: usize = 12;

/// How many candidates go to the checker, and to the search when none is identified.
const MAX_CANDIDATES: usize = 3;

impl Crack for Decoder<Base64AltDecoder> {
    fn new() -> Decoder<Base64AltDecoder> {
        Decoder {
            name: "Base64 Alt",
            description: "Base64 with a non-standard alphabet: crypt/itoa64, bcrypt, y64, z64, Radix-64, XML, filename-safe, ROT13 and CyberChef's Atom128, Megan35, Zong22 and Hazz15; the alphabet is reported as the key.",
            link: "https://en.wikipedia.org/wiki/Base64#Variants_summary_table",
            tags: vec!["base64", "base64_alt", "decoder", "base"],
            popularity: 0.4,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decodes `text` with every alphabet that fits it and checks the best candidates, at
    /// most three. Returns the first one the checker identifies, or else all of them for
    /// the search to decode further.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Base64 Alt with text {:?}", text);
        let candidates = decode_alt(text);
        if candidates.is_empty() {
            debug!("Base64 Alt found no alphabet that decodes the text to printable ASCII");
            return CrackResult::new(self, text.to_string());
        }
        check_candidates(self, text, candidates, |candidate| checker.check(candidate))
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Runs `check` on each candidate in order and returns the first one it identifies, with
/// its alphabet as the key. If it identifies none, returns every candidate, and as the key
/// their alphabets in the same order.
fn check_candidates(
    decoder: &Decoder<Base64AltDecoder>,
    text: &str,
    candidates: Vec<(&'static str, String)>,
    mut check: impl FnMut(&str) -> CheckResult,
) -> CrackResult {
    let mut results = CrackResult::new(decoder, text.to_string());
    for (alphabet, candidate) in &candidates {
        let checker_result = check(candidate);
        if checker_result.is_identified {
            trace!("Found a match with the {alphabet} Base64 alphabet");
            results.unencrypted_text = Some(vec![candidate.clone()]);
            results.update_checker(&checker_result);
            results.key = Some(alphabet.to_string());
            return results;
        }
    }

    let alphabets: Vec<&str> = candidates.iter().map(|(alphabet, _)| *alphabet).collect();
    results.key = Some(alphabets.join(", "));
    results.unencrypted_text = Some(candidates.into_iter().map(|(_, text)| text).collect());
    results
}

/// A set of ASCII bytes: bit `b` stands for byte `b`.
type ByteSet = u128;

/// The set of `bytes`. Fails to compile for a non-ASCII byte.
const fn byte_set(bytes: &[u8]) -> ByteSet {
    let mut set = 0;
    let mut i = 0;
    while i < bytes.len() {
        set |= 1 << bytes[i];
        i += 1;
    }
    set
}

/// The set of the bytes `first..=last`.
const fn byte_range(first: u8, last: u8) -> ByteSet {
    let mut set = 0;
    let mut byte = first;
    while byte <= last {
        set |= 1 << byte;
        byte += 1;
    }
    set
}

/// `A-Z`
const UPPER: ByteSet = byte_range(b'A', b'Z');
/// `a-z`
const LOWER: ByteSet = byte_range(b'a', b'z');
/// `A-Za-z0-9`
const ALPHANUMERIC: ByteSet = UPPER | LOWER | byte_range(b'0', b'9');
/// Every symbol and padding character of the alphabets below
const SYMBOLS: ByteSet = ALPHANUMERIC | byte_set(b"+/=-_.");
/// Standard Base64, padding included
const STANDARD: ByteSet = ALPHANUMERIC | byte_set(b"+/=");
/// URL-safe Base64, padding included
const URL_SAFE: ByteSet = ALPHANUMERIC | byte_set(b"-_=");

/// A Base64 alphabet this decoder tries.
struct AltAlphabet {
    /// Reported as the key, e.g. `itoa64 / crypt(3)`
    name: &'static str,
    /// The set of the 64 symbols
    symbol_set: ByteSet,
    /// The padding character, or `None` for an alphabet without padding
    padding: Option<u8>,
    /// Decodes text in this alphabet once the padding is removed
    engine: GeneralPurpose,
}

impl AltAlphabet {
    /// Builds the alphabet at compile time, so a malformed table can't compile.
    const fn new(name: &'static str, symbols: &'static str, padding: Option<u8>) -> Self {
        // The crate wants a padding symbol even for an alphabet without padding. `=` is
        // fine for those: it isn't one of their symbols, and the engine never sees padding.
        let engine_padding = match padding {
            Some(padding) => padding,
            None => b'=',
        };
        let Some(engine_padding) = Symbol::new(engine_padding) else {
            panic!("the padding must be printable ASCII");
        };
        let alphabet = match Alphabet::new_with_padding(symbols, engine_padding) {
            Ok(alphabet) => alphabet,
            Err(_) => panic!("not 64 distinct printable symbols, or the padding is one of them"),
        };
        AltAlphabet {
            name,
            symbol_set: byte_set(symbols.as_bytes()),
            padding,
            engine: GeneralPurpose::new(&alphabet, general_purpose::NO_PAD),
        }
    }
}

