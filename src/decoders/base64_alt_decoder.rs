    /// A checker result that identifies the text or doesn't
    fn check_result(is_identified: bool) -> CheckResult {
        let mut result = CheckResult::new(&Checker::<Athena>::new());
        result.is_identified = is_identified;
        result
    }

    #[test]
    fn checks_at_most_three_and_hands_them_all_on() {
        let decoder = Decoder::<Base64AltDecoder>::new();
        let text = "p21Yp21Hp29+";
        let mut checked = Vec::new();
        let result = check_candidates(&decoder, text, decode_alt(text), |candidate| {
            checked.push(candidate.to_string());
            check_result(false)
        });
        assert_eq!(checked.len(), MAX_CANDIDATES);
        assert!(!result.success);
        assert_eq!(result.unencrypted_text, Some(checked));
        assert_eq!(result.key.as_deref(), Some("ROT13, Atom128, z64"));
    }

    #[test]
    fn checking_stops_at_the_first_identified() {
        let decoder = Decoder::<Base64AltDecoder>::new();
        let text = "p21Yp21Hp29+";
        let candidates = decode_alt(text);
        let second = candidates[1].clone();
        let mut calls = 0;
        let result = check_candidates(&decoder, text, candidates, |_| {
            calls += 1;
            check_result(calls == 2)
        });
        assert_eq!(calls, 2);
        assert!(result.success);
        assert_eq!(result.unencrypted_text, Some(vec![second.1]));
        assert_eq!(result.key.as_deref(), Some(second.0));
    }

    /// The symbols of `engine`'s alphabet, in order
    fn symbols(engine: &GeneralPurpose) -> String {
        // The 48 bytes that standard Base64 writes as its own alphabet
        let every_symbol = general_purpose::STANDARD_NO_PAD
            .decode("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/")
            .unwrap();
        engine.encode(every_symbol)
    }

    #[test]
    fn alphabets_are_well_formed() {
        let crypt = GeneralPurpose::new(&base64::alphabet::CRYPT, general_purpose::NO_PAD);
        let bcrypt = GeneralPurpose::new(&base64::alphabet::BCRYPT, general_purpose::NO_PAD);
        assert_eq!(symbols(&alphabet(ITOA64).engine), symbols(&crypt));
        assert_eq!(symbols(&alphabet("bcrypt").engine), symbols(&bcrypt));
        assert_eq!(
            symbols(&alphabet("Atom128").engine),
            "/128GhIoPQROSTeUbADfgHijKLM+n0pFWXY456xyzB7=39VaqrstJklmNuZvwcdE"
        );
        for alphabet in &ALPHABETS {
            // 64 distinct symbols and a padding character that isn't one of them are
            // checked when the table is built
            assert_eq!(alphabet.symbol_set.count_ones(), 64, "{}", alphabet.name);
            assert_eq!(alphabet.symbol_set & !SYMBOLS, 0, "{}", alphabet.name);
            assert_eq!(
                super::byte_set(symbols(&alphabet.engine).as_bytes()),
                alphabet.symbol_set,
                "{}",
                alphabet.name
            );
            if let Some(padding) = alphabet.padding {
                assert_ne!(SYMBOLS & 1 << padding, 0, "{}", alphabet.name);
            }
        }
    }

