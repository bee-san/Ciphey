//! Decode Base64 written with a non-standard alphabet, such as crypt(3)'s itoa64 or
//! CyberChef's Atom128.
//!
//! Everything but the table of 64 symbols is ordinary Base64: 6 bits per symbol, 4
//! symbols to 3 bytes, and 1 or 2 trailing padding symbols or none. The alphabets are
//! CyberChef's `From Base64` presets (`ALPHABET_OPTIONS` in its `src/core/lib/Base64.mjs`),
//! which are the ones CTF players meet:
//!
//! | Key | Symbols 0 to 63 | Padding |
//! |---|---|---|
//! | `Filename safe` | `A-Za-z0-9+-` | `=` |
//! | `itoa64 / crypt(3)` | `./0-9A-Za-z` | `=` |
//! | `bcrypt` | `./A-Za-z0-9` | `=` |
//! | `XML` | `A-Za-z0-9_.` | none |
//! | `y64` | `A-Za-z0-9._` | `-` |
//! | `z64` | `0-9a-zA-Z+/` | `=` |
//! | `Radix-64 (CyberChef)` | `0-9A-Za-z+/` | `=` |
//! | `ROT13` | `N-ZA-Mn-za-m0-9+/` | `=` |
//! | `Atom128`, `Megan35`, `Zong22`, `Hazz15` | shuffled tables that use `=` as a symbol | `C`, `5`, `2`, `5` |
//!
//! Standard and URL-safe Base64 belong to the Base64 decoder. Text it decodes to UTF-8 is
//! rejected here, so the search doesn't get the same candidate twice.
//!
//! Every applicable alphabet is tried. Output that isn't printable ASCII is dropped, the
//! rest is ranked by its share of letters and spaces, and the best three are checked.
//! The alphabet is reported as the key.
//!
//! References: <https://en.wikipedia.org/wiki/Base64#Variants_summary_table>,
//! <https://github.com/gchq/CyberChef/blob/master/src/core/lib/Base64.mjs>.

