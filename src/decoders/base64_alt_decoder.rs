/// The bytes of a text that [`scan`] accepted.
struct Scan {
    /// Every byte of the text
    all: ByteSet,
    /// The bytes before the last two, where padding can't be
    head: ByteSet,
}

/// Collects the bytes of `text` in one pass, or returns `None` at the first byte that no
/// alphabet uses. `text` has at least two bytes.
fn scan(text: &[u8]) -> Option<Scan> {
    let (head, tail) = text.split_at(text.len() - 2);
    let mut head_set = 0;
    for &byte in head {
        head_set |= symbol_bit(byte)?;
    }
    let mut all = head_set;
    for &byte in tail {
        all |= symbol_bit(byte)?;
    }
    Some(Scan {
        all,
        head: head_set,
    })
}

/// The bit for `byte` if some alphabet uses it as a symbol or padding.
fn symbol_bit(byte: u8) -> Option<ByteSet> {
    // `None` for a byte above 127
    let bit = (1 as ByteSet).checked_shl(u32::from(byte))?;
    (SYMBOLS & bit != 0).then_some(bit)
}

/// `text` without its padding, if what is left is written in `alphabet`. More than two
/// padding characters don't fit any alphabet.
fn unpadded<'a>(alphabet: &AltAlphabet, text: &'a [u8], scan: &Scan) -> Option<&'a [u8]> {
    let padding_len = alphabet.padding.map_or(0, |padding| {
        text.iter()
            .rev()
            .take(3)
            .take_while(|&&byte| byte == padding)
            .count()
    });
    if padding_len > 2 {
        return None;
    }
    let body = &text[..text.len() - padding_len];
    // The bytes of `body`: those before the last two, plus whichever of the last two
    // aren't padding
    let body_set = text[text.len() - 2..body.len()]
        .iter()
        .fold(scan.head, |set, &byte| set | 1 << byte);
    (body_set & !alphabet.symbol_set == 0).then_some(body)
}

/// Decodes unpadded `body` and returns it if every byte is printable ASCII, a tab or a
/// line break. Other output is almost never plaintext, and allowing it doubles the junk
/// candidates that random text produces.
fn decode_printable(engine: &GeneralPurpose, body: &[u8]) -> Option<String> {
    // One symbol left over is never valid Base64
    if body.len() % 4 == 1 {
        return None;
    }
    let bytes = engine.decode(body).ok()?;
    if !bytes
        .iter()
        .all(|&byte| matches!(byte, b' '..=b'~' | b'\t' | b'\n' | b'\r'))
    {
        return None;
    }
    String::from_utf8(bytes).ok()
}

/// Whether `text` (already trimmed) is standard or URL-safe Base64 that the Base64 decoder
/// turns into UTF-8, so this decoder must not offer another reading of it. Text ending in
/// `-` is left to this decoder: `-` is y64's padding, and the Base64 decoder reads it as
/// data (`aGVsbG8gd29ybGQ-` is `hello world>` to it and `hello world` in y64).
fn base64_decoder_finds(text: &str, scan: &Scan) -> bool {
    // Anything else would fail to decode
    let fits = scan.all & !STANDARD == 0 || scan.all & !URL_SAFE == 0;
    fits && !text.ends_with('-') && {
        // What `base64_decoder.rs` does: drop every `=`, decode with the standard alphabet
        // if the text contains `+`, `/` or `=` and with the URL-safe one otherwise, and
        // keep the bytes if they are UTF-8
        let unpadded: Vec<u8> = text.bytes().filter(|&byte| byte != b'=').collect();
        let engine = if text.contains(['+', '/', '=']) {
            &general_purpose::STANDARD_NO_PAD
        } else {
            &general_purpose::URL_SAFE_NO_PAD
        };
        engine
            .decode(unpadded)
            .is_ok_and(|bytes| std::str::from_utf8(&bytes).is_ok())
    }
}

/// The share of `text` that is ASCII letters and spaces, which ranks the candidates.
fn letter_share(text: &str) -> f32 {
    let letters = text
        .bytes()
        .filter(|&byte| byte.is_ascii_alphabetic() || byte == b' ')
        .count();
    letters as f32 / text.len().max(1) as f32
}

/// Decodes `text` with every alphabet that fits it, and returns the alphabet name and the
/// text of the best [`MAX_CANDIDATES`] decodings that are printable ASCII, best first.
/// Nothing is checked.
fn decode_alt(text: &str) -> Vec<(&'static str, String)> {
    let text = text.trim();
    if text.len() < MIN_LEN {
        return Vec::new();
    }
    let bytes = text.as_bytes();
    let Some(scan) = scan(bytes) else {
        return Vec::new();
    };
    // Each alphabet has all 52 letters, so real input of 12 or more symbols has both
    // cases: hex, Base32, binary and digits stop here
    if scan.all & LOWER == 0 || scan.all & UPPER == 0 {
        return Vec::new();
    }
    if base64_decoder_finds(text, &scan) {
        trace!("Leaving {:?} to the Base64 decoder", text);
        return Vec::new();
    }

    let mut candidates: Vec<(f32, &'static str, String)> = ALPHABETS
        .iter()
        .filter_map(|alphabet| {
            let body = unpadded(alphabet, bytes, &scan)?;
            let decoded = decode_printable(&alphabet.engine, body)?;
            check_string_success(&decoded, text)
                .then(|| (letter_share(&decoded), alphabet.name, decoded))
        })
        .collect();
    // Stable, so equal scores keep the order of `ALPHABETS`
    candidates.sort_by(|a, b| b.0.total_cmp(&a.0));
    candidates
        .into_iter()
        .take(MAX_CANDIDATES)
        .map(|(_, alphabet, decoded)| (alphabet, decoded))
        .collect()
}

