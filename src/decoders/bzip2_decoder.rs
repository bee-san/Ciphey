/// Decompressed output above this many bytes is rejected rather than truncated: a
/// fragment of the plaintext isn't the plaintext.
const MAX_OUTPUT: usize = 1024 * 1024;

/// Output the checker didn't accept is only handed on for more decoding up to this many
/// bytes. Bzip2 output isn't bounded by the input's size (a few dozen bytes can hold
/// megabytes of one repeated byte), and every decoder runs on every node of the search,
/// so a short input could otherwise make a megabyte node. The Gzip decoder uses the same
/// limit.
const MAX_CANDIDATE: usize = 16 * 1024;

/// Anything shorter can't be a complete stream. The shortest, `bz2.compress(b"")`, is the
/// 4-byte header, the 6-byte end-of-stream magic and the 4-byte stream CRC.
const MIN_STREAM_LEN: usize = 14;

/// The first three bytes of every bzip2 stream. The block-size digit follows.
const MAGIC: [u8; 3] = *b"BZh";

/// The magic at the start of every block, `1AY&SY`: the first twelve digits of π in BCD.
const BLOCK_MAGIC: [u8; 6] = [0x31, 0x41, 0x59, 0x26, 0x53, 0x59];

/// The magic bytes as hex digits.
const MAGIC_HEX_DIGITS: [u8; 6] = [0x4, 0x2, 0x5, 0xa, 0x6, 0x8];

/// The magic bytes as Base64. Three bytes fill exactly four Base64 characters.
const MAGIC_BASE64: &str = "Qlpo";

/// The possible fifth Base64 characters, the top six bits of the block-size digit: `M`
/// for `1` to `3`, `N` for `4` to `7` and `O` for `8` and `9`.
const BLOCK_SIZE_BASE64: [u8; 3] = *b"MNO";

/// ID1, ID2 and CM of a gzip member, which the Gzip decoder reads from raw bytes.
const GZIP_MAGIC: [u8; 3] = [0x1f, 0x8b, 0x08];

/// The magic of an xz stream.
const XZ_MAGIC: [u8; 6] = [0xfd, 0x37, 0x7a, 0x58, 0x5a, 0x00];

/// The Bzip2 decoder, call:
/// `let bzip2_decoder = Decoder::<Bzip2Decoder>::new()` to create a new instance
/// And then call:
/// `result = bzip2_decoder.crack(input)` to decompress bzip2 given as Base64, hex or raw bytes
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::bzip2_decoder::Bzip2Decoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_bzip2 = Decoder::<Bzip2Decoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // Python: base64.b64encode(bz2.compress(b"The quick brown fox jumps over the lazy dog"))
/// let result = decode_bzip2
///     .crack(
///         "QlpoOTFBWSZTWUWd7mEAAAQTgEAABAA////wIAAxRoaAAAAx6ammTIYRtG1HYmIISe16oVNlZbEl4+JgsfiYOd1MCW+c6F3JFOFCQRZ3uYQ=",
///         &checker,
///     )
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "The quick brown fox jumps over the lazy dog");
/// ```
pub struct Bzip2Decoder;

impl Crack for Decoder<Bzip2Decoder> {
    fn new() -> Decoder<Bzip2Decoder> {
        Decoder {
            name: "Bzip2",
            description: "Bzip2 compresses data with the Burrows–Wheeler transform and Huffman coding. Every stream starts with BZh and a block-size digit, which is Qlpo in Base64. Ciphey reads the compressed bytes from Base64, hex or raw text and decompresses them, including files with several streams.",
            link: "https://en.wikipedia.org/wiki/Bzip2",
            tags: vec!["bzip2", "compression", "decoder"],
            // Less common in CTFs than gzip and zlib (0.5)
            popularity: 0.4,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decompresses `text` if it is bzip2 as Base64, hex or raw bytes, and checks the
    /// decompressed text. Fails (with `unencrypted_text` set to `None`) if `text` isn't
    /// bzip2, doesn't decompress, decompresses to something that is neither text nor
    /// compressed data, or decompresses to more than [`MAX_CANDIDATE`] bytes that the
    /// checker doesn't accept.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Bzip2 with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(compressed) = bzip2_bytes(text) else {
            debug!("Bzip2 failed: input is not bzip2 as Base64, hex or raw bytes");
            return results;
        };
        let Some(decompressed) = bunzip_bounded(&compressed) else {
            debug!("Bzip2 failed: the data did not decompress");
            return results;
        };

        let decoded_text = match as_plaintext(decompressed) {
            Ok(decoded_text) => decoded_text,
            Err(binary) => {
                // Compressed again (bzip2 inside bzip2, or gzip, zlib or xz inside it):
                // hand it back as raw bytes for another step. It is binary, so there is
                // nothing for the checker to look at.
                if !is_compressed(&binary) {
                    info!("Failed to decode Bzip2: the output is binary, not text");
                } else if binary.len() > MAX_CANDIDATE {
                    debug!("Bzip2 output is compressed again, but too long to decode further");
                } else {
                    debug!("Bzip2 output is compressed again; returning it unchecked");
                    results.unencrypted_text = Some(vec![latin1_to_string(&binary)]);
                }
                return results;
            }
        };
        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Bzip2 because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        if !checker_result.is_identified && decoded_text.len() > MAX_CANDIDATE {
            debug!(
                "Bzip2 output is not plaintext and too long ({} bytes) to decode further",
                decoded_text.len()
            );
            return results;
        }
        results.unencrypted_text = Some(vec![decoded_text]);
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// Finds bzip2 bytes in `text`: Base64, hex, or raw bytes as Latin-1 characters.
/// Only the first few characters are looked at unless they spell the bzip2 magic.
fn bzip2_bytes(text: &str) -> Option<Vec<u8>> {
    let bytes = base64_view(text)
        .or_else(|| hex_view(text))
        .or_else(|| raw_view(text))?;
    has_stream_header(&bytes).then_some(bytes)
}

/// Base64, standard or URL-safe, that starts with `QlpoM`, `QlpoN` or `QlpoO`.
/// Whitespace (line breaks) is ignored and padding is optional.
fn base64_view(text: &str) -> Option<Vec<u8>> {
    let text = text.trim();
    let starts_like_bzip2 = text.starts_with(MAGIC_BASE64)
        && text
            .as_bytes()
            .get(MAGIC_BASE64.len())
            .is_some_and(|c| BLOCK_SIZE_BASE64.contains(c));
    if !starts_like_bzip2 {
        return None;
    }
    let body: String = text.chars().filter(|c| !c.is_whitespace()).collect();
    let unpadded = body.trim_end_matches('=');
    if body.len() - unpadded.len() > 2 {
        return None;
    }
    // The Base64 decoder's engines. Both reject '=' inside the text.
    general_purpose::STANDARD_NO_PAD
        .decode(unpadded)
        .or_else(|_| general_purpose::URL_SAFE_NO_PAD.decode(unpadded))
        .ok()
}

/// Hex that starts with `425a68`, in any case. Bytes can be separated by whitespace,
/// `:`, `,`, `;`, `-` or `%`, and each can have a `0x` or `\x` prefix.
fn hex_view(text: &str) -> Option<Vec<u8>> {
    let text = text.trim();
    // Cheap gate: the first six digits have to be the magic, otherwise stop here.
    let mut digits = HexDigits::new(text.as_bytes());
    for expected in MAGIC_HEX_DIGITS {
        if digits.next() != Some(Some(expected)) {
            return None;
        }
    }

    let mut bytes = Vec::with_capacity(text.len() / 2);
    let mut digits = HexDigits::new(text.as_bytes());
    while let Some(high) = digits.next() {
        // A character that isn't hex or a separator, or an odd number of digits
        let (high, low) = (high?, digits.next()??);
        bytes.push((high << 4) | low);
    }
    Some(bytes)
}

/// Bzip2 bytes as Latin-1 text, one character per byte. The Hexadecimal and Binary
/// decoders turn bytes that aren't UTF-8 (bzip2 streams practically never are) into this,
/// and so does this decoder for compressed data inside bzip2. Not trimmed: the stream can
/// end with bytes that look like whitespace.
fn raw_view(text: &str) -> Option<Vec<u8>> {
    if !text.as_bytes().starts_with(&MAGIC) {
        return None;
    }
    text.chars().map(|c| u8::try_from(c).ok()).collect()
}

/// Iterates over the hex digits of a hex string, skipping the separators and prefixes
/// [`hex_view`] allows. Yields `Some(digit)` for each digit, and `None` for a character
/// that doesn't belong in hex. Separators and prefixes are only allowed between bytes.
struct HexDigits<'a> {
    /// The text being read.
    bytes: &'a [u8],
    /// Index of the next unread byte.
    position: usize,
    /// Whether the last digit read was the first half of a byte.
    mid_byte: bool,
}

impl<'a> HexDigits<'a> {
    /// Starts reading at the beginning of `bytes`.
    fn new(bytes: &'a [u8]) -> Self {
        HexDigits {
            bytes,
            position: 0,
            mid_byte: false,
        }
    }
}

impl Iterator for HexDigits<'_> {
    type Item = Option<u8>;

    fn next(&mut self) -> Option<Self::Item> {
        loop {
            let byte = *self.bytes.get(self.position)?;
            let next = self.bytes.get(self.position + 1).copied();
            if let Some(digit) = char::from(byte).to_digit(16) {
                if !self.mid_byte && byte == b'0' && matches!(next, Some(b'x' | b'X')) {
                    // A 0x prefix
                    self.position += 2;
                    continue;
                }
                self.position += 1;
                self.mid_byte = !self.mid_byte;
                return Some(Some(digit as u8));
            }
            let is_prefix = byte == b'\\' && matches!(next, Some(b'x' | b'X'));
            let is_separator = byte.is_ascii_whitespace() || b":,;-%".contains(&byte);
            if self.mid_byte || !(is_prefix || is_separator) {
                // Stop for good after the first bad character
                self.position = self.bytes.len();
                return Some(None);
            }
            self.position += if is_prefix { 2 } else { 1 };
        }
    }
}

/// Whether `bytes` start like a bzip2 stream with data in it: `BZh`, a block-size digit
/// from `1` to `9` and the magic of the first block. An empty stream (`bz2.compress(b"")`)
/// has no block, so it is rejected here: it could only decompress to nothing.
fn has_stream_header(bytes: &[u8]) -> bool {
    bytes.len() >= MIN_STREAM_LEN
        && bytes.starts_with(&MAGIC)
        && (b'1'..=b'9').contains(&bytes[3])
        && bytes[4..10] == BLOCK_MAGIC
}

/// Decompresses a bzip2 file of one or more streams, as `bzip2 -d` does.
///
/// Every stream has to decompress and pass its block and stream CRCs, and the next one
/// has to start right after it. Unlike `bzip2 -d`, which warns about "trailing garbage"
/// and ignores it, bytes after the last stream are an error. Returns `None` if the data
/// isn't bzip2, is corrupt or truncated, has anything after its last stream, or
/// decompresses to more than [`MAX_OUTPUT`] bytes. In that case decompression stops at
/// the limit, so a bzip2 bomb costs about as much as decompressing [`MAX_OUTPUT`] bytes.
fn bunzip_bounded(compressed: &[u8]) -> Option<Vec<u8>> {
    if !has_stream_header(compressed) {
        return None;
    }

    // Room for typical text in one go; it grows when it fills up.
    let mut output = Vec::with_capacity((compressed.len() * 4).clamp(64, MAX_OUTPUT + 1));
    let mut rest = compressed;
    while !rest.is_empty() {
        // Like bzip2 -d, anything starting with the magic is another stream and has to
        // decompress. Unlike the first stream it may be empty.
        if !rest.starts_with(&MAGIC) {
            debug!("Bzip2: {} bytes after the last stream", rest.len());
            return None;
        }
        let stream_len = bunzip_stream(rest, &mut output)?;
        rest = &rest[stream_len..];
    }
    Some(output)
}

/// Decompresses the bzip2 stream at the start of `input`, appending to `output`, and
/// returns the stream's length in bytes. Returns `None` if the stream is corrupt or
/// truncated, or if `output` would grow past [`MAX_OUTPUT`] bytes.
fn bunzip_stream(input: &[u8], output: &mut Vec<u8>) -> Option<usize> {
    // The fast mode. The `small` one is about half as fast and still needs over 2 MB for
    // a level 9 block.
    let mut stream = Decompress::new(false);
    loop {
        // Never more than input.len(), which is a usize
        let read = stream.total_in() as usize;
        let written = output.len();
        let status = match stream.decompress_vec(&input[read..], output) {
            Ok(status) => status,
            Err(error) => {
                // A bad CRC, a corrupt block or a bad magic
                debug!("Bzip2 stream failed to decompress: {}", error);
                return None;
            }
        };
        if output.len() > MAX_OUTPUT {
            debug!("Bzip2 output is over {} bytes, giving up", MAX_OUTPUT);
            return None;
        }
        match status {
            Status::StreamEnd => return Some(stream.total_in() as usize),
            // The output is full. Make room, up to one byte over the limit, which tells an
            // output of exactly MAX_OUTPUT bytes apart from a longer one.
            Status::Ok if output.len() == output.capacity() => {
                let capacity = (output.capacity() * 2).min(MAX_OUTPUT + 1);
                output.reserve_exact(capacity - output.len());
            }
            // No progress with room left for output: the input ends inside the stream.
            Status::Ok if stream.total_in() as usize == read && output.len() == written => {
                debug!("Bzip2 stream is truncated");
                return None;
            }
            Status::Ok => {}
            // MemNeeded means libbzip2 couldn't allocate its buffers. The other statuses
            // are only returned when compressing.
            status => {
                debug!("Bzip2 stream stopped with {:?}", status);
                return None;
            }
        }
    }
}

/// Whether binary output is itself compressed, in a form one of the decoders reads from
/// raw bytes: another bzip2 stream, a gzip member, a zlib stream with a `78` header (as
/// the Zlib decoder's raw view expects) or an xz stream.
fn is_compressed(bytes: &[u8]) -> bool {
    has_stream_header(bytes)
        || bytes.starts_with(&GZIP_MAGIC)
        || bytes.starts_with(&XZ_MAGIC)
        || has_zlib_header(bytes)
}

/// Whether `bytes` start with a zlib header (RFC 1950 section 2.2) that the Zlib decoder
/// reads from raw bytes: `78` (DEFLATE with a 32 KiB window), a FLG byte that makes the
/// two a multiple of 31, and no preset dictionary.
fn has_zlib_header(bytes: &[u8]) -> bool {
    let &[cmf @ 0x78, flg, ..] = bytes else {
        return false;
    };
    u16::from_be_bytes([cmf, flg]) % 31 == 0 && flg & 0x20 == 0
}

/// The decompressed bytes as text, if they are UTF-8 text without control characters
/// other than tab, line feed and carriage return. Otherwise the bytes are handed back.
fn as_plaintext(data: Vec<u8>) -> Result<String, Vec<u8>> {
    let text = String::from_utf8(data).map_err(|error| error.into_bytes())?;
    let is_text = !text
        .chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\n' | '\r'));
    if is_text {
        Ok(text)
    } else {
        Err(text.into_bytes())
    }
}

/// One character per byte, U+0000 to U+00FF. The inverse of [`raw_view`].
fn latin1_to_string(bytes: &[u8]) -> String {
    bytes.iter().map(|&byte| char::from(byte)).collect()
}

