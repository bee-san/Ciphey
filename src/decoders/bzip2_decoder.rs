        let truncated = "QlpoOTFBWSZTWUWd7mEAAAQTgEAABAA////wIAAxRoaAAAAx6ammTIYRtG1HYmIISe16oVNlZbEl4+JgsfiYOd1MCW+c6F3JFOE=";

