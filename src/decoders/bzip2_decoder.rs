//! Decompress bzip2 data.
//!
//! A bzip2 stream is the header `BZh` and a block-size digit from `1` to `9`, then one or
//! more blocks, each starting with the 48-bit magic `31 41 59 26 53 59` (π in BCD) and
//! the block's CRC, then the end-of-stream magic `17 72 45 38 50 90` (√π) and a CRC of
//! the whole stream. The blocks are Burrows–Wheeler transformed and Huffman coded, and
//! are not byte-aligned. A file can be several streams back to back, as `pbzip2` writes
//! them; `bzip2 -d` decompresses them all, and so does this decoder.
//!
//! Ciphey passes text between decoders, and bzip2 is binary, so this decoder reads the
//! bzip2 bytes from three textual forms itself:
//! * Base64 (standard or URL-safe, line breaks allowed), which starts with `QlpoM`,
//!   `QlpoN` or `QlpoO` (`BZh1` to `BZh3`, `BZh4` to `BZh7`, `BZh8` and `BZh9`),
//! * hex (`425a68…`, optionally split into bytes by whitespace, `:`, `,`, `;`, `-` or
//!   `%`, or prefixed with `0x` or `\x`),
//! * the raw bytes as Latin-1 text, which is what the Hexadecimal and Binary decoders
//!   emit for bytes that aren't UTF-8.
//!
//! Each form is recognised from its first few characters, so other text is rejected
//! without decoding or copying it. Decompression stops at [`MAX_OUTPUT`] bytes, so a
//! bzip2 bomb fails quickly instead of eating memory, and output the checker doesn't
//! accept is only passed on for more decoding up to [`MAX_CANDIDATE`] bytes.
//!
//! Call `bzip2_decoder.crack` to use. It returns a [`CrackResult`]; check
//! `result.unencrypted_text.is_some()` to see if it decoded.

