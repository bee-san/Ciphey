    #[test]
    fn stops_a_gzip_bomb_at_the_size_limit() {
        // 64 MiB of "A" compresses to about 300 KB at this level (65 KB at best)
        let bomb = {
            let mut encoder = GzEncoder::new(Vec::new(), Compression::fast());
            let chunk = vec![b'A'; 1024 * 1024];
            for _ in 0..64 {
                encoder.write_all(&chunk).unwrap();
            }
            encoder.finish().unwrap()
        };
        let base64_bomb = general_purpose::STANDARD.encode(&bomb);

        let start = Instant::now();
        assert_eq!(gunzip_bounded(&bomb), None);
        assert_eq!(decode(&base64_bomb), None);
        assert!(
            start.elapsed() < Duration::from_secs(5),
            "took {:?}",
            start.elapsed()
        );
    }

    #[test]
    fn output_size_limit_is_inclusive() {
        let at_limit = gzip(&vec![b'A'; MAX_OUTPUT]);
        assert_eq!(gunzip_bounded(&at_limit).unwrap().data.len(), MAX_OUTPUT);

        let over_limit = gzip(&vec![b'A'; MAX_OUTPUT + 1]);
        assert_eq!(gunzip_bounded(&over_limit), None);

        // The limit is for all members together
        let half = gzip(&vec![b'A'; MAX_OUTPUT / 2 + 1]);
        assert_eq!(gunzip_bounded(&[half.clone(), half].concat()), None);
    }

    #[test]
    fn long_output_is_only_kept_if_the_checker_accepts_it() {
        let crack = |data: &[u8]| {
            let base64 = general_purpose::STANDARD.encode(gzip(data));
            Decoder::<GzipDecoder>::new().crack(&base64, &get_athena_checker())
        };

        // Not plaintext: handed on for more decoding up to the limit, dropped above it
        let result = crack(&vec![b'A'; MAX_CANDIDATE]);
        assert!(!result.success);
        assert_eq!(result.unencrypted_text.unwrap()[0].len(), MAX_CANDIDATE);
        assert!(crack(&vec![b'A'; MAX_CANDIDATE + 1])
            .unencrypted_text
            .is_none());

        // Plaintext is returned whatever its length (up to MAX_OUTPUT)
        let english = format!("{FOX}. ").repeat(MAX_CANDIDATE / FOX.len() + 1);
        assert!(english.len() > MAX_CANDIDATE);
        let result = crack(english.as_bytes());
        assert!(result.success, "Athena should identify the plaintext");
        assert_eq!(result.unencrypted_text.unwrap(), [english]);
    }

    #[test]
    fn long_nested_gzip_is_not_handed_on() {
        // Pseudo-random bytes (xorshift64) don't compress, so the inner gzip stream is
        // longer than the limit
        let mut state = 0x2545_f491_4f6c_dd1d_u64;
        let noise: Vec<u8> = (0..MAX_CANDIDATE)
            .map(|_| {
                state ^= state << 13;
                state ^= state >> 7;
                state ^= state << 17;
                state as u8
            })
            .collect();
        let inner = gzip(&noise);
        assert!(inner.len() > MAX_CANDIDATE);
        let nested = general_purpose::STANDARD.encode(gzip(&inner));
        let result = Decoder::<GzipDecoder>::new().crack(&nested, &get_athena_checker());
        assert!(result.unencrypted_text.is_none());
    }

