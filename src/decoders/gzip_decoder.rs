//! Decompress gzip (RFC 1952) data.
//!
//! Ciphey passes text between decoders, and gzip is binary, so this decoder reads the
//! gzip bytes from three textual forms itself:
//! * Base64 (standard or URL-safe, line breaks allowed), which starts with `H4sI`,
//! * hex (`1f8b08…`, optionally split into bytes by whitespace, `:`, `,`, `;`, `-` or
//!   `%`, or prefixed with `0x` or `\x`),
//! * the raw bytes as Latin-1 text, which is what the Hexadecimal and Binary decoders
//!   emit for bytes that aren't UTF-8.
//!
//! Each form is recognised from its first few characters, so other text is rejected
//! without decoding or copying it. Decompression stops at [`MAX_OUTPUT`] bytes, so a
//! gzip bomb fails quickly instead of eating memory, and output the checker doesn't
//! accept is only passed on for more decoding up to [`MAX_CANDIDATE`] bytes.
//!
//! Call `gzip_decoder.crack` to use. It returns a [`CrackResult`]; check
//! `result.unencrypted_text.is_some()` to see if it decoded.

use std::io::Read;

use crate::checkers::CheckerTypes;
use crate::decoders::interface::check_string_success;
use base64::{engine::general_purpose, Engine as _};
