    #[test]
    fn rejects_text_that_is_not_gzip() {
        // None of these get past the prefix checks
        for text in [
            "",
            "😀",
            "hello world",
            "hello my name is panicky mc panic face!",
            // Base64 and hex that aren't gzip
            "aGVsbG8gd29ybGQ=",
            "68656c6c6f20776f726c64",
            "1f8b08 is the gzip magic number",
            "1f8b0g000000000002ff0bc94855282ccd4cce56482aca2fcf5348cbaf50c8",
            // A separator inside a byte
            "1f8b0 8000000000002ff0bc94855282ccd4cce56482aca2fcf5348cbaf50c8",
            // Python zlib.compress(FOX) (#1021): 78 9c ...
            "eJwLyUhVKCzNTM5WSCrKL89TSMuvUMgqzS0oVsgvSy1SKAFK5yRWVSqk5KcDAFvcD9o=",
            // Too much padding
            "H4sIAAAAAAAC/wvJSFUoLM1MzlZIKsovz1NIy69QyCrNLShWyC9LLVIoAUrnJFZVKqTkpwMAOaNPQSsAAAA===",
        ] {
            assert_eq!(gzip_bytes(text), None, "{text}");
            assert_eq!(decode(text), None, "{text}");
        }

        // These start like gzip but don't decompress
        for text in [
            "H4sI is how gzip starts in Base64",
            "H4sIAAAAAAAC/wvJSFUoLM1MzlZIKsovz1NIy69Q",
            "1f8b0800000000000000000000000000000000000000000000",
        ] {
            assert_eq!(decode(text), None, "{text}");
        }
    }

