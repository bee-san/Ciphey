use log::{debug, info, trace};

/// Decompressed output above this many bytes is rejected rather than truncated: a
/// fragment of the plaintext isn't the plaintext.
const MAX_OUTPUT: usize = 1024 * 1024;

/// Output the checker didn't accept is only handed on for more decoding up to this many
/// bytes. Gzip output isn't bounded by the input's size, and every decoder runs on every
/// node of the search, so a few hundred bytes of gzip could otherwise make a megabyte
/// node. A 64 KiB input already keeps the search running well past its 5 second
/// timeout, and a 1 MiB one keeps it running for minutes.
const MAX_CANDIDATE: usize = 16 * 1024;

/// The smallest possible gzip member: a 10-byte header and an 8-byte trailer.
const MIN_MEMBER_LEN: usize = 18;

/// ID1, ID2 and CM (8 = deflate), the first three bytes of every gzip member.
const MAGIC: [u8; 3] = [0x1f, 0x8b, 0x08];

/// The magic bytes as hex digits.
const MAGIC_HEX_DIGITS: [u8; 6] = [0x1, 0xf, 0x8, 0xb, 0x0, 0x8];

/// The magic bytes as Base64. Three bytes fill exactly four Base64 characters.
const MAGIC_BASE64: &str = "H4sI";

/// The Gzip decoder, call:
/// `let gzip_decoder = Decoder::<GzipDecoder>::new()` to create a new instance
/// And then call:
/// `result = gzip_decoder.crack(input)` to decompress gzip given as Base64 or hex
/// The struct generated by new() comes from interface.rs
/// ```
/// use ciphey::decoders::gzip_decoder::GzipDecoder;
/// use ciphey::decoders::interface::{Crack, Decoder};
/// use ciphey::checkers::{athena::Athena, CheckerTypes, checker_type::{Check, Checker}};
///
/// let decode_gzip = Decoder::<GzipDecoder>::new();
/// let athena_checker = Checker::<Athena>::new();
/// let checker = CheckerTypes::CheckAthena(athena_checker);
///
/// // Python: base64.b64encode(gzip.compress(b"The quick brown fox jumps over the lazy dog", mtime=0))
/// let result = decode_gzip
///     .crack(
///         "H4sIAAAAAAAC/wvJSFUoLM1MzlZIKsovz1NIy69QyCrNLShWyC9LLVIoAUrnJFZVKqTkpwMAOaNPQSsAAAA=",
///         &checker,
///     )
///     .unencrypted_text;
/// assert!(result.is_some());
/// assert_eq!(result.unwrap()[0], "The quick brown fox jumps over the lazy dog");
/// ```
pub struct GzipDecoder;

impl Crack for Decoder<GzipDecoder> {
    fn new() -> Decoder<GzipDecoder> {
        Decoder {
            name: "Gzip",
            description: "Gzip is a file format for data compressed with DEFLATE. Every gzip member starts with the bytes 1F 8B 08, which is H4sI in Base64. This decoder decompresses gzip given as Base64, as hex or as the raw bytes, including files with several members.",
            link: "https://datatracker.ietf.org/doc/html/rfc1952",
            tags: vec!["gzip", "compression", "decoder"],
            popularity: 0.5,
            phantom: std::marker::PhantomData,
        }
    }

    /// Decompresses `text` if it is gzip as Base64, hex or raw bytes, and checks the
    /// decompressed text. Fails (with `unencrypted_text` set to `None`) if `text` isn't
    /// gzip, doesn't decompress, decompresses to something that isn't text, or
    /// decompresses to more than [`MAX_CANDIDATE`] bytes that the checker doesn't accept.
    fn crack(&self, text: &str, checker: &CheckerTypes) -> CrackResult {
        trace!("Trying Gzip with text {:?}", text);
        let mut results = CrackResult::new(self, text.to_string());

        let Some(compressed) = gzip_bytes(text) else {
            debug!("Gzip failed: input is not gzip as Base64, hex or raw bytes");
            return results;
        };
        let Some(gunzipped) = gunzip_bounded(&compressed) else {
            debug!("Gzip failed: the data did not decompress");
            return results;
        };

        // Another gzip stream inside: hand it back as raw bytes for another Gzip step.
        // It is binary, so there is nothing for the checker to look at.
        if gunzipped.data.starts_with(&MAGIC) {
            if gunzipped.data.len() > MAX_CANDIDATE {
                debug!("Gzip output is gzip again, but too long to decode further");
                return results;
            }
            debug!("Gzip output is gzip again; returning it as an unchecked candidate");
            results.unencrypted_text = Some(vec![latin1_to_string(&gunzipped.data)]);
            results.key = gunzipped.filename;
            return results;
        }

        let Some(decoded_text) = as_plaintext(gunzipped.data) else {
            info!("Failed to decode Gzip: the output is binary, not text");
            return results;
        };
        if !check_string_success(&decoded_text, text) {
            info!(
                "Failed to decode Gzip because check_string_success returned false on string {}",
                decoded_text
            );
            return results;
        }

        let checker_result = checker.check(&decoded_text);
        if !checker_result.is_identified && decoded_text.len() > MAX_CANDIDATE {
            debug!(
                "Gzip output is not plaintext and too long ({} bytes) to decode further",
                decoded_text.len()
            );
            return results;
        }
        results.unencrypted_text = Some(vec![decoded_text]);
        // gzip has no key, but the header can carry the original file name (FNAME)
        results.key = gunzipped.filename;
        results.update_checker(&checker_result);

        results
    }

    /// Gets all tags for this decoder
    fn get_tags(&self) -> &Vec<&str> {
        &self.tags
    }
    /// Gets the name for the current decoder
    fn get_name(&self) -> &str {
        self.name
    }
    /// Gets the popularity for the current decoder
    fn get_popularity(&self) -> f32 {
        self.popularity
    }
    /// Gets the description for the current decoder
    fn get_description(&self) -> &str {
        self.description
    }
    /// Gets the link for the current decoder
    fn get_link(&self) -> &str {
        self.link
    }
}

/// The result of decompressing a gzip file.
#[derive(Debug, PartialEq)]
struct Gunzipped {
    /// The decompressed bytes of every member, in order.
    data: Vec<u8>,
    /// The original file name from the first member's header (FNAME), if it has one
    /// that is printable.
    filename: Option<String>,
}

/// Finds gzip bytes in `text`: Base64, hex, or raw bytes as Latin-1 characters.
/// Only the first few characters are looked at unless they spell the gzip magic.
fn gzip_bytes(text: &str) -> Option<Vec<u8>> {
    let bytes = base64_view(text)
        .or_else(|| hex_view(text))
        .or_else(|| raw_view(text))?;
    (bytes.len() >= MIN_MEMBER_LEN).then_some(bytes)
}

/// Base64, standard or URL-safe, that starts with `H4sI`. Whitespace (line breaks) is
/// ignored and padding is optional.
fn base64_view(text: &str) -> Option<Vec<u8>> {
    let text = text.trim();
    if !text.starts_with(MAGIC_BASE64) {
        return None;
    }
    let body: String = text.chars().filter(|c| !c.is_whitespace()).collect();
    let unpadded = body.trim_end_matches('=');
    if body.len() - unpadded.len() > 2 {
        return None;
    }
    // The Base64 decoder's engines. Both reject '=' inside the text.
    general_purpose::STANDARD_NO_PAD
        .decode(unpadded)
        .or_else(|_| general_purpose::URL_SAFE_NO_PAD.decode(unpadded))
        .ok()
}

/// Hex that starts with `1f8b08`, in any case. Bytes can be separated by whitespace,
/// `:`, `,`, `;`, `-` or `%`, and each can have a `0x` or `\x` prefix.
fn hex_view(text: &str) -> Option<Vec<u8>> {
    let text = text.trim();
    // Cheap gate: the first six digits have to be the magic, otherwise stop here.
    let mut digits = HexDigits::new(text.as_bytes());
    for expected in MAGIC_HEX_DIGITS {
        if digits.next() != Some(Some(expected)) {
            return None;
        }
    }

    let mut bytes = Vec::with_capacity(text.len() / 2);
    let mut digits = HexDigits::new(text.as_bytes());
    while let Some(high) = digits.next() {
        // A character that isn't hex or a separator, or an odd number of digits
        let (high, low) = (high?, digits.next()??);
        bytes.push((high << 4) | low);
    }
    Some(bytes)
}

/// Gzip bytes as Latin-1 text, one character per byte. The Hexadecimal and Binary
/// decoders turn bytes that aren't UTF-8 (gzip never is) into this.
fn raw_view(text: &str) -> Option<Vec<u8>> {
    let mut chars = text.chars();
    if !MAGIC
        .iter()
        .all(|&byte| chars.next() == Some(char::from(byte)))
    {
        return None;
    }
    text.chars().map(|c| u8::try_from(c).ok()).collect()
}

/// Iterates over the hex digits of a hex string, skipping the separators and prefixes
/// [`hex_view`] allows. Yields `Some(digit)` for each digit, and `None` for a character
/// that doesn't belong in hex. Separators and prefixes are only allowed between bytes.
struct HexDigits<'a> {
    /// The text being read.
    bytes: &'a [u8],
    /// Index of the next unread byte.
    position: usize,
    /// Whether the last digit read was the first half of a byte.
    mid_byte: bool,
}

impl<'a> HexDigits<'a> {
    /// Starts reading at the beginning of `bytes`.
    fn new(bytes: &'a [u8]) -> Self {
        HexDigits {
            bytes,
            position: 0,
            mid_byte: false,
        }
    }
}

impl Iterator for HexDigits<'_> {
    type Item = Option<u8>;

    fn next(&mut self) -> Option<Self::Item> {
        loop {
            let byte = *self.bytes.get(self.position)?;
            let next = self.bytes.get(self.position + 1).copied();
            if let Some(digit) = char::from(byte).to_digit(16) {
                if !self.mid_byte && byte == b'0' && matches!(next, Some(b'x' | b'X')) {
                    // A 0x prefix
                    self.position += 2;
                    continue;
                }
                self.position += 1;
                self.mid_byte = !self.mid_byte;
                return Some(Some(digit as u8));
            }
            let is_prefix = byte == b'\\' && matches!(next, Some(b'x' | b'X'));
            let is_separator = byte.is_ascii_whitespace() || b":,;-%".contains(&byte);
            if self.mid_byte || !(is_prefix || is_separator) {
                // Stop for good after the first bad character
                self.position = self.bytes.len();
                return Some(None);
            }
            self.position += if is_prefix { 2 } else { 1 };
        }
    }
}

/// Decompresses a gzip file of one or more members (RFC 1952 section 2.2), the way
/// `gzip -d` does.
///
/// Every member has to decompress, pass its CRC-32 and length check and start right
/// after the previous one. Anything after the last member that isn't another member,
/// such as zero padding, is ignored, also like `gzip -d`. Returns `None` if the data
/// isn't gzip, is corrupt or truncated, or decompresses to more than [`MAX_OUTPUT`]
/// bytes. In that case decompression stops at the limit, so a gzip bomb costs about as
/// much as decompressing [`MAX_OUTPUT`] bytes.
fn gunzip_bounded(compressed: &[u8]) -> Option<Gunzipped> {
    if compressed.len() < MIN_MEMBER_LEN || !compressed.starts_with(&MAGIC) {
        return None;
    }

    let mut data = Vec::new();
    let mut filename = None;
    let mut rest = compressed;
    let mut first_member = true;
    // Like gzip -d, anything starting with the two ID bytes is another member and has to
    // decode. A different CM byte is an error there too.
    while first_member || rest.starts_with(&MAGIC[..2]) {
        let mut member = GzDecoder::new(rest);
        // One byte over the limit tells an output of exactly MAX_OUTPUT bytes apart from
        // a longer one.
        let budget = (MAX_OUTPUT + 1 - data.len()) as u64;
        if let Err(error) = (&mut member).take(budget).read_to_end(&mut data) {
            debug!("Gzip member failed to decompress: {}", error);
            return None;
        }
        if data.len() > MAX_OUTPUT {
            debug!("Gzip output is over {} bytes, giving up", MAX_OUTPUT);
            return None;
        }
        if first_member {
            filename = member
                .header()
                .and_then(|header| header.filename())
                .and_then(printable_filename);
            first_member = false;
        }
        rest = member.into_inner();
    }

    Some(Gunzipped { data, filename })
}

/// The header's file name as text, if it has any characters and none of them are
/// control characters. RFC 1952 says it is Latin-1, but gzip writes whatever bytes the
/// file system uses, which today is UTF-8, so UTF-8 is tried first.
fn printable_filename(name: &[u8]) -> Option<String> {
    let name = match std::str::from_utf8(name) {
        Ok(name) => name.to_string(),
        Err(_) => latin1_to_string(name),
    };
    (!name.is_empty() && !name.chars().any(char::is_control)).then_some(name)
}

/// The decompressed bytes as text, if they are UTF-8 text without control characters
/// other than tab, line feed and carriage return. Binary files are rejected.
fn as_plaintext(data: Vec<u8>) -> Option<String> {
    let text = String::from_utf8(data).ok()?;
    let is_text = !text
        .chars()
        .any(|c| c.is_control() && !matches!(c, '\t' | '\n' | '\r'));
    is_text.then_some(text)
}

/// One character per byte, U+0000 to U+00FF. The inverse of [`raw_view`].
fn latin1_to_string(bytes: &[u8]) -> String {
    bytes.iter().map(|&byte| char::from(byte)).collect()
}

